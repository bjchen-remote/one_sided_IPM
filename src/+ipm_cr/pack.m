function info=pack(s,ctx,folder,meta,history,names)
%PACK Write an accepted native scientific-data package; never saves a context.
% W is centered canonical density, eta is its analytic residual; R=a+W.
% Native overlap copies remain distinct. No display interpolation is applied.
if nargin<4,meta=struct();end
if nargin<5,history=[];names={};end
assert(strcmp(s.ctxId,ctx.id)&&isequaln(s.ctxKey,ctx.key), ...
    'ipm_cr:PackState','Use an accepted state and its own context.');
assert(s.rhs.diagnosticsComplete,'ipm_cr:PackDiagnostics','Complete endpoint fields are required.');
assert(isequaln(ctx.identity.source,ipm_cr.io.identity('source'))&& ...
    isequaln(ctx.identity.authority,ipm_cr.io.identity('authority',ipm_cr.root(),ctx.opts.initial)), ...
    'ipm_cr:PackIdentity','Source or initial datum changed after this state was initialized.');
if ~isfolder(folder),mkdir(folder);end
parent=fullfile(folder,'data');if ~isfolder(parent),mkdir(parent);end
temporary=tempname(parent);mkdir(temporary);
[~,nonce]=fileparts(temporary);target=fullfile(parent,sprintf('step%012d_%s',s.step,nonce));
data=struct('format','ipm_cr_science_v1','createdUtc',ipm_cr.io.identity('utc'), ...
    'step',s.step,'scale',s.scale,'method',ctx.opts,'reference',s.originalAuthority, ...
    'source',ctx.identity.source,'initial',ctx.identity.authority, ...
    'coordinateFrame','canonical upper half-plane; rows y/r, columns x/theta', ...
    'densityDefinition','R=densityOrigin+W; W=eta+analytic background when eta exists; rho_phys=R*exp(-logC_omega)', ...
    'overlapDefinition','Both active interiors retained; duplicate overlap is not a physical quadrature.', ...
    'scaleMap','x_phys=(X-X_shift)*exp(-logC_l); y_phys=Y*exp(-logC_l); rho_phys=exp(-logC_omega)*(densityOrigin+W); u_phys=exp(-logC_omega)*u', ...
    'rates',struct('c_l',s.rhs.c_l,'c_omega',s.rhs.c_omega,'c_r',s.rhs.c_r, ...
        'delta',s.rhs.delta,'Uref',s.rhs.Uref), ...
    'gauge',struct('measurement',s.rhs.measurement,'residual',s.rhs.gaugeResidual), ...
    'poisson',s.rhs.poisson,'meta',meta,'mesh',struct(),'fields',struct());
for patch={'core','polar'}
    key=patch{1};g=ctx.mesh.(key);
    grid=struct('X',g.X,'Y',g.Y,'active',g.active,'ghost',g.ghost);
    if strcmp(key,'core'),grid.x=g.x;grid.y=g.y;
    else,grid.r=g.r;grid.theta=g.theta;end
    data.mesh.(key)=grid;
    v=struct('W',s.W.(key),'q',s.rhs.q.(key),'F',s.rhs.F.(key),'Q',s.rhs.Q.(key), ...
        'u1',s.rhs.physical.(key).u1,'u2',s.rhs.physical.(key).u2, ...
        'u1Centered',s.rhs.physical.(key).u1-s.rhs.Uref);
    if isfield(s,'eta'),v.eta=s.eta.(key);end
    if isfield(s.rhs.physical.(key),'psi'),v.psi=s.rhs.physical.(key).psi;end
    data.fields.(key)=v;
end
save(fullfile(temporary,'fields.mat'),'data','-v7.3');
metadata=rmfield(data,{'mesh','fields'});
metadata.gauge=struct('I',s.rhs.measurement.I,'P',s.rhs.measurement.P, ...
    'C',s.rhs.measurement.C,'peakX',s.rhs.measurement.peak.x, ...
    'residual',s.rhs.gaugeResidual,'fullFunctionalsInMat',true);
metadata.fieldFile='fields.mat';metadata.fieldSHA256=ipm_cr.io.sha(fullfile(temporary,'fields.mat'));
metadata.meshSize=struct('core',size(s.W.core),'polar',size(s.W.polar));
metadata.steadyStateCertified=false;metadata.trajectoryAccuracyCertified=false;
if ~isempty(history)
    assert(size(history,2)==numel(names),'ipm_cr:PackHistory','History schema mismatch.');
    writetable(array2table(history,'VariableNames',names),fullfile(temporary,'history.csv'));
    metadata.historyFile='history.csv';metadata.historySHA256=ipm_cr.io.sha(fullfile(temporary,'history.csv'));
end
ipm_cr.io.json(fullfile(temporary,'metadata.json'),metadata);
[ok,message]=movefile(temporary,target);assert(ok,'ipm_cr:PackCommit','%s',message);
info=struct('format','ipm_cr_science_package_v1','folder',target, ...
    'fieldFile','fields.mat','fieldSHA256',metadata.fieldSHA256, ...
    'metadataFile','metadata.json','metadataSHA256',ipm_cr.io.sha(fullfile(target,'metadata.json')), ...
    'nativeOnly',true,'steadyStateCertified',false);
end
