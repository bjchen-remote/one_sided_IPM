function metrics=overlapVelocityMetrics(a,b,reference,scaleFloor)
%OVERLAPVELOCITYMETRICS Legacy, absolute and local de-translated errors.
% The common physical reference is the same core solution's wall origin.
% New criteria supplement, and never replace, the original acceptance gate.
du1=abs(a.u1-b.u1);du2=abs(a.u2-b.u2);
absolute=max([du1(:);du2(:)]);
legacyScale=max([abs(a.u1(:));abs(a.u2(:));abs(b.u1(:));abs(b.u2(:));1]);
localScale=max([abs(a.u1(:)-reference(1)),abs(a.u2(:)-reference(2)), ...
    abs(b.u1(:)-reference(1)),abs(b.u2(:)-reference(2)), ...
    scaleFloor*ones(numel(a.u1),1)],[],2);
localMismatch=max(du1(:),du2(:));
metrics=struct('absoluteMismatch',absolute,'legacyScale',legacyScale, ...
    'legacyScaledMismatch',absolute/legacyScale, ...
    'centeredLocalScaledMismatch',max(localMismatch./localScale), ...
    'centeredLocalScaleMinimum',min(localScale), ...
    'centeredLocalScaleMaximum',max(localScale),'referenceVelocity',reference, ...
    'scaleFloor',scaleFloor,'referenceDefinition','physical_velocity_of_same_core_solution_at_wall_origin');
end
