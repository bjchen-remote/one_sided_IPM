function integral = integral(wallGradient,ops,settings)
%IPM.EVOLVE.WALLGRADIENTINTEGRAL Integrate R_X on the wall over [-L,L].
%   L=wallIntegralRadius is fixed in rescaled X coordinates. The weights
%   integrate the piecewise-linear wall-gradient interpolant exactly, including
%   partial end cells when -L or L is not a mesh node. Weights are rebuilt
%   after remeshing; the coordinate interval and initial reference are fixed.

if ~isnumeric(wallGradient) || ~isreal(wallGradient) || ...
        ~isvector(wallGradient) || numel(wallGradient) ~= numel(ops.x) || ...
        any(~isfinite(wallGradient),'all')
    error('ipm:WallIntegralGradient', ...
        'The wall integral requires one finite R_X sample per x node.');
end
x = reshape(ops.x,1,[]);
if ~isnumeric(x) || ~isreal(x) || numel(x) < 3 || ...
        any(~isfinite(x)) || any(diff(x) <= 0)
    error('ipm:WallIntegralAxis', ...
        'The wall integral requires a finite, strictly increasing x axis.');
end
if ~isfield(settings,'wallIntegralRadius') || ...
        ~isnumeric(settings.wallIntegralRadius) || ...
        ~isreal(settings.wallIntegralRadius) || ...
        ~isscalar(settings.wallIntegralRadius) || ...
        ~isfinite(settings.wallIntegralRadius) || ...
        settings.wallIntegralRadius <= 0
    error('ipm:WallIntegralRadius', ...
        'wallIntegralRadius must be a positive finite scalar.');
end
radius = settings.wallIntegralRadius;
if x(1) >= -radius || x(end) <= radius
    error('ipm:WallIntegralDomain', ...
        'The fixed wall-integral interval must lie inside the x domain.');
end
interior = x > -radius & x < radius;
if nnz(interior) < 3 || ~any(interior & x < 0) || ...
        ~any(interior & x > 0)
    error('ipm:WallIntegralSupport', ...
        ['The wall-integral interval needs at least three interior nodes ' ...
        'with resolved samples on both sides of the origin.']);
end

left = x(1:end-1);
right = x(2:end);
lower = max(left,-radius);
upper = min(right,radius);
active = upper > lower;
indices = find(active);
cellWidth = right(active)-left(active);
clippedWidth = upper(active)-lower(active);
averageCoordinate = ((lower(active)-left(active)) + ...
    (upper(active)-left(active)))./(2*cellWidth);
weights = zeros(size(x));
weights(indices) = clippedWidth.*(1-averageCoordinate);
weights(indices+1) = weights(indices+1) + ...
    clippedWidth.*averageCoordinate;
support = weights > 0;
supportPoints = nnz(support);
weightTolerance = 256*eps(max(1,2*radius));
if supportPoints < 3 || any(~isfinite(weights)) || ...
        any(weights < 0) || abs(sum(weights)-2*radius) > weightTolerance
    error('ipm:WallIntegralWeights', ...
        'The clipped wall quadrature does not resolve the fixed interval.');
end

wallGradient = reshape(wallGradient,1,[]);
value = sum(weights.*wallGradient);
absoluteValue = sum(weights.*abs(wallGradient));
condition = value/max(absoluteValue,realmin);
if ~isfinite(value) || value <= 2*radius*settings.cOmegaGaugeFloor || ...
        ~isfinite(condition) || condition < settings.pointStrainConditionFloor
    error('ipm:DegenerateWallIntegral', ...
        'The signed wall-gradient integral is nonpositive or poorly conditioned.');
end
integral = struct('weights',weights,'value',value, ...
    'radius',radius,'center',0,'support',support, ...
    'supportPoints',supportPoints,'condition',condition, ...
    'absoluteValue',absoluteValue,'meanValue',value/(2*radius));
end
