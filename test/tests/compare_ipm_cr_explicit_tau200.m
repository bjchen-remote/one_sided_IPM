function report=compare_ipm_cr_explicit_tau200(outputDir,hybridFolder,nativeFolder)
%COMPARE_IPM_CR_EXPLICIT_TAU200 Read-only comparison of two accepted tau200s.
% The historical polar trajectory is a coarse numerical comparator, not an
% exact reference. No Poisson solve, RHS evaluation, remesh or step is run.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(root,'test'),fullfile(root,'time_evolution'));
if nargin<1||isempty(outputDir),outputDir=fullfile(root,'test','results','explicit_tau200_comparison');end
if nargin<2||isempty(hybridFolder),hybridFolder=fullfile(root,'test','results','explicit_tau200_20261021_v1','native');end
if nargin<3||isempty(nativeFolder),nativeFolder=fullfile(root,'runs','ipm_c_tau200_originfix_20261021_07','native');end
outputDir=char(outputDir);hybridFolder=char(hybridFolder);nativeFolder=char(nativeFolder);
assert(startsWith(outputDir,filesep)&&~within(outputDir,hybridFolder)&&~within(outputDir,nativeFolder), ...
    'ipm_cr:CompareOutput','Use a separate absolute comparison output directory.');
assert(~isfile(fullfile(outputDir,'comparison.json')), ...
    'ipm_cr:ComparePreserve','Choose a fresh comparison output directory.');
threads=maxNumCompThreads(1);threadCleanup=onCleanup(@()maxNumCompThreads(threads)); %#ok<NASGU>
timer=tic;
[hc,hp]=load_hybrid(hybridFolder);[nc,np]=ipm_c.output.loadCheckpoint(nativeFolder);
assert(hp.tau==200&&hc.state.scale.canonicalTime==200&&np.tau==200&&nc.state.scale.canonicalTime==200, ...
    'ipm_cr:CompareExactEndpoint','Both durable accepted checkpoints must be at exactly tau200.');
[nf,nativeFrame]=load_native_frame(nativeFolder,nc,np);
hw=hc.wallOps;nw=nc.authority.cart.originalWallOps;
assert(isequaln(hw.x,nw.x)&&isequaln(hw.Dx,nw.Dx), ...
    'ipm_cr:CompareWallAuthority','Both trajectories must preserve the identical original wall x and Dx.');
hr=hc.state.originalAuthority;nr=nc.authority.shared.references;
for name={'I0','P0','C0'}
    assert(isequaln(hr.(name{1}),nr.(name{1})), ...
        'ipm_cr:CompareReferences','The original reference %s differs.',name{1});
end
for name={'wallIntegralRadius','referenceWallIntegral','referenceWallGradientCentroid','peakPositionRestoringRate'}
    assert(isequaln(hw.rescaling.(name{1}),nw.rescaling.(name{1})), ...
        'ipm_cr:CompareReferences','The original fixed gauge setting %s differs.',name{1});
end
assert(strcmp(hc.authority.sha256,nc.authority.authoritySha256)&&hc.state.referencePeak==nr.P0, ...
    'ipm_cr:CompareAuthorityIdentity','The initial datum/peak authority differs.');

% Use one physical origin per cloud and fixed physical queries, independent
% of either evolving node set. The rectangle lies in the active FD core.
[X,Y]=meshgrid(linspace(-1.1,1.1,45),linspace(0,1.1,33));X(:,23)=0;
clouds.core=struct('X',X,'Y',Y,'description','45-by-33 rectangle, |X|<=1.1 and 0<=Y<=1.1');
r=linspace(.05,3,60)';theta=linspace(0,pi,97);si=sin(theta);si([1,end])=0;
X=r*cos(theta);Y=r*si;
clouds.near=struct('X',[0;X(:)],'Y',[0;Y(:)],'radii',r,'theta',theta, ...
    'description','One origin plus 60 positive radii and 97 wall-inclusive angles, r<=3');
hOrigin=ipm_cr.explicit.interpolate(hc.state.rho,hc.geometry,0,0);
nOrigin=nc.state.rho(1,1);
samples=struct();differences=struct();
for region={'core','near'}
    name=region{1};query=clouds.(name);
    [~,hm]=ipm_cr.explicit.interpolate(hc.state.rho,hc.geometry,query.X,query.Y);
    assert(hm.allValid,'ipm_cr:CompareQueries','A common query has no hybrid owner.');
    nm=ipm_cr.carrier.tensorMap(nc.grid.r,nc.grid.theta,hypot(query.X(:),query.Y(:)), ...
        max(0,min(pi,atan2(query.Y(:),query.X(:)))),7);
    hs=hybrid_samples(hc.state,hm,hOrigin);ns=native_samples(nf,nm,size(query.X),nOrigin);
    samples.(name)=struct('hybrid',hs,'native',ns);
    names=fieldnames(hs);row=struct('queryCount',numel(query.X));
    for k=1:numel(names)
        field=names{k};row.(field)=difference(hs.(field),ns.(field),query.X,query.Y);
    end
    differences.(name)=row;
end

% Reuse the unchanged original wall functionals only to expose complete
% wall samples. The saved native diagnostics remain the trajectory record.
method='linear';if isfield(nc.cfg.rhsOptions,'measurementInterpolation'),method=nc.cfg.rhsOptions.measurementInterpolation;end
nm=ipm_c.gauge.measure(nc.state.rho,nc.grid.r,nw,struct('interpolation',method));
hm=hc.state.flow.measurement;
assert(isequaln(hm.x,nm.x)&&all(isfinite(hm.wallValues))&&all(isfinite(nm.wallValues)), ...
    'ipm_cr:CompareWallSamples','Wall samples must use the complete identical original axis.');
wall=struct('x',hm.x,'hybridCenteredDensity',hm.wallValues-hOrigin, ...
    'nativeCenteredDensity',nm.wallValues-nOrigin,'hybridQ',hm.q,'nativeQ',nm.q);
wallComparison=struct('hybridMeasurements',[hm.I,hm.P,hm.C], ...
    'nativeSavedMeasurements',[nf.diagnostics.wallIntegral,nf.diagnostics.wallPeak,nf.diagnostics.wallCentroid], ...
    'nativeRecomputedMeasurements',[nm.I,nm.P,nm.C], ...
    'measurementNames',{{'I','P','C'}},'signedDifference',[hm.I-nm.I,hm.P-nm.P,hm.C-nm.C], ...
    'nativeRecomputedMinusSaved',[nm.I-nf.diagnostics.wallIntegral,nm.P-nf.diagnostics.wallPeak,nm.C-nf.diagnostics.wallCentroid], ...
    'hybridRelativeIntegralDrift',(hm.I-hr.I0)/hr.I0,'nativeRelativeIntegralDrift',(nm.I-nr.I0)/nr.I0, ...
    'hybridRelativePeakDrift',(hm.P-hr.P0)/hr.P0,'nativeRelativePeakDrift',(nm.P-nr.P0)/nr.P0, ...
    'hybridCentroidDisplacement',hm.C-hr.C0,'nativeCentroidDisplacement',nm.C-nr.C0, ...
    'centeredDensityDifference',difference(wall.hybridCenteredDensity,wall.nativeCenteredDensity,hm.x,zeros(size(hm.x))), ...
    'qDifference',difference(hm.q,nm.q,hm.x,zeros(size(hm.x))));

hTiming=timing(hybridFolder,hc,'hybrid');nTiming=timing(nativeFolder,nc,'native');
assert(hTiming.allMissionSegmentsCompleted&&nTiming.allMissionSegmentsCompleted, ...
    'ipm_cr:CompareActiveMission','Wait for both supervisors to finish their final segment before comparing total activity costs.');
rateH=[hc.state.flow.c_l,hc.state.flow.c_omega,hc.state.flow.c_r];rateN=[nf.c_l,nf.c_omega,nf.c_r];
scaleH=hc.state.scale;scaleN=nc.state.scale;
report=struct('kind','accepted_native_hybrid_and_polar_tau200_readonly_comparison_v1', ...
    'status','completed_comparison','tau',200,'hybridCheckpoint',hp,'nativeCheckpoint',np, ...
    'nativeFrame',nativeFrame,'originalReferencesIdentical',true,'originalWallAxesAndDxIdentical',true, ...
    'originalReferences',struct('I0',hr.I0,'P0',hr.P0,'C0',hr.C0, ...
        'wallIntegralRadius',hw.rescaling.wallIntegralRadius,'restoringRate',hw.rescaling.peakPositionRestoringRate), ...
    'cloudDefinitions',struct('core',cloud_summary(clouds.core),'near',cloud_summary(clouds.near)), ...
    'fieldDifferences',differences,'wall',wallComparison, ...
    'backgroundAlignment',struct('hybridInterpolatedCenteredOrigin',hOrigin,'nativeCenteredOrigin',nOrigin, ...
        'definition','Subtract each interpolated W(0,0) only for the centered-density comparison. Scalar origin amplitudes remain separate. No spatial shift, scale or time alignment is applied.'), ...
    'rates',struct('names',{{'c_l','c_omega','c_r'}},'hybrid',rateH,'native',rateN, ...
        'signedDifference',rateH-rateN,'relativeToNative',abs(rateH-rateN)./max(abs(rateN),realmin), ...
        'hybridDelta',hc.state.flow.delta,'nativeDelta',nf.diagnostics.translationRate, ...
        'deltaSignedDifference',hc.state.flow.delta-nf.diagnostics.translationRate, ...
        'hybridUref',hc.state.flow.Uref,'nativeUref',nf.diagnostics.referenceVelocity), ...
    'scalesAndClock',scale_difference(scaleH,scaleN), ...
    'hybridTiming',hTiming,'nativeTiming',nTiming, ...
    'nativeOverHybridMissionActiveSegmentWallRatio',nTiming.missionActiveSegmentWallSeconds/hTiming.missionActiveSegmentWallSeconds, ...
    'nativeOverHybridMatlabSolverInvocationRatio',safe_ratio(nTiming.matlabSolverInvocationSeconds,hTiming.matlabSolverInvocationSeconds), ...
    'nativeOverHybridAcceptedStepCountRatio',nc.state.step/hc.state.step, ...
    'CFL',struct('hybridConfigured',hc.explicitOptions.cfl,'nativeConfigured',nc.cfg.time.cfl, ...
        'hybridMaximumRecordedAllStage',history_max(hc,'maximumStageCfl'), ...
        'nativeAllStageHistoryAvailable',false,'hybridMaxDt',hc.explicitOptions.maxDt,'nativeMaxDt',nc.cfg.time.maxDt), ...
    'hybridFinalPoissonDiagnostics',hc.state.flow.poisson, ...
    'nativeFinalPoissonDiagnostics',nf.diagnostics.poissonSolveInfo, ...
    'hybridFinalOverlapAudit',hc.spatialAudit, ...
    'accuracyCertified',false,'equalAccuracySpeedupClaimed',false,'timeEvolutionAdvancedByComparison',false, ...
    'sourceFiles',source_files(), ...
    'limitations',{{'The original polar tau200 trajectory is a finite-resolution numerical comparator, not an exact solution.', ...
    'The trajectories use different transport meshes, CFL settings, remesh/output policies and Poisson discretizations.', ...
    'Initial spatial refinement or a short half-step test cannot certify accuracy throughout either tau200 trajectory.', ...
    'The reported wall-time ratios describe these actual runs and their costs; they do not establish equal-accuracy speedup.', ...
    'Active segment and MATLAB tic elapsed records are used; UTC sleep gaps and supervisorWallSeconds are not treated as operator time.'}});
report.nativeRemeshCount=nf.remeshCount;report.hybridRemeshCount=0;
report.elapsedComparisonSeconds=toc(timer);
assert_unchanged(hybridFolder,hp);assert_unchanged(nativeFolder,np);
assert(strcmp(ipm_c.output.sha256(nativeFrame.path),nativeFrame.sha256)&& ...
    strcmp(ipm_c.output.sha256(nativeFrame.catalogPath),nativeFrame.catalogSha256)&& ...
    strcmp(ipm_c.output.sha256(hTiming.missionPath),hTiming.missionSha256)&& ...
    strcmp(ipm_c.output.sha256(nTiming.missionPath),nTiming.missionSha256), ...
    'ipm_cr:CompareChangedInput','An input changed during the read-only comparison.');
report.inputPointersAndFilesUnchanged=true;
if ~isfolder(outputDir),mkdir(outputDir);end
temporary=fullfile(outputDir,'comparison.writing.mat');save(temporary,'report','clouds','samples','wall','-v7.3');
[ok,message]=movefile(temporary,fullfile(outputDir,'comparison.mat'),'f');assert(ok,'ipm_cr:CompareSave','%s',message);
write_json(fullfile(outputDir,'comparison.json'),report);
fid=fopen(fullfile(outputDir,'comparison.txt'),'w');assert(fid>=0,'ipm_cr:CompareSave');cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'Both accepted endpoints: tau=200. Hybrid steps %d; polar steps %d.\n',hc.state.step,nc.state.step);
fprintf(fid,'Active segment wall seconds: hybrid %.6f; polar %.6f; polar/hybrid %.6f.\n', ...
    hTiming.missionActiveSegmentWallSeconds,nTiming.missionActiveSegmentWallSeconds,report.nativeOverHybridMissionActiveSegmentWallRatio);
fprintf(fid,'Core differences: centered rho %.6e; q %.6e; Q %.6e; u1-Uref %.6e; u2 %.6e.\n', ...
    differences.core.centeredRho.absoluteInfinity,differences.core.q.absoluteInfinity,differences.core.Q.absoluteInfinity, ...
    differences.core.UrefCenteredU1.absoluteInfinity,differences.core.u2.absoluteInfinity);
fprintf(fid,'Neither trajectory is an exact reference. These costs and differences do not certify equal-accuracy speedup.\n');
fprintf('CR TAU200 comparison: hybrid %d steps, polar %d; active wall %.3f/%.3fs; core W %.3e q %.3e Q %.3e du %.3e\n', ...
    hc.state.step,nc.state.step,hTiming.missionActiveSegmentWallSeconds,nTiming.missionActiveSegmentWallSeconds, ...
    differences.core.centeredRho.absoluteInfinity,differences.core.q.absoluteInfinity,differences.core.Q.absoluteInfinity, ...
    max(differences.core.UrefCenteredU1.absoluteInfinity,differences.core.u2.absoluteInfinity));
end

function [cp,pointer]=load_hybrid(folder)
pointer=jsondecode(fileread(fullfile(folder,'latest.json')));
assert(strcmp(pointer.kind,'ipm_cr_explicit_accepted_pointer_v1')&& ...
    any(strcmp(pointer.path,{fullfile(folder,'accepted_0.mat'),fullfile(folder,'accepted_1.mat')}))&& ...
    strcmp(ipm_c.output.sha256(pointer.path),pointer.sha256),'ipm_cr:CompareHybridSha');
saved=load(pointer.path,'checkpoint');cp=saved.checkpoint;
assert(strcmp(cp.kind,'ipm_cr_explicit_accepted_checkpoint_v1')&&cp.acceptedOnly&& ...
    cp.sequence==pointer.sequence&&cp.state.step==pointer.sequence&& ...
    cp.state.scale.canonicalTime==pointer.tau&&isequaln(cp.rho,cp.state.rho), ...
    'ipm_cr:CompareHybridCheckpoint');
assert(cp.history(end,1)==cp.state.step&&cp.history(end,2)==pointer.tau, ...
    'ipm_cr:CompareHybridHistory','Accepted history and checkpoint disagree.');
end

function [frame,evidence]=load_native_frame(folder,cp,pointer)
catalogPath=fullfile(folder,'data.mat');saved=load(catalogPath,'data');catalog=saved.data;
indices=find([catalog.frames.step]==pointer.sequence&[catalog.frames.tau]==200);
assert(numel(indices)==1,'ipm_cr:CompareNativeCatalog','Require one authoritative exact endpoint frame.');
entry=catalog.frames(indices);path=fullfile(folder,entry.file);saved=load(path,'frame');frame=saved.frame;
assert(frame.step==pointer.sequence&&frame.tau==200&&isequaln(frame.rho_centered,cp.state.rho)&& ...
    isequaln(frame.scale,cp.state.scale)&&frame.rho_origin==cp.state.scale.densityOrigin, ...
    'ipm_cr:CompareNativeFramePrimary','The saved derived frame must belong to the exact accepted primary state.');
meshPath=fullfile(folder,frame.meshFile);saved=load(meshPath,'grid');mesh=saved.grid;
assert(strcmp(mesh.meshId,frame.meshId)&&isequaln(mesh.r(:),cp.grid.r(:))&& ...
    isequaln(mesh.theta(:),cp.grid.theta(:)),'ipm_cr:CompareNativeFrameGrid');
for name={'rho_centered','rho_X','Q','rho_tau_centered','u1','u2'}
    assert(isequal(size(frame.(name{1})),size(cp.state.rho))&&all(isfinite(frame.(name{1})),'all'), ...
        'ipm_cr:CompareNativeFrameFinite','The complete saved native field %s must be finite.',name{1});
end
evidence=struct('path',path,'sha256',ipm_c.output.sha256(path),'step',frame.step,'tau',frame.tau, ...
    'meshPath',meshPath,'meshSha256',ipm_c.output.sha256(meshPath), ...
    'catalogPath',catalogPath,'catalogSha256',ipm_c.output.sha256(catalogPath), ...
    'primaryStateExactlyMatchesAcceptedCheckpoint',true,'derivedFieldsRecomputed',false);
end

function values=hybrid_samples(state,map,origin)
apply=@(f)reshape(map.core*f.core(:)+map.polar*f.polar(:),map.shape);
values=struct('centeredRho',apply(state.rho)-origin,'q',apply(state.flow.q),'Q',apply(state.flow.Q), ...
    'centeredF',apply(state.flow.F), ...
    'UrefCenteredU1',apply(struct('core',state.flow.physical.core.u1,'polar',state.flow.physical.polar.u1))-state.flow.Uref, ...
    'u2',apply(struct('core',state.flow.physical.core.u2,'polar',state.flow.physical.polar.u2)));
end

function values=native_samples(frame,map,shape,origin)
apply=@(f)reshape(map*f(:),shape);
values=struct('centeredRho',apply(frame.rho_centered)-origin,'q',apply(frame.rho_X),'Q',apply(frame.Q), ...
    'centeredF',apply(frame.rho_tau_centered), ...
    'UrefCenteredU1',apply(frame.u1)-frame.diagnostics.referenceVelocity,'u2',apply(frame.u2));
end

function result=difference(hybrid,native,X,Y)
assert(all(isfinite(hybrid),'all')&&all(isfinite(native),'all'), ...
    'ipm_cr:CompareFinite','Every common interpolated query must remain finite.');
d=hybrid-native;[value,index]=max(abs(d(:)));scale=max(abs(native),[],'all');
result=struct('absoluteInfinity',value,'rms',sqrt(mean(d(:).^2)), ...
    'mixedRelativeInfinity',value/max(1,scale),'relativeToNativeInfinity',value/max(scale,realmin), ...
    'nativeInfinity',scale,'hybridInfinity',max(abs(hybrid),[],'all'), ...
    'signedDifferenceAtMaximum',d(index),'maximumLocation',struct('X',X(index),'Y',Y(index)));
end

function result=scale_difference(h,n)
result=struct('hybrid',h,'native',n,'logLengthSignedDifference',h.logC_l-n.logC_l, ...
    'logAmplitudeSignedDifference',h.logC_omega-n.logC_omega,'shiftSignedDifference',h.X_shift-n.X_shift, ...
    'originAmplitudeSignedDifference',h.densityOrigin-n.densityOrigin, ...
    'originAmplitudeRelativeDifference',(h.densityOrigin-n.densityOrigin)/max(abs(n.densityOrigin),realmin), ...
    'physicalClockSignedDifference',(h.physicalTime-n.physicalTime)+(h.physicalTimeLow-n.physicalTimeLow), ...
    'physicalHighSignedDifference',h.physicalTime-n.physicalTime, ...
    'physicalLowSignedDifference',h.physicalTimeLow-n.physicalTimeLow);
end

function result=timing(folder,cp,kind)
missionPath=fullfile(fileparts(folder),'mission.json');mission=jsondecode(fileread(missionPath));
segments=mission.segments;active=0;completed=0;maximumRss=0;
for k=1:numel(segments)
    if isfield(segments(k),'elapsedSeconds')&&~isempty(segments(k).elapsedSeconds)&& ...
        isfield(segments(k),'returncode')&&~isempty(segments(k).returncode)
        active=active+segments(k).elapsedSeconds;completed=completed+1;
    end
    if isfield(segments(k),'maximumRssBytes')&&~isempty(segments(k).maximumRssBytes)
        maximumRss=max(maximumRss,segments(k).maximumRssBytes);
    end
end
if strcmp(kind,'hybrid')
    path=fullfile(folder,'run.log');log=fileread(path);
    tokens=regexp(log,'END status=[^\r\n]*?wall=([0-9.eE+\-]+)','tokens');
    values=cellfun(@(x)str2double(x{1}),tokens);logPaths={path};
    names=cp.historyColumns;stepSeconds=sum(cp.history(:,strcmp(names,'stepSeconds')));
    stepSecondsAvailable=true;
else
    values=[];logPaths={};
    for k=1:numel(segments)
        if isfield(segments(k),'log')&&~isempty(segments(k).log),name=segments(k).log;
        else,name=sprintf('segment_%05d.log',segments(k).index);end
        path=fullfile(fileparts(folder),name);logPaths{end+1}=path; %#ok<AGROW>
        tokens=regexp(fileread(path),'(?m)^[ \t]*elapsedSeconds:[ \t]*([0-9.eE+\-]+)','tokens');
        assert(numel(tokens)<=1,'ipm_cr:CompareTimingLog','A segment has ambiguous solver elapsed records.');
        if ~isempty(tokens),values(end+1)=str2double(tokens{1}{1});end %#ok<AGROW>
    end
    stepSeconds=NaN;stepSecondsAvailable=false;
end
complete=completed==numel(segments)&&completed>0;
solverComplete=numel(values)==completed&&all(isfinite(values));solverSum=NaN;
if solverComplete,solverSum=sum(values);end
result=struct('missionPath',missionPath,'missionSha256',ipm_c.output.sha256(missionPath), ...
    'missionStatus',mission.status,'actualAcceptedSteps',cp.state.step, ...
    'missionSegments',numel(segments),'completedMissionSegments',completed, ...
    'allMissionSegmentsCompleted',complete,'missionActiveSegmentWallSeconds',active, ...
    'matlabSolverInvocationSeconds',solverSum,'solverInvocationTimingsComplete',solverComplete, ...
    'recordedSolverInvocationSeconds',values,'solverTimingLogPaths',{logPaths}, ...
    'acceptedAdvanceStepSeconds',stepSeconds,'acceptedAdvanceStepSecondsAvailable',stepSecondsAvailable, ...
    'mainProcessSampledRssMaximumBytes',maximumRss, ...
    'missionActiveSegmentScope','Sum of completed segment.elapsedSeconds, including MATLAB startup, solver initialization/output and polling tail; no UTC-envelope or supervisorWallSeconds sum.', ...
    'matlabSolverInvocationScope','Sum of each MATLAB runner END wall or native elapsedSeconds report; includes initialization/checkpoints/output, excludes external MATLAB startup. Text values may be rounded.', ...
    'acceptedAdvanceStepScope','Hybrid-only sum of per-accepted-step advance.seconds, including CFL retries; excludes initialization/checkpoints/output. Native matching narrow metric was not recorded.', ...
    'utcSleepGapsUsedAsOperatorTime',false,'supervisorWallSecondsUsedAsTotal',false);
end

function value=history_max(cp,name)
column=strcmp(cp.historyColumns,name);values=cp.history(:,column);values=values(isfinite(values));
if isempty(values),value=NaN;else,value=max(values);end
end

function value=safe_ratio(a,b)
if isfinite(a)&&isfinite(b)&&b>0,value=a/b;else,value=NaN;end
end

function summary=cloud_summary(c)
summary=struct('description',c.description,'queryCount',numel(c.X),'shape',size(c.X), ...
    'xBounds',[min(c.X,[],'all'),max(c.X,[],'all')],'yBounds',[min(c.Y,[],'all'),max(c.Y,[],'all')], ...
    'maximumRadius',max(hypot(c.X,c.Y),[],'all'));
if isfield(c,'radii'),summary.radii=c.radii;summary.theta=c.theta;end
end

function files=source_files()
paths={[mfilename('fullpath'),'.m'],which('ipm_cr.explicit.interpolate'), ...
    which('ipm_cr.carrier.tensorMap'),which('ipm_cr.carrier.localMap'), ...
    which('ipm_c.gauge.measure'),which('ipm_c.output.loadCheckpoint')};files=struct([]);
for k=1:numel(paths)
    entry=struct('path',paths{k},'sha256',ipm_c.output.sha256(paths{k}));
    if isempty(files),files=entry;else,files(end+1)=entry;end %#ok<AGROW>
end
end

function assert_unchanged(folder,pointer)
current=jsondecode(fileread(fullfile(folder,'latest.json')));
assert(current.sequence==pointer.sequence&&strcmp(current.sha256,pointer.sha256)&& ...
    strcmp(ipm_c.output.sha256(pointer.path),pointer.sha256), ...
    'ipm_cr:CompareChangedInput','An accepted input checkpoint changed during comparison.');
end

function value=within(path,parent)
path=char(java.io.File(path).getCanonicalPath());parent=char(java.io.File(parent).getCanonicalPath());
value=strcmp(path,parent)||startsWith(path,[parent,filesep]);
end

function write_json(path,value)
temporary=[path,'.writing'];fid=fopen(temporary,'w');assert(fid>=0,'ipm_cr:CompareSave');
cleanup=onCleanup(@()fclose(fid));fwrite(fid,jsonencode(value,'PrettyPrint',true),'char');clear cleanup
[ok,message]=movefile(temporary,path,'f');assert(ok,'ipm_cr:CompareSave','%s',message);
end
