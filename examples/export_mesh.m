function [m,paths]=export_mesh(outputDir)
%EXPORT_MESH Export actual transport/spectral nodes without evolving a PDE.
%   [M,PATHS]=EXPORT_MESH(ABSOLUTE_OUTPUT_DIR) creates a new output directory.
%   The compressed MATLAB v7 file contains only numeric geometry and masks,
%   not factors, states, analytic fields, or interpolated display geometry.
%   Python: scipy.io.loadmat(PATHS.mat,simplify_cells=True)['m'].
%
%   All array indices in this export are MATLAB 1-based. Transport arrays
%   have [ny,nx] (core) or [nr,ntheta] (polar) layout. Spectral panelIndex,
%   panelR and panelT have [degree+1,nPanels] layout. A shared radial endpoint
%   appears once in the global radial axis and once in EACH adjacent panel.

assert((ischar(outputDir)&&isrow(outputDir))|| ...
    (isstring(outputDir)&&isscalar(outputDir)), ...
    'ipm_cr:MeshExportPath','Use a text scalar output directory.');
outputDir=char(outputDir);
target=java.io.File(outputDir);
assert(target.isAbsolute(),'ipm_cr:MeshExportPath', ...
    'Use an absolute output directory.');
assert(~isfolder(outputDir)&&~isfile(outputDir),'ipm_cr:MeshExportExists', ...
    'Output already exists; choose a new directory: %s',outputDir);
root=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'src'));

grid=struct('nr',385,'ntheta',129,'rmax',1e10,'firstSpacing',.03, ...
    'radialMap','uniform_core','coreRadius',2,'coreTailFraction',.01, ...
    'stencilWidth',7);
rr=struct('enabled',true,'factor',2,'preserveRadius',4, ...
    'fullRefinementRadius',20);
transport=struct('grid',grid,'coreHalfWidth',1.2,'coreHeight',1.2, ...
    'coreSpacing',.03,'polarStart',.72,'ghostWidth',3, ...
    'interpolationWidth',7,'radialRedistribution',rr);
spectral=ipm_cr.pconfig(struct('coreDegree',[64,64], ...
    'angularDegree',80,'polarDegree',20,'rOuter',1e10));

% These are the production constructors. No context, initial condition,
% source, time step, or spectral/core coupling solve is constructed here.
g=ipm_cr.mesh.build(transport);
base=ipm_cr.mesh.polar(grid);
[r,metric,ri]=ipm_cr.mesh.radial(base,rr);
c=ipm_cr.poisson.core.build(spectral);
p=ipm_cr.poisson.polar.build(spectral);
assert(isequal(r(g.polar.originalIndices),g.polar.r)&& ...
    isequal(metric(g.polar.originalIndices),g.polar.drMetric), ...
    'ipm_cr:MeshExportAxis','Rebuilt full radial axis differs from transport geometry.');

m=struct('format','ipm_cr_mesh_v1', ...
    'createdUtc',char(datetime('now','TimeZone','UTC', ...
        'Format',"yyyy-MM-dd'T'HH:mm:ss'Z'")), ...
    'cfg',struct('transport',transport,'poisson',spectral));
m.transport.core=pick(g.core,{'x','y','X','Y','active','ghost', ...
    'activeXBounds','activeYBounds','activeRows','activeColumns', ...
    'ghostWidth','physicalWallRow'});
m.transport.polar=pick(g.polar,{'r','theta','X','Y','active','ghost', ...
    'drMetric','innerHaloRadius','innerActiveRadius','activeRows', ...
    'activeColumns','innerHaloRows','originalIndices','ghostWidth'});
m.radial=struct('baseR',base.r,'baseMetric',base.radialMetric/(base.nr-1), ...
    'r',r,'metric',metric,'oldIndex',ri.oldIndexAtNewNodes, ...
    'preservedPrefixCount',ri.preservedPrefixCount, ...
    'copiedMetricPrefixCount',ri.copiedMetricPrefixCount, ...
    'preserveRadius',rr.preserveRadius, ...
    'fullRefinementRadius',rr.fullRefinementRadius, ...
    'actualTailDensityFactor',ri.actualTailDensityFactor);
m.poisson.core=pick(c,{'x','y','X','Y','traceIndex','traceX','traceY'});
m.poisson.polar=pick(p,{'r','t','theta','X','Y','logEdges', ...
    'interfaceRows','equationRows','degree','angularDegree','nPanels'});
m.poisson.polar.panelIndex=cat(1,p.panelIndices{:}).';
m.poisson.polar.panelR=p.r(m.poisson.polar.panelIndex);
m.poisson.polar.panelT=cat(2,p.panelNodes{:});
m.bounds=struct('coreBox',[-transport.coreHalfWidth,transport.coreHalfWidth, ...
    0,transport.coreHeight], ...
    'coreActiveBox',[g.core.activeXBounds,g.core.activeYBounds.'], ...
    'polarInnerHalo',g.polar.innerHaloRadius, ...
    'polarInnerActive',g.polar.innerActiveRadius,'outer',g.polar.r(end), ...
    'spectralCoreBox',[-spectral.coreHalfWidth,spectral.coreHalfWidth, ...
        0,spectral.coreHeight],'spectralInner',p.rInner);
m.counts=struct('coreNodes',numel(g.core.X), ...
    'coreActive',nnz(g.core.active),'coreGhost',nnz(g.core.ghost), ...
    'polarNodes',numel(g.polar.X),'polarActive',nnz(g.polar.active), ...
    'polarGhost',nnz(g.polar.ghost),'transportActive',g.activeDofCount, ...
    'radialBase',numel(base.r),'radialFull',numel(r), ...
    'radialAnnulus',g.polar.nr,'angularTransport',g.polar.ntheta, ...
    'spectralCoreNodes',numel(c.X),'spectralPolarNodes',numel(p.X), ...
    'spectralPanels',p.nPanels, ...
    'spectralPanelLocalRadialNodes',numel(m.poisson.polar.panelIndex));

% SHA every MATLAB source so the sidecar identifies constructor dependencies
% even when helper files change. The exporter itself is included explicitly.
files=dir(fullfile(root,'src','**','*.m'));
relative=strings(numel(files)+1,1);
for k=1:numel(files)
    full=fullfile(files(k).folder,files(k).name);
    relative(k)=replace(string(full(numel(root)+2:end)),filesep,'/');
end
relative(end)="examples/export_mesh.m";
relative=sort(relative);
sources=repmat(struct('path','','sha256',''),numel(relative),1);
for k=1:numel(relative)
    sources(k).path=char(relative(k));
    sources(k).sha256=ipm_cr.io.sha(fullfile(root,char(relative(k))));
end
assert(~isfolder(outputDir)&&~isfile(outputDir),'ipm_cr:MeshExportExists', ...
    'Output appeared during geometry construction; refusing to overwrite it.');
[ok,message]=mkdir(outputDir);
assert(ok,'ipm_cr:MeshExportDirectory','Cannot create output: %s',message);
paths=struct('mat',fullfile(outputDir,'mesh.mat'), ...
    'json',fullfile(outputDir,'mesh.json'));
save(paths.mat,'m','-v7');
meta=struct('format',m.format,'createdUtc',m.createdUtc, ...
    'dataFile','mesh.mat','sha256',ipm_cr.io.sha(paths.mat), ...
    'cfg',m.cfg,'bounds',m.bounds,'counts',m.counts,'sources',sources, ...
    'noTimeIntegration',true,'noPhysicalFieldData',true, ...
    'coordinates','Actual physical x,y; polar radius spans the full half plane to 1e10.', ...
    'masks','Both overlapping active interiors evolve; ghost masks are interpolation collars.', ...
    'panelContract',['panelIndex is MATLAB 1-based, degree+1 by nPanels. ' ...
        'Adjacent panel endpoints share one global node; panelR/panelT retain both local copies.'], ...
    'metricContract',['dr/dj for the redistributed integer radial index; complete protected ' ...
        'FD7 stencils retain original radialMetric/(baseNr-1).'], ...
    'sourcesContract','All src MATLAB files plus this exporter, with SHA-256.');
fid=fopen(paths.json,'w');
assert(fid>=0,'ipm_cr:MeshExportWrite','Cannot create metadata sidecar.');
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',jsonencode(meta,'PrettyPrint',true));
end

function out=pick(in,names)
out=struct();
for k=1:numel(names),out.(names{k})=in.(names{k});end
end
