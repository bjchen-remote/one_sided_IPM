% Audit one-sided C native checkpoints on their own fixed grid and box.
% Called by main('audit',...) through ipm.workflow.audit_accepted.
% Required environment: IPM_AUDIT_CODE_ROOT, IPM_AUDIT_CHECKPOINT.
% Optional: IPM_AUDIT_OUTPUT_DIR, IPM_AUDIT_MIN_TAU, IPM_AUDIT_STRIDE.
% This script reads the checkpoint and writes only new audit artifacts.

auditRoot = fileparts(mfilename('fullpath'));
codeRoot = getenv('IPM_AUDIT_CODE_ROOT');
sourceCheckpoint = getenv('IPM_AUDIT_CHECKPOINT');
outputRoot = getenv('IPM_AUDIT_OUTPUT_DIR');
if isempty(outputRoot), outputRoot = fullfile(auditRoot,'output'); end
assert(~isempty(codeRoot) && isfolder(codeRoot) && ...
    ~isempty(sourceCheckpoint) && isfile(sourceCheckpoint), ...
    'Set IPM_AUDIT_CODE_ROOT and IPM_AUDIT_CHECKPOINT to existing paths.');
assert(startsWith(codeRoot,filesep) && ...
    startsWith(sourceCheckpoint,filesep) && ...
    startsWith(outputRoot,filesep), ...
    'Use absolute paths for all audit environment variables.');

% MATLAB checks the current folder before the path. Enter the selected
% archived code root to prevent a different +ipm package from shadowing it.
entryFolder = pwd;
rhsThreadCount = maxNumCompThreads;
cd(codeRoot);
codeRoot = pwd;
addpath(codeRoot,'-begin');
assert(startsWith(which('ipm.solve'),[codeRoot filesep]) && ...
    startsWith(which('ipm.field.poisson'),[codeRoot filesep]), ...
    'The selected +ipm package is not first on the MATLAB path.');

% Older checkpoint signatures used exact floating sums. Verify them with
% one thread, then restore the original count before every physical RHS.
try
    maxNumCompThreads(1);
    cp = ipm.output.readCheckpoint(sourceCheckpoint);
catch errorInfo
    maxNumCompThreads(rhsThreadCount);
    rethrow(errorInfo);
end
maxNumCompThreads(rhsThreadCount);
saved = cp.payload.state;
common = cp.payload.log.history.common;
snapshots = cp.payload.log.snapshotRho;
tau = common.canonicalTau(:);
assert(iscell(snapshots) && numel(snapshots)==numel(tau) && ...
    ~isempty(tau) && all(diff(tau)>0), ...
    'Checkpoint snapshots and canonical times must align and increase.');
assert(abs(tau(1))<=1e-10, ...
    'A tau=0 snapshot is needed for P/K drift from the analytic start.');
terminalTau = saved.scale.canonicalTime;
assert(abs(tau(end)-terminalTau)<=1e-9*max(1,terminalTau), ...
    'The last snapshot does not match the checkpoint canonical time.');
assert(strcmp(saved.config.physics.symmetryMode,'half_plane') && ...
    strcmp(saved.config.scaling.dynamicScaleGeometry,'isotropic'), ...
    'Expected a one-sided isotropic checkpoint.');

x = saved.x(:)';
y = saved.y(:);
assert(numel(x)>=9 && numel(y)>=9 && x(1)<0 && x(end)>0 && ...
    y(1)==0 && y(end)>2 && all(diff(x)>0) && all(diff(y)>0), ...
    'The checkpoint does not contain a valid full-X half-plane grid.');
assert(numel(cp.payload.log.snapshotX)==numel(tau) && ...
    numel(cp.payload.log.snapshotY)==numel(tau), ...
    'The snapshot axis logs do not align with canonical times.');
for snapshotIndex = 1:numel(tau)
    assert(isequal(cp.payload.log.snapshotX{snapshotIndex}(:)',x) && ...
        isequal(cp.payload.log.snapshotY{snapshotIndex}(:),y), ...
        ['Snapshot %d uses a different grid. Audit each fixed-grid ' ...
        'branch separately.'],snapshotIndex);
end
grid = saved.config.grid;
grid.nx = numel(x);
grid.ny = numel(y);
grid.customX = x;
grid.customY = y;
ops = ipm.mesh.build(saved.config,grid);
assert(isequal(ops.x(:)',x) && isequal(ops.y(:),y), ...
    'Rebuilt operators do not use the stored axes.');
ops.rescaling = ipm.output.restoreRuntimeReferences( ...
    ops.rescaling,saved.rescaling,x,true);
assert(any(x>=-2 & x<=2) && any(y>=0 & y<=2), ...
    'The fixed core [-2,2] x [0,2] has no grid nodes.');

assert(numel(common.c_l)==numel(tau) && ...
    numel(common.c_omega)==numel(tau), ...
    'The scale-rate history does not align with canonical times.');
gamma = common.c_l(:)-common.c_omega(:);
Cs = NaN(size(gamma));
validCs = isfinite(gamma) & gamma>0 & isfinite(common.c_l(:));
Cs(validCs) = common.c_l(validCs)./gamma(validCs);
minTau = str2double(getenv('IPM_AUDIT_MIN_TAU'));
if isnan(minTau), minTau = max(tau(1),terminalTau-1.5); end
stride = str2double(getenv('IPM_AUDIT_STRIDE'));
if isnan(stride), stride = 5; end
assert(isfinite(minTau) && minTau>=tau(1) && minTau<=terminalTau && ...
    isfinite(stride) && stride>=1 && stride==fix(stride), ...
    'IPM_AUDIT_MIN_TAU or IPM_AUDIT_STRIDE is invalid.');
eligible = find(tau>=minTau);
indices = eligible(1:stride:end);
if indices(end)~=eligible(end), indices(end+1)=eligible(end); end
coreX = x>=-2 & x<=2;
coreY = y>=0 & y<=2;

rhsRows = repmat(struct( ...
    'tau',NaN,'snapshotIndex',NaN,'Cs',NaN, ...
    'fullSourceNorm',NaN,'fullRateNorm',NaN, ...
    'coreSourceNorm',NaN,'coreRateNorm',NaN, ...
    'fullRelative',NaN,'coreRelative',NaN, ...
    'coreRelativeGlobal',NaN, ...
    'globalSourceX',NaN,'globalSourceY',NaN, ...
    'globalRateX',NaN,'globalRateY',NaN, ...
    'leftSourceRatio',NaN,'rightSourceRatio',NaN, ...
    'topSourceRatio',NaN,'leftRateRatio',NaN, ...
    'rightRateRatio',NaN,'topRateRatio',NaN, ...
    'boundarySourceRatio',NaN,'boundaryRateRatio',NaN, ...
    'leftInflowNodes',NaN,'rightInflowNodes',NaN, ...
    'topInflowNodes',NaN, ...
    'leftSourceOverPeak',NaN,'rightSourceOverPeak',NaN, ...
    'topSourceOverPeak',NaN, ...
    'front1e5X',NaN,'front1e5DistanceLeft',NaN, ...
    'front1e5CellsLeft',NaN,'frontAtLeftBoundary',false), ...
    numel(indices),1);
for row = 1:numel(indices)
    snapshotIndex = indices(row);
    density = snapshots{snapshotIndex};
    assert(isequal(size(density),[numel(y),numel(x)]), ...
        'Snapshot %d does not match the checkpoint grid.',snapshotIndex);
    [densityRate,flow] = ipm.evolve.rhs(density,ops);
    assert(isfield(flow,'transportU1') && ...
        isfield(flow,'transportU2') && ...
        isequal(size(flow.transportU1),size(density)) && ...
        isequal(size(flow.transportU2),size(density)) && ...
        all(isfinite(flow.transportU1),'all') && ...
        all(isfinite(flow.transportU2),'all'), ...
        'Missing or invalid transport velocity at snapshot %d.', ...
        snapshotIndex);
    leftInflowNodes = nnz(flow.transportU1(:,1)>0);
    rightInflowNodes = nnz(flow.transportU1(:,end)<0);
    topInflowNodes = nnz(flow.transportU2(end,:)<0);
    source = flow.source;
    sourceRate = densityRate*ops.Dx';
    [sourceNorm,sourceIndex] = max(abs(source),[],'all');
    [rateNorm,rateIndex] = max(abs(sourceRate),[],'all');
    coreSourceNorm = max(abs(source(coreY,coreX)),[],'all');
    coreRateNorm = max(abs(sourceRate(coreY,coreX)),[],'all');
    assert(sourceNorm>0 && coreSourceNorm>0, ...
        'A source norm vanished at snapshot %d.',snapshotIndex);
    [sourceYIndex,sourceXIndex] = ind2sub(size(source),sourceIndex);
    [rateYIndex,rateXIndex] = ind2sub(size(sourceRate),rateIndex);
    sidesSource = [max(abs(source(:,1))), ...
        max(abs(source(:,end))),max(abs(source(end,:)))];
    sidesRate = [max(abs(sourceRate(:,1))), ...
        max(abs(sourceRate(:,end))),max(abs(sourceRate(end,:)))];
    [~,peakIndex] = max(source(1,:));
    peak = ipm.evolve.quadraticPeakFunctional( ...
        source(1,:),x,peakIndex);
    assert(peak.value>0,'The wall source peak must be positive.');
    activeColumns = max(abs(source),[],1)>=1e-5*peak.value;
    frontIndex = find(activeColumns,1,'first');
    if isempty(frontIndex)
        frontX = NaN; frontDistance = NaN; frontCells = NaN;
        frontAtBoundary = false;
    else
        frontX = x(frontIndex);
        frontDistance = frontX-x(1);
        frontCells = frontIndex-1;
        frontAtBoundary = frontIndex==1;
    end
    sidesRateRatio = NaN(1,3);
    if rateNorm>0, sidesRateRatio = sidesRate/rateNorm; end
    rhsRows(row) = struct( ...
        'tau',tau(snapshotIndex),'snapshotIndex',snapshotIndex, ...
        'Cs',Cs(snapshotIndex), ...
        'fullSourceNorm',sourceNorm,'fullRateNorm',rateNorm, ...
        'coreSourceNorm',coreSourceNorm,'coreRateNorm',coreRateNorm, ...
        'fullRelative',rateNorm/sourceNorm, ...
        'coreRelative',coreRateNorm/coreSourceNorm, ...
        'coreRelativeGlobal',coreRateNorm/sourceNorm, ...
        'globalSourceX',x(sourceXIndex),'globalSourceY',y(sourceYIndex), ...
        'globalRateX',x(rateXIndex),'globalRateY',y(rateYIndex), ...
        'leftSourceRatio',sidesSource(1)/sourceNorm, ...
        'rightSourceRatio',sidesSource(2)/sourceNorm, ...
        'topSourceRatio',sidesSource(3)/sourceNorm, ...
        'leftRateRatio',sidesRateRatio(1), ...
        'rightRateRatio',sidesRateRatio(2), ...
        'topRateRatio',sidesRateRatio(3), ...
        'boundarySourceRatio',max(sidesSource)/sourceNorm, ...
        'boundaryRateRatio',max(sidesRateRatio), ...
        'leftInflowNodes',leftInflowNodes, ...
        'rightInflowNodes',rightInflowNodes, ...
        'topInflowNodes',topInflowNodes, ...
        'leftSourceOverPeak',sidesSource(1)/peak.value, ...
        'rightSourceOverPeak',sidesSource(2)/peak.value, ...
        'topSourceOverPeak',sidesSource(3)/peak.value, ...
        'front1e5X',frontX,'front1e5DistanceLeft',frontDistance, ...
        'front1e5CellsLeft',frontCells, ...
        'frontAtLeftBoundary',frontAtBoundary);
end
rhsTable = struct2table(rhsRows);

% Three late half-tau windows are reported when they contain data. Short
% verification runs retain explicit NaNs instead of pretending to have
% measured three late-time slopes.
windowRows = repmat(struct('startTau',NaN,'endTau',NaN, ...
    'count',0,'CsMedian',NaN,'CsRelativeRange',NaN, ...
    'CsSlope',NaN),3,1);
for row = 1:3
    lower = terminalTau-(4-row)*0.5;
    upper = lower+0.5;
    selected = false(size(tau));
    if lower>=tau(1)
        selected = tau>=lower & tau<upper & isfinite(Cs);
        if row==3
            selected = tau>=lower & tau<=upper & isfinite(Cs);
        end
    end
    times = tau(selected);
    values = Cs(selected);
    windowRows(row).startTau = lower;
    windowRows(row).endTau = upper;
    windowRows(row).count = numel(values);
    if ~isempty(values)
        windowRows(row).CsMedian = median(values);
        windowRows(row).CsRelativeRange = ...
            (max(values)-min(values))/abs(median(values));
    end
    if numel(values)>=2
        fit = polyfit(times,values,1);
        windowRows(row).CsSlope = fit(1);
    end
end
windowTable = struct2table(windowRows);

gaugeIndices = unique([1;find(tau>=max(tau(1),terminalTau-1.5))]);
gaugeRows = repmat(struct('tau',NaN,'snapshotIndex',NaN, ...
    'peak',NaN,'curvature',NaN,'peakX',NaN, ...
    'peakRelativeDriftFromTau0',NaN, ...
    'curvatureRelativeDriftFromTau0',NaN), ...
    numel(gaugeIndices),1);
for row = 1:numel(gaugeIndices)
    snapshotIndex = gaugeIndices(row);
    source = snapshots{snapshotIndex}*ops.Dx';
    [~,peakIndex] = max(source(1,:));
    peak = ipm.evolve.quadraticPeakFunctional( ...
        source(1,:),x,peakIndex);
    [~,curvature] = ipm.evolve.smoothPeakCurvatureFunctional( ...
        source(1,:),x,peak,ops.rescaling.peakCurvatureRadius);
    assert(peak.value>0 && curvature<0, ...
        'The wall peak or curvature is invalid at snapshot %d.',snapshotIndex);
    gaugeRows(row).tau = tau(snapshotIndex);
    gaugeRows(row).snapshotIndex = snapshotIndex;
    gaugeRows(row).peak = peak.value;
    gaugeRows(row).curvature = curvature;
    gaugeRows(row).peakX = peak.x;
end
referencePeak = gaugeRows(1).peak;
referenceCurvature = gaugeRows(1).curvature;
referencePeakX = gaugeRows(1).peakX;
for row = 1:numel(gaugeRows)
    gaugeRows(row).peakRelativeDriftFromTau0 = ...
        gaugeRows(row).peak/referencePeak-1;
    gaugeRows(row).curvatureRelativeDriftFromTau0 = ...
        gaugeRows(row).curvature/referenceCurvature-1;
end
gaugeTable = struct2table(gaugeRows);
gaugeWindowRows = repmat(struct('startTau',NaN,'endTau',NaN, ...
    'count',0,'peakMedian',NaN,'peakRelativeRange',NaN, ...
    'peakSlope',NaN,'curvatureMedian',NaN, ...
    'curvatureRelativeRange',NaN,'curvatureSlope',NaN, ...
    'peakXMedian',NaN,'peakXSlope',NaN),3,1);
for row = 1:3
    lower = windowRows(row).startTau;
    upper = windowRows(row).endTau;
    selected = false(size(gaugeTable.tau));
    if lower>=tau(1)
        selected = gaugeTable.tau>=lower & gaugeTable.tau<upper;
        if row==3
            selected = gaugeTable.tau>=lower & gaugeTable.tau<=upper;
        end
    end
    times = gaugeTable.tau(selected);
    p = gaugeTable.peak(selected);
    k = gaugeTable.curvature(selected);
    center = gaugeTable.peakX(selected);
    gaugeWindowRows(row).startTau = lower;
    gaugeWindowRows(row).endTau = upper;
    gaugeWindowRows(row).count = numel(times);
    if ~isempty(times)
        gaugeWindowRows(row).peakMedian = median(p);
        gaugeWindowRows(row).peakRelativeRange = ...
            (max(p)-min(p))/abs(median(p));
        gaugeWindowRows(row).curvatureMedian = median(k);
        gaugeWindowRows(row).curvatureRelativeRange = ...
            (max(k)-min(k))/abs(median(k));
        gaugeWindowRows(row).peakXMedian = median(center);
    end
    if numel(times)>=2
        pFit = polyfit(times,p,1);
        kFit = polyfit(times,k,1);
        centerFit = polyfit(times,center,1);
        gaugeWindowRows(row).peakSlope = pFit(1);
        gaugeWindowRows(row).curvatureSlope = kFit(1);
        gaugeWindowRows(row).peakXSlope = centerFit(1);
    end
end
gaugeWindowTable = struct2table(gaugeWindowRows);

% Four requested profile times over the available final three tau; nearest
% actual snapshots are deduplicated so early short tests remain meaningful.
profileStart = max(tau(1),terminalTau-3);
profileTargets = linspace(profileStart,terminalTau,4);
profileIndices = zeros(1,numel(profileTargets));
for j = 1:numel(profileTargets)
    [~,profileIndices(j)] = min(abs(tau-profileTargets(j)));
end
profileIndices = unique(profileIndices,'stable');
[Z,E] = meshgrid(linspace(-2,2,101),linspace(0,2,51));
[Zwide,Ewide] = meshgrid(linspace(-4,4,101),linspace(0,4,51));
profileGrid = struct('Z',Z,'E',E,'Zwide',Zwide,'Ewide',Ewide);
profileRows = repmat(struct('tau',NaN,'snapshotIndex',NaN, ...
    'Cs',NaN,'peak',NaN,'peakX',NaN,'curvature',NaN, ...
    'ell',NaN,'front1e5',NaN,'front1e4',NaN,'front1e3',NaN, ...
    'front1e5X',NaN,'front1e5DistanceLeft',NaN, ...
    'coreProfileChangePerTau',NaN,'wideProfileChangePerTau',NaN, ...
    'QChangePerTau',NaN,'QzChangePerTau',NaN, ...
    'QzWideChangePerTau',NaN),numel(profileIndices),1);
profiles = repmat(struct('tau',NaN,'Q',[],'Qz',[],'QzWide',[]), ...
    numel(profileIndices),1);

% Cuts are snapped to stored nodes. Their actual coordinates, not just
% nominal fractions, are written in every row of the cut table.
cutFractions = [1,0.5,0.1,0.01];
cutIndices = zeros(size(cutFractions));
for j = 1:numel(cutFractions)
    [~,cutIndices(j)] = min(abs(x-x(1)*cutFractions(j)));
end
[cutIndices,keptCuts] = unique(cutIndices,'stable');
cutFractions = cutFractions(keptCuts);
cutRows = repmat(struct('tau',NaN,'snapshotIndex',NaN, ...
    'nominalLeftFraction',NaN,'nominalX',NaN, ...
    'gridIndex',NaN,'x',NaN,'actualX',NaN, ...
    'actualLeftFraction',NaN,'maxAbsRxOverPeak',NaN, ...
    'maxAbsR',NaN,'transportMin',NaN,'transportMax',NaN, ...
    'transportWall',NaN,'fractionTransportPositive',NaN), ...
    numel(profileIndices)*numel(cutIndices),1);

for row = 1:numel(profileIndices)
    snapshotIndex = profileIndices(row);
    density = snapshots{snapshotIndex};
    [~,flow] = ipm.evolve.rhs(density,ops);
    source = flow.source;
    [~,peakIndex] = max(source(1,:));
    peak = ipm.evolve.quadraticPeakFunctional( ...
        source(1,:),x,peakIndex);
    [~,curvature] = ipm.evolve.smoothPeakCurvatureFunctional( ...
        source(1,:),x,peak,ops.rescaling.peakCurvatureRadius);
    assert(peak.value>0 && curvature<0, ...
        'The normalized profile requires a positive peak and negative K.');
    ell = sqrt(-2*peak.value/curvature);
    qInterpolator = griddedInterpolant({y,x},source,'spline','none');
    rhoInterpolator = griddedInterpolant({y,x},density,'spline','none');
    Qz = qInterpolator(ell*E,peak.x+ell*Z)/peak.value;
    QzWide = qInterpolator(ell*Ewide,peak.x+ell*Zwide)/peak.value;
    Q = (rhoInterpolator(ell*E,peak.x+ell*Z)- ...
        rhoInterpolator(0,peak.x))/(peak.value*ell);
    assert(all(isfinite(Q),'all') && all(isfinite(Qz),'all') && ...
        all(isfinite(QzWide),'all'), ...
        'A normalized profile comparison window left the saved grid.');
    columnMaximum = max(abs(source),[],1)/peak.value;
    front5 = find(columnMaximum>=1e-5,1,'first');
    front4 = find(columnMaximum>=1e-4,1,'first');
    front3 = find(columnMaximum>=1e-3,1,'first');
    frontX = NaN; front4X = NaN; front3X = NaN;
    frontDistance = NaN;
    if ~isempty(front5)
        frontX = x(front5);
        frontDistance = frontX-x(1);
    end
    if ~isempty(front4), front4X = x(front4); end
    if ~isempty(front3), front3X = x(front3); end
    profileRows(row) = struct('tau',tau(snapshotIndex), ...
        'snapshotIndex',snapshotIndex,'Cs',Cs(snapshotIndex), ...
        'peak',peak.value,'peakX',peak.x,'curvature',curvature, ...
        'ell',ell,'front1e5',frontX,'front1e4',front4X, ...
        'front1e3',front3X,'front1e5X',frontX, ...
        'front1e5DistanceLeft',frontDistance, ...
        'coreProfileChangePerTau',NaN, ...
        'wideProfileChangePerTau',NaN, ...
        'QChangePerTau',NaN,'QzChangePerTau',NaN, ...
        'QzWideChangePerTau',NaN);
    profiles(row) = struct('tau',tau(snapshotIndex), ...
        'Q',Q,'Qz',Qz,'QzWide',QzWide);
    if row>1
        dt = profiles(row).tau-profiles(row-1).tau;
        previous = profiles(row-1);
        profileRows(row).QChangePerTau = ...
            norm(Q(:)-previous.Q(:))/ ...
            max(norm(Q(:)),norm(previous.Q(:)))/dt;
        profileRows(row).QzChangePerTau = ...
            norm(Qz(:)-previous.Qz(:))/ ...
            max(norm(Qz(:)),norm(previous.Qz(:)))/dt;
        profileRows(row).QzWideChangePerTau = ...
            norm(QzWide(:)-previous.QzWide(:))/ ...
            max(norm(QzWide(:)),norm(previous.QzWide(:)))/dt;
        profileRows(row).coreProfileChangePerTau = ...
            profileRows(row).QzChangePerTau;
        profileRows(row).wideProfileChangePerTau = ...
            profileRows(row).QzWideChangePerTau;
    end
    for j = 1:numel(cutIndices)
        cutIndex = cutIndices(j);
        velocityCut = flow.transportU1(:,cutIndex);
        cutRows((row-1)*numel(cutIndices)+j) = struct( ...
            'tau',tau(snapshotIndex), ...
            'snapshotIndex',snapshotIndex, ...
            'nominalLeftFraction',cutFractions(j), ...
            'nominalX',x(1)*cutFractions(j), ...
            'gridIndex',cutIndex,'x',x(cutIndex), ...
            'actualX',x(cutIndex), ...
            'actualLeftFraction',x(cutIndex)/x(1), ...
            'maxAbsRxOverPeak',max(abs(source(:,cutIndex)))/peak.value, ...
            'maxAbsR',max(abs(density(:,cutIndex))), ...
            'transportMin',min(velocityCut), ...
            'transportMax',max(velocityCut), ...
            'transportWall',velocityCut(1), ...
            'fractionTransportPositive',mean(velocityCut>0));
    end
end
profileTable = struct2table(profileRows);
cutTable = struct2table(cutRows);

