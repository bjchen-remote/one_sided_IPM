audit = struct('inputFile',sourceCheckpoint, ...
    'rhs',rhsTable,'CsWindows',windowTable, ...
    'profiles',profileTable,'cuts',cutTable, ...
    'gauge',gaugeTable,'gaugeWindows',gaugeWindowTable);

