"""Independent quadrature/ODE checks and figure for the exact-master route."""
import json
import numpy as np
import sympy as sp
from scipy.interpolate import CubicSpline
from exact_master_route import OUT, Wall
from exact_master_shoot import build


def main():
    s,z=sp.symbols('s z',real=True)
    mu=sp.Rational(1,5);lam=3*mu;q=1+s*s
    I=sp.integrate(z**3*(1+(s*z)**2)**3,(z,0,1))
    r=-I/(mu*q)
    forcing=(-mu*q*sp.diff(q,s)-mu*s*q*sp.diff(q,s,2)+mu*s*sp.diff(q,s)**2
             -3*q*q*sp.diff(r,s)+q*sp.diff(q,s)*r)
    integrand=sp.cancel((q*q*forcing).subs(s,s*z))
    assert sp.denom(integrand).free_symbols.isdisjoint({s,z})
    t=sp.integrate(z**8*integrand,(z,0,1))/(mu*q*q)
    one=sp.factor(mu*s*sp.diff(r,s)+(2*(lam-mu)+mu*s*sp.diff(q,s)/q)*r+q*q)
    two=sp.factor(mu*s*sp.diff(t,s)+(4*lam-3*mu+2*mu*s*sp.diff(q,s)/q)*t-forcing)
    assert one==0 and two==0
    # Run the same numerical jet generator on an independently solvable source.
    synthetic=Wall.__new__(Wall)
    synthetic.mu=float(mu);synthetic.lam=float(lam)
    synthetic.slo=-3.;synthetic.shi=3.
    synthetic.qspline=lambda x,i=0: (1+x*x if i==0 else 2*x if i==1 else np.zeros_like(x)+2)
    ss=np.linspace(-1.5,1.5,101)
    rn,tn=synthetic.jets(ss,48)
    rf,tf=sp.lambdify(s,r,'numpy'),sp.lambdify(s,t,'numpy')
    re=float(np.max(abs(rn-rf(ss))))
    te=float(np.max(abs(tn-tf(ss))))
    assert re<1e-10 and te<1e-9

    prior=json.loads((OUT/'checks.json').read_text())
    shoots=json.loads((OUT/'shooting.json').read_text())
    ode=[]
    for row in shoots:
        config=dict(row['config'])
        par=row['optimized']
        if row['freeRates']:config.update(zip(['lam','mu','v'],par[3:]))
        zz=np.linspace(*row['trainingXiRange'],1201)
        fine=build(par[:3],config,zz)
        # An independent derivative of integrated h must equal f G_xi.
        hder=CubicSpline(zz,fine['h'])(zz,1)
        g=np.cosh(config['beta']*zz)+config['k0']*np.sinh(config['beta']*zz)
        err=float(abs((hder-fine['f']*g)[3:-3]).max())
        assert err<2e-6
        # Freeze accelerations and recheck the continuum between fit nodes.
        res=fine['matrix']@np.array(row['secondGeometryRates'])-fine['target']
        ode.append(dict(case=row['case'],integratedDensityDerivativeMaxError=err,
            denseSecondRms=float(np.sqrt(np.mean(res*res))),
            denseSecondRelativeToForcing=float(np.linalg.norm(res)/np.linalg.norm(fine['forcing'])),
            denseMotherMin=float(fine['f'].min())))
    # Quadrature and saved-grid sensitivity compare IDENTICAL spatial supports.
    audits=prior['audits']
    ref=next(r for r in audits if r['name']=='L4_257x129' and r['stride']==1 and r['nodes']==64 and r['beta']==1.5)
    sensitivity=[]
    for row in audits:
        if row['name']=='L4_257x129' and row['beta']==1.5:
            sensitivity.append(dict(stride=row['stride'],nodes=row['nodes'],
                firstErrorDifference=row['fits'][0]['firstRelativeL2']-ref['fits'][0]['firstRelativeL2'],
                secondErrorDifference=row['fits'][0]['secondRelativeL2']-ref['fits'][0]['secondRelativeL2']))
    result=dict(syntheticSource='q(s)=1+s^2, lambda=3/5, mu=1/5',
        syntheticFirstSymbolic=str(one),syntheticSecondSymbolic=str(two),
        quadratureFirstMaxError=re,quadratureSecondMaxError=te,
        generatedMasterChecks=ode,sensitivity=sensitivity)
    (OUT/'validation.json').write_text(json.dumps(result,indent=2)+'\n')

    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.size':10,'axes.spines.top':False,'axes.spines.right':False})
    fig,ax=plt.subplots(1,3,figsize=(14,4),layout='constrained')
    labels={'narrow_fixed_rates':'Narrow fit, fixed rates','wide_fixed_rates':'Wider fit, fixed rates',
            'wide_free_rates':'Free rates (extension failed)'}
    colors=['#247ba0','#dc8054','#7854a4']
    for row,color in zip(shoots,colors):
        arr=np.load(OUT/(row['case']+'.npz'))
        ax[0].plot(arr['xi'],arr['mother'],color=color,label=labels[row['case']])
        ax[1].plot(arr['xi'],arr['secondResidual'],color=color)
    arr=np.load(OUT/'generated_local_master.npz')
    ax[0].plot(arr['xi'],arr['savedWallMother'],'k--',lw=1,label='Saved conditional wall')
    ax[0].set(xlabel='Transverse coordinate xi',ylabel='Fixed mother f',title='Mother generated by the first wall ODE')
    ax[0].legend(fontsize=8)
    ax[1].axhline(0,color='black',lw=.7)
    ax[1].set(xlabel='Transverse coordinate xi',ylabel='Second wall identity defect',title='The next identity still does not vanish')
    chosen=[next(r for r in audits if r['name']=='L4_257x129' and r['stride']==1 and r['nodes']==64 and r['beta']==b) for b in [0.,1.5]]
    pos=np.arange(2)
    for i,(key,label) in enumerate([('firstRelativeL2','First normal jet'),('secondRelativeL2','Second normal jet')]):
        ax[2].bar(pos+(i-.5)*.3,[100*r['fits'][0][key] for r in chosen],.3,label=label)
    ax[2].set_xticks(pos,['Affine map','Hyperbolic + skew'])
    ax[2].set(ylabel='Relative jet mismatch (%)',title='Same saved wall; zero shape modes')
    ax[2].legend(fontsize=8)
    for a in ax:a.grid(alpha=.2)
    fig.suptitle('Exact-mother exploration: first-order construction, second-order mismatch remains',fontsize=13)
    fig.savefig(OUT/'exact_master_route.png',dpi=170)
    plt.close(fig)
    print(json.dumps(result,indent=2))


if __name__=='__main__':main()
