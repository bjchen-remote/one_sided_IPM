function widthRate = normalized_width_rate( ...
        feature,featureRate,x,peakIndex,level)
peak = feature(peakIndex);
threshold = level*peak;
leftNode = peakIndex;
while leftNode > 1 && feature(leftNode-1) >= threshold
    leftNode = leftNode-1;
end
rightNode = peakIndex;
while rightNode < numel(feature) && feature(rightNode+1) >= threshold
    rightNode = rightNode+1;
end
if leftNode == 1 || rightNode == numel(feature)
    error('ipm:DegenerateLengthGauge', ...
        'The tracked wall-omega selected-level component is not interior.');
end

[leftSlope,leftRate] = crossing_data(leftNode-1,leftNode, ...
    feature,featureRate,x,threshold);
[rightSlope,rightRate] = crossing_data(rightNode,rightNode+1, ...
    feature,featureRate,x,threshold);
peakRate = featureRate(peakIndex);
leftVelocity = -(leftRate-level*peakRate)/leftSlope;
rightVelocity = -(rightRate-level*peakRate)/rightSlope;
widthRate = rightVelocity-leftVelocity;
end

function [slope,rate] = crossing_data( ...
        left,right,feature,featureRate,x,threshold)
valueDifference = feature(right)-feature(left);
if abs(valueDifference) <= 100*eps(max(abs(feature)))
    error('ipm:DegenerateLengthGauge', ...
        'A wall-omega selected-level crossing has zero discrete slope.');
end
fraction = (threshold-feature(left))/valueDifference;
slope = valueDifference/(x(right)-x(left));
rate = featureRate(left)+fraction*(featureRate(right)-featureRate(left));
end

function [crossing,slope,condition,leftIndex] = ...
        upward_crossing(x,values,level)
index = find(values >= level,1,'first');
if isempty(index)
    error('ipm:DegenerateLengthGauge', ...
        'A wall-density length-gauge level has no crossing.');
end
if index == 1
    error('ipm:DegenerateLengthGauge', ...
        'A wall-density crossing is not bracketed in the open profile.');
end
leftValue = values(index-1);
rightValue = values(index);
valueDifference = rightValue-leftValue;
valueScale = max(abs(values));
if valueDifference <= 100*eps(max(valueScale,1))
    error('ipm:DegenerateLengthGauge', ...
        ['A wall-density crossing has zero, reversed, or numerically ' ...
        'unresolved discrete slope.']);
end
fraction = (level-leftValue)/valueDifference;
if ~isfinite(fraction) || fraction < 0 || fraction > 1
    error('ipm:DegenerateLengthGauge', ...
        'A wall-density crossing left its discrete interpolation bracket.');
end
crossing = x(index-1)+fraction*(x(index)-x(index-1));
slope = valueDifference/(x(index)-x(index-1));
condition = valueDifference/max(valueScale,realmin);
leftIndex = index-1;
end
