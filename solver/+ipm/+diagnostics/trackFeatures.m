function details = trackFeatures(rho,physicalRhs,flow,ops)
%IPM.DIAGNOSTICS.TRACKFEATURES Extract peak, crossing, width, and resolution data.

details = empty_details();
r = ops.rescaling;
sourceScale = max(abs(flow.source),[],'all');
details.rhoXInf = sourceScale;

if ~r.enabled && ~isfield(r,'pinX')
    return;
end

trackingMask = abs(ops.x-r.pinX) <= r.peakTrackingHalfWidth;
wall = ipm.diagnostics.measureFeatures( ...
    flow.source(1,:),ops.x,r.adaptiveLevels,trackingMask);
if ~r.enabled && wall.peak <= 0
    return;
end
trackedPeakX = ipm.diagnostics.peakLocation( ...
    wall.feature,ops.x,wall.peakIndex);
if r.enabled && strcmp(r.lengthGauge,'wall_omega_width')
    [~,reportedWidthIndex] = max(r.adaptiveLevels);
else
    [~,reportedWidthIndex] = min(abs(r.adaptiveLevels-0.5));
end
levelGridPoints = wall.gridPoints;
% Count only the connected primary component; remote tails cannot hide
% an under-resolved core.
peakGridPoints = wall.areaPoints(1);
vertical = ipm.diagnostics.measureFeatures( ...
    abs(flow.source(:,wall.peakIndex))',ops.y',r.adaptiveLevels,[]);
if r.enabled && strcmp(r.lengthGauge,'wall_density_width')
    positive = find(ops.x >= 0);
    wallDensity = rho(1,positive);
    wallScale = max(wallDensity);
    if wallScale <= r.cOmegaGaugeFloor
        error('ipm:DegenerateLengthGauge', ...
            'Wall density is too small for the width length gauge.');
    end
    normalizedWallDensity = wallDensity/wallScale;
    [details.wallDensityLowerX,details.wallDensityLowerSlope, ...
        details.wallDensityLowerCondition, ...
        details.wallDensityLowerBracket] = upward_crossing( ...
        ops.x(positive),normalizedWallDensity,r.lengthGaugeLevels(1));
    [details.wallDensityUpperX,details.wallDensityUpperSlope, ...
        details.wallDensityUpperCondition, ...
        details.wallDensityUpperBracket] = upward_crossing( ...
        ops.x(positive),normalizedWallDensity,r.lengthGaugeLevels(2));
    details.wallDensityWidth = ...
        details.wallDensityUpperX-details.wallDensityLowerX;
    if details.wallDensityWidth <= 100*eps(max(abs([ ...
            details.wallDensityLowerX,details.wallDensityUpperX])))
        error('ipm:DegenerateLengthGauge', ...
            'Wall-density level crossings are not separated.');
    end
elseif r.enabled && strcmp(r.lengthGauge,'wall_omega_width')
    level = r.adaptiveLevels(reportedWidthIndex);
    rate0 = physicalRhs*ops.Dx';
    details.wallWidthRate = normalized_width_rate( ...
        wall.feature,rate0(1,:),ops.x,wall.peakIndex,level);
    details.wallWidthCurrent = wall.widths(reportedWidthIndex);
end

details = measured_details(details,wall,vertical,trackedPeakX, ...
    reportedWidthIndex,r,ops.x,sourceScale);
% These counts are diagnostics and hard-stop/remesh evidence only.  They
% never feed back into c_l or c_omega under the exact-gauge contract.
details.peakExpansionRatio = max([ ...
    peakGridPoints/max(r.referencePeakPoints,eps), ...
    levelGridPoints./max(r.referenceLevelPoints,eps)]);
details.resolutionFactor = max([ ...
    r.adaptiveTargetPeakPoints/max(peakGridPoints,1), ...
    r.adaptiveTargetLevelPoints./max(levelGridPoints,1), ...
    r.adaptiveTargetVerticalPeakPoints/ ...
    max(vertical.areaPoints(1),1), ...
    r.adaptiveTargetVerticalLevelPoints./ ...
    max(vertical.gridPoints,1)]);
details.safetyFactor = max([ ...
    r.safetyPeakPoints/max(peakGridPoints,1), ...
    r.safetyLevelPoints./max(levelGridPoints,1), ...
    r.safetyVerticalPeakPoints/max(vertical.areaPoints(1),1), ...
    r.safetyVerticalLevelPoints./max(vertical.gridPoints,1)]);
end

function details = measured_details(details,wall,vertical,trackedPeakX, ...
        reportedWidthIndex,r,x,sourceScale)
[~,verticalHalfIndex] = min(abs(r.adaptiveLevels-0.5));
details.peakGridPoints = wall.areaPoints(1);
details.levelGridPoints = wall.gridPoints;
details.supportGridPoints = wall.gridPoints(1);
details.coreGridPoints = wall.gridPoints(end);
details.verticalPeakGridPoints = vertical.areaPoints(1);
details.verticalLevelGridPoints = vertical.gridPoints;
details.verticalSupportGridPoints = vertical.gridPoints(1);
details.verticalCoreGridPoints = vertical.gridPoints(end);
details.trackedVerticalPeakWidth = vertical.widths(verticalHalfIndex);
details.trackedVerticalCoreWidth = vertical.widths(end);
details.targetPeakGridPoints = r.adaptiveTargetPeakPoints;
details.targetSupportGridPoints = r.adaptiveTargetLevelPoints(1);
details.targetCoreGridPoints = r.adaptiveTargetLevelPoints(end);
details.trackedWallPeak = wall.peak;
details.trackedWallPeakWidth = wall.widths(reportedWidthIndex);
details.trackedWallCoreWidth = wall.widths(end);
details.wallOmegaPeakIndex = wall.peakIndex;
details.omegaGaugePeakX = x(wall.peakIndex);
details.omegaGaugePeakCondition = wall.peak/sourceScale;
details.trackedPeakX = trackedPeakX;
details.trackedPeakOffset = trackedPeakX-r.pinX;
end

