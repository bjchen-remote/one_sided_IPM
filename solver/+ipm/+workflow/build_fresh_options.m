function [opts,meshAudit] = build_fresh_options(s,outputRoot)
%BUILD_FRESH_OPTIONS Map main.m settings to ipm.solve options.
% This function builds the analytic mesh but never starts a solve or writes
% an output file. Existing checkpoint continuations do not use it.

arguments
    s (1,1) struct
    outputRoot (1,:) char
end
k = s.initial.power;
assert(any(strcmp(s.initial.kind, ...
    {'shifted_degenerate_primitive', ...
     'shifted_degenerate_primitive_cutoff'})) && ...
    isnumeric(k) && isscalar(k) && isfinite(k) && k>1, ...
    'This archived mesh builder supports the shifted primitive family.');
assert(isnumeric(s.initial.cutoffB) && isscalar(s.initial.cutoffB) && ...
    isfinite(s.initial.cutoffB) && ...
    s.initial.cutoffB>(k-1)^(1/k), ...
    'cutoffB must lie to the right of the analytic wall-gradient peak.');
assert(s.grid.nodesX==fix(s.grid.nodesX) && mod(s.grid.nodesX,2)==1 && ...
    s.grid.nodesY==fix(s.grid.nodesY) && s.grid.nodesY>=17);
assert(s.box.left>0 && s.box.right>0 && s.box.top>0);
frontX = -(k-1)^(1/k);
[x,y,meshAudit] = ipm.mesh.one_sided_multiscale_mesh( ...
    s.grid.nodesX,s.grid.nodesY,s.box.left,s.box.right,s.box.top,frontX);
assert(numel(x)==s.grid.nodesX && numel(y)==s.grid.nodesY && ...
    any(x==0) && x(1)==-s.box.left && x(end)==s.box.right && ...
    y(1)==0 && y(end)==s.box.top);

monitorFile = fullfile(outputRoot,'monitor_full_absolute_rate.csv');
resultFile = fullfile(outputRoot,'result_or_target.mat');
checkpointFile = fullfile(outputRoot,'checkpoints','checkpoint.mat');
opts = struct( ...
    'nx',s.grid.nodesX,'ny',s.grid.nodesY, ...
    'xlim',[-s.box.left,s.box.right],'ymax',s.box.top, ...
    'gridMode','stretched','gridStretchAutomatic',false, ...
    'gridStretch',[5.5,5.5],'customX',x,'customY',y, ...
    'symmetryMode','half_plane', ...
    'initialCondition',s.initial.kind,'degeneratePower',k, ...
    'shiftedCutoffB',s.initial.cutoffB, ...
    'rescalingMode','dynamic','dynamicScaleGeometry','isotropic', ...
    'lengthGauge',s.gauge.length, ...
    'cOmegaGauge',s.gauge.amplitude, ...
    'travelingWaveGauge',s.gauge.position, ...
    'scalingContract',s.gauge.contract, ...
    'peakPositionRestoringRate',s.gauge.peakPositionRestoringRate, ...
    'peakCurvatureRadius',s.gauge.peakCurvatureRadius, ...
    'adaptiveLevels',s.grid.adaptiveLevels, ...
    'spatialDiscretization',s.grid.spatialOrder, ...
    'transportScheme',s.transport.scheme, ...
    'wenoAlphaMode',s.transport.alphaMode, ...
    'wenoInflowDensityDegree',s.transport.inflowDensityDegree, ...
    'timeIntegrator',s.time.integrator, ...
    'remeshTransferScheme',s.grid.transferScheme, ...
    'farBoundaryMode',s.boundary.farMode, ...
    'transportBoundaryMode',s.boundary.transportMode, ...
    'anisotropicPoissonSolver',s.poisson.solver, ...
    'anisotropicPoissonTolerance',s.poisson.tolerance, ...
    'greenSourceTolerance',s.poisson.greenSourceTolerance, ...
    'greenMaxSources',s.poisson.greenMaxSources, ...
    'adaptiveRemesh',s.grid.adaptiveRemesh, ...
    'finalTime',s.time.finalTau, ...
    'physicalFinalTime',s.time.physicalLimit, ...
    'cfl',s.time.cfl,'maxDt',s.time.maxDt, ...
    'maxSteps',s.time.maxSteps,'outputEvery',s.time.outputEvery, ...
    'rhoXStop',Inf,'storeSnapshots',true, ...
    'saveResults',true,'makePlots',false, ...
    'livePlot',true,'writeVideo',false,'verbose',true, ...
    'checkpoint',struct('enabled',true,'file',checkpointFile, ...
        'every',s.time.checkpointEvery,'atExit',true), ...
    'caseMetadata',struct( ...
        'seedKind','analytic_one_sided_primitive', ...
        'frontX',frontX,'meshKind','multiscale', ...
        'study','one_sided_main', ...
        'boundaryVariant','low_order_degree1', ...
        'intervals',[s.grid.nodesX-1,s.grid.nodesY-1], ...
        'box',[-s.box.left,s.box.right,0,s.box.top], ...
        'fullRhoXRateTarget',s.stop.fullAbsoluteRhoXRate, ...
        'fullRhoXRateHoldTau',s.stop.holdTau, ...
        'fullRhoXRateMonitorFile',monitorFile), ...
    'resultFile',resultFile);
end
