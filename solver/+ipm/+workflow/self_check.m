function self_check(s)
%SELF_CHECK Validate the editable experiment without evolving the PDE.
% Called by main.m before a fresh run.
workflowRoot=fileparts(mfilename('fullpath'));
solverRoot=fileparts(fileparts(workflowRoot));
addpath(solverRoot,'-begin');
assert(startsWith(which('ipm.solve'),[solverRoot,filesep]), ...
    'A different +ipm package shadows this release. Change MATLAB folder.');
[opts,meshAudit]=ipm.workflow.build_fresh_options(s, ...
    fullfile(solverRoot,'dry_run_only'));
config=ipm.config.resolve(opts);
ops=ipm.mesh.build(config,config.grid);
rho=ipm.field.initialDensity(ops,config.physics);
assert(isequal(size(rho),[opts.ny,opts.nx]) && ...
    all(isfinite(rho),'all') && all(diff(ops.x)>0) && ...
    all(diff(ops.y)>0) && ops.x(1)==opts.xlim(1) && ...
    ops.x(end)==opts.xlim(2) && ops.y(1)==0 && ...
    ops.y(end)==opts.ymax, ...
    'The initial density or mesh failed the standalone check.');
fprintf('check grid=%dx%d gridRatio(x/y)=%.4f/%.4f\n', ...
    opts.nx,opts.ny,meshAudit.maximumAdjacentXRatio, ...
    meshAudit.maximumAdjacentYRatio);
end
