    'omegaGaugeBulkValue','omegaGaugeBulkCondition', ...
    'omegaGaugeBulkEnergy','omegaGaugeBulkRateScale', ...
    'omegaGaugeReferenceBulkValue', ...
    'transportAnchorX','lengthGaugeStrain','trackedPeakX', ...
    'trackedPeakOffset','peakLocationRhoXX', ...
    'peakLocationRhoXXScale','peakLocationPhaseDefect', ...
    'peakLocationResponseCondition','wallDensityLowerSlope', ...
    'wallDensityUpperSlope','wallDensityLowerCondition', ...
    'wallDensityUpperCondition','wallDensityLowerBracket', ...
    'wallDensityUpperBracket'};
for index = 1:numel(copyNames)
    name = copyNames{index};
    flow.(name) = details.(name);
end

rateNames = {'strainRateResidual','omegaPeakRateResidual', ...
    'omegaGaugeQuadraticRateResidual', ...
    'omegaGaugeAnchorRateResidual','omegaGaugeWindowRateResidual', ...
    'omegaGaugeTemplateRateResidual','omegaGaugeBulkRateResidual', ...
    'pinGaugeResidual','pinTransportVelocity','transportAnchorVelocity', ...
    'lengthGaugeResidual','peakLocationFullPhaseResidual', ...
    'peakLocationNormalizedFullPhaseResidual','peakTransportVelocity', ...
    'travelingWaveResidual'};
for index = 1:numel(rateNames)
    name = rateNames{index};
    flow.(name) = details.(name);
end
flow.canonicalTransportAnchorVelocity = details.transportAnchorVelocity;
if isfield(details,'peakCurvature')
    flow.peakCurvature = details.peakCurvature;
    flow.innerCurvatureWidth = details.innerCurvatureWidth;
    flow.peakCurvatureRate = details.peakCurvatureRate;
    flow.peakHeightRate = details.peakHeightRate;
    flow.peakPositionTargetRate = details.peakPositionTargetRate;
end
end
