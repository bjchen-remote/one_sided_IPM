function [rhs,flow] = rhs(rho,ops,scale)
%IPM.EVOLVE.RHS Shared physical/rescaled IPM right-hand side.

isAnisotropic = strcmp(ops.dynamicScaleGeometry,'anisotropic');
if isAnisotropic
    if nargin < 3
        error('ipm:MissingAnisotropicScale', ...
            ['Anisotropic dynamic scaling requires the current scale so ' ...
            'every stage uses its own aspect ratio.']);
    end
    aspect = exp(scale.logC_y-scale.logC_l);
else
    aspect = 1;
end

[u1,u2,psi,source,poissonResidual,poissonSolveInfo] = ...
    ipm.field.velocity(rho,ops,aspect);
physicalFlow = struct('u1',u1,'u2',u2,'psi',psi,'source',source, ...
    'poissonResidual',poissonResidual, ...
    'poissonSolveInfo',poissonSolveInfo);
% Most exact dynamic gauges assemble their own rescaled transport below and
% never consume the unscaled transport RHS.  Avoid paying for that second
% WENO evaluation unless the physical evolution or a width/peak-rate gauge
% explicitly needs it.  This is a lazy evaluation only: the algebraic gauge
% definitions, canonical clock, CFL rate, and returned RHS are unchanged.
needsPhysicalRhs = ~ops.rescaling.enabled || ...
    (~isAnisotropic && any(strcmp(ops.rescaling.lengthGauge, ...
        {'omega_peak_location','wall_omega_width'}))) || ...
    (~isAnisotropic && ops.rescaling.enabled && ...
        isfield(ops.rescaling,'travelingWaveGauge') && ...
        strcmp(ops.rescaling.travelingWaveGauge,'gradient_peak') && ...
        ~strcmp(ops.rescaling.lengthGauge,'wall_gradient_curvature'));
if needsPhysicalRhs
    [physicalRhs,~,~,~] = ipm.evolve.assembleRhs( ...
        rho,u1,u2,0,0,0,0,ops,ops.transportBoundaryMode);
else
    physicalRhs = [];
end

if isAnisotropic
    [rates,baseRhs,details,transportU1,transportU2,extras] = ...
        ipm.evolve.anisotropicGauge(rho,physicalRhs,physicalFlow,ops);
    rateVector = [rates.cx,rates.cy,rates.comega,rates.cr];
else
    details = ipm.diagnostics.trackFeatures(rho,physicalRhs,physicalFlow,ops);
    [cL,cOmega,cR,baseRhs,details,transportU1,transportU2] = ...
        ipm.evolve.isotropicGauge( ...
        rho,physicalRhs,physicalFlow,ops,details);
    rates = struct('cx',cL,'cy',cL,'comega',cOmega,'cr',cR, ...
        'conservativeSource',2*cL+cOmega);
    rateVector = [cL,cOmega,cR];
    extras = struct();
end

if ops.rescaling.enabled
    translationScale = max(abs(ops.rescaling.pinX),1);
else
    translationScale = 1;
end
[rateMagnitude,~] = ipm.evolve.rateMagnitude( ...
    rateVector,translationScale);
% Canonical tau is the integration clock.  There is deliberately no
% state-dependent rate cap or auxiliary time reparameterization.
rhs = baseRhs+rates.comega*rho;

flow = common_flow(physicalFlow,details,rates, ...
    rateMagnitude,transportU1,transportU2,aspect);
if isAnisotropic
    flow.anisotropicGaugeMode = extras.mode;
    flow.peakTranslationResidual = extras.peakTranslationResidual;
    flow.peakTranslationRawVelocity = extras.peakTranslationRawVelocity;
    flow.peakTranslationTargetVelocity = ...
        extras.peakTranslationTargetVelocity;
    flow.canonicalPeakTranslationTargetVelocity = ...
        extras.peakTranslationTargetVelocity;
end
end

function flow = common_flow(physical,details,rates, ...
        rateMagnitude,transportU1,transportU2,aspect)
