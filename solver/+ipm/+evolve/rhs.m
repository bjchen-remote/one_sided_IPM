flow.aspect = aspect;
flow.c_l = rates.cx;
flow.c_x = rates.cx;
flow.c_y = rates.cy;
flow.c_omega = rates.comega;
flow.c_r = rates.cr;
flow.canonicalCL = rates.cx;
flow.canonicalCX = rates.cx;
flow.canonicalCY = rates.cy;
flow.canonicalCOmega = rates.comega;
flow.canonicalCR = rates.cr;
% Retained only so result-v2 readers can verify the removed clock factor.
flow.timeSpeed = 1;
flow.canonicalRateMagnitude = rateMagnitude;
flow.conservativeSource = rates.conservativeSource;
flow.canonicalConservativeSource = rates.conservativeSource;
flow.aspectRate = rates.cy-rates.cx;
flow.canonicalAspectRate = rates.cy-rates.cx;
flow.transportU1 = transportU1;
flow.transportU2 = transportU2;

flow.c_lNominal = details.c_lNominal;
flow.canonicalCLNominal = details.c_lNominal;
flow.lengthScaleGain = details.lengthScaleGain;
flow.widthCorrection = details.widthCorrection;
flow.canonicalWidthCorrection = details.widthCorrection;
flow.widthRateScale = details.widthRateScale;
flow.widthControlMode = details.widthControlMode;

copyNames = {'peakGridPoints','supportGridPoints','coreGridPoints', ...
    'verticalPeakGridPoints','verticalSupportGridPoints', ...
    'verticalCoreGridPoints','targetPeakGridPoints', ...
    'targetSupportGridPoints','targetCoreGridPoints', ...
    'peakExpansionRatio','resolutionFactor','safetyFactor', ...
    'trackedWallPeak','trackedWallPeakWidth','trackedWallCoreWidth', ...
    'rhoXInf', ...
    'trackedVerticalPeakWidth','trackedVerticalCoreWidth', ...
    'strain','strainError','strainCondition','omegaGaugeEnergy', ...
    'omegaGaugeEnergyX','omegaGaugeEnergyY', ...
    'omegaGaugeForcingX','omegaGaugeForcingY', ...
    'omegaGaugeForcing','omegaGaugeAbsoluteForcing', ...
    'omegaGaugeForcingCancellationRatio', ...
    'omegaGaugeResidual','omegaGaugePeakX','omegaGaugePeakCondition', ...
    'omegaGaugeQuadraticPeakX','omegaGaugeQuadraticPeakValue', ...
    'omegaGaugeQuadraticForcing', ...
    'omegaGaugeQuadraticCurvature', ...
    'omegaGaugeQuadraticStationarityResidual', ...
    'omegaGaugeQuadraticNormalizedStationarityResidual', ...
    'omegaGaugeQuadraticCurvatureCondition', ...
    'omegaGaugeQuadraticWeightCondition', ...
    'omegaGaugeQuadraticActiveNodeMargin', ...
    'omegaGaugeQuadraticActiveSelectionMargin', ...
    'omegaGaugeQuadraticStencilCenterX', ...
    'omegaGaugeQuadraticVertexInteriorFraction', ...
    'omegaGaugeQuadraticRelativeSubgridLift', ...
    'omegaGaugeQuadraticRateScale', ...
    'omegaGaugeAnchorX','omegaGaugeAnchorValue', ...
    'omegaGaugeAnchorCondition','omegaGaugeReferenceAnchorValue', ...
    'omegaGaugeWindowCenter','omegaGaugeWindowRadius', ...
    'omegaGaugeWindowValue','omegaGaugeWindowCondition', ...
    'omegaGaugeWindowEnergy','omegaGaugeReferenceWindowValue', ...
    'omegaGaugeWindowMomentOrder','omegaGaugeWindowMoment', ...
    'omegaGaugeWindowSupportPoints','omegaGaugeWindowRateScale', ...
    'omegaGaugeTemplateCenter','omegaGaugeTemplateRadius', ...
    'omegaGaugeTemplateSupportPoints','omegaGaugeTemplateValue', ...
    'omegaGaugeTemplateCondition','omegaGaugeTemplateRateScale', ...
