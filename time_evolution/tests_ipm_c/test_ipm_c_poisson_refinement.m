function report=test_ipm_c_poisson_refinement(options)
%TEST_IPM_C_POISSON_REFINEMENT Mixed smooth Cartesian Poisson manufactures.
% Production defaults are unchanged. The existing manufactured=true,
% outerPsi option supplies the EXACT Dirichlet trace at finite R, isolating
% radial/sine/pole errors from Green quadrature and domain truncation.
% An anisotropic Gaussian case has a nontrivial remaining angular solve
% after the nonzero-wall-source lift. No time integration or native F call.
if nargin<1,options=struct();end
counts=[65,129,257];radius=4;alpha=3;includeGreen=false;
if isfield(options,'counts'),counts=options.counts;end
if isfield(options,'includeGreen'),includeGreen=options.includeGreen;end
assert(numel(counts)==3&&all(counts>=17)&&all(diff(counts)>0), ...
    'polar:PoissonRefinementCounts','Supply three increasing tensor counts.');
assert(counts(2)==2*(counts(1)-1)+1&&counts(3)==2*(counts(2)-1)+1, ...
    'polar:PoissonRefinementCounts','Use nested factor-two tensor levels.');
cases=[1,1.7];caseNames={'isotropic_mixed_gaussian','anisotropic_mixed_gaussian'};
errors=zeros(2,3,4);records=cell(2,3);
rawOptions=struct('poleRegularization',false);
for level=1:3
    n=counts(level);h=radius*sinh(alpha/(n-1))/sinh(alpha);
    g=ipm_c.mesh.build(struct('nr',n,'ntheta',n,'rmax',radius,'firstSpacing',h));
    first=false(n,n);first(2,:)=true;near=false(n,n);near(1:5,:)=true;
    for k=1:2
        exact=manufacture(g.X,g.Y,cases(k));
        [f,info]=ipm_c_legacy_fixture('poisson',exact.source,g, ...
            struct('manufactured',true,'outerPsi',exact.psi(end,:)));
        du1=ipm_c.field.derivatives(f.u1,g,rawOptions);du2=ipm_c.field.derivatives(f.u2,g,rawOptions);
        eu=max(abs(f.u1-exact.u1),abs(f.u2-exact.u2));
        ed=max(abs(du1.rx-exact.u1x),abs(du2.rx-exact.u2x));
        % Derivative-of-error removes the shared postprocessor truncation
        % from this diagnostic; total derivative error above remains public.
        de1=ipm_c.field.derivatives(f.u1-exact.u1,g,rawOptions);
        de2=ipm_c.field.derivatives(f.u2-exact.u2,g,rawOptions);
        derivativeOfError=max(abs(de1.rx),abs(de2.rx));
        A=sin(g.theta).^2.*(1+cos(g.theta))/4;
        B=sin(g.theta).^2.*(1-cos(g.theta))/4;A([1,end])=0;B([1,end])=0;
        lift=(-g.r.^2.*exact.source(:,1))*A+(-g.r.^2.*exact.source(:,end))*B;
        remainder=f.psi-lift;S=sin(g.theta(2:end-1)'*(1:n-2));
        modes=remainder(:,2:end-1)*S*(2/(n-1));
        slopes=g.Dr(1,:)*modes;
        nontrivial=max(abs(exact.psi-lift),[],'all');
        assert(nontrivial>.01,'polar:NontrivialPoissonRemainder', ...
            'This manufacture must exercise the sine residual solve, not only the analytic lift.');
        rec=struct('name',caseNames{k},'betaY',cases(k),'nr',n,'ntheta',n, ...
            'firstSpacing',h,'exactSourceAtOrigin',exact.source(1,1), ...
            'exactResidualPsiInfinity',nontrivial,'poisson',info, ...
            'psiError',maximum(abs(f.psi-exact.psi),g,true(n)), ...
            'velocityError',maximum(eu,g,true(n)), ...
            'firstRingVelocityError',maximum(eu,g,first), ...
            'originAndFirstFourVelocityError',maximum(eu,g,near), ...
            'velocityXDerivativeError',maximum(ed,g,true(n)), ...
            'firstRingVelocityXDerivativeError',maximum(ed,g,first), ...
            'originAndFirstFourVelocityXDerivativeError',maximum(ed,g,near), ...
            'derivativeOfVelocityError',maximum(derivativeOfError,g,true(n)), ...
            'firstRingDerivativeOfVelocityError',maximum(derivativeOfError,g,first), ...
            'originU1Error',abs(f.u1(1,1)+1), ...
            'higherModeOriginSlopeLeakInfinity',max(abs(slopes(2:end))), ...
            'higherModeFirstRingPsiOverRadiusInfinity',max(abs(modes(2,2:end)))/g.r(2), ...
            'sourceWallTraceNonzero',max(abs(exact.source(:,[1,end])),[],'all')>0, ...
            'postprocessor','unregularized Cartesian chain rule; no experimental pole jet');
        errors(k,level,:)=[rec.velocityError.infinity,rec.firstRingVelocityError.infinity, ...
            rec.velocityXDerivativeError.infinity,rec.firstRingVelocityXDerivativeError.infinity];
        records{k,level}=rec;
    end
end
convergence=cell(1,2);passed=true;
for k=1:2
    e=reshape(errors(k,:,:),3,4);ratios=e(2:3,:)./max(e(1:2,:),realmin);
    metricPassed=(e(3,:)<=.75*e(2,:)) | e(3,:)<1e-10;
    passed=passed&&all(metricPassed);
    convergence{k}=struct('name',caseNames{k}, ...
        'metricOrder',{{'fullVelocity','firstRingVelocity','fullVelocityXDerivative','firstRingVelocityXDerivative'}}, ...
        'absoluteErrors',e,'successiveErrorRatios',ratios, ...
        'finestConvergencePassed',metricPassed,'passed',all(metricPassed));
end
report=struct('kind','mixed_Cartesian_polar_poisson_spatial_refinement_v1', ...
    'passed',passed,'records',{records},'convergence',{convergence}, ...
    'exactManufacturedDirichletTraceUsed',true,'productionBoundaryDefaultsChanged',false, ...
    'nativePdeCalls',0,'actualTrajectoryAdvanced',false,'stationaryQGateUsed',false, ...
    'uniformPhysicalRadius',radius,'fixedSinhParameter',alpha, ...
    'interpretation','Manufactured Poisson spatial convergence only; no native trajectory qualification.');
if includeGreen
    report.greenQuadratureScreen=green_screen(counts,alpha);
end
end

function report=green_screen(counts,alpha)
% Separate R=8 production-Green screen. Gaussian tails beyond R are tiny;
% remaining error includes polar source quadrature and angular compression.
radius=8;records=cell(1,3);
for level=1:3
    n=counts(level);h=radius*sinh(alpha/(n-1))/sinh(alpha);
    g=ipm_c.mesh.build(struct('nr',n,'ntheta',n,'rmax',radius,'firstSpacing',h));
    exact=manufacture(g.X,g.Y,1.7);
    [f,info]=ipm_c_legacy_fixture('poisson',exact.source,g,struct('greenSourceTolerance',1e-14,'greenMaxSources',1e6));
    du1=ipm_c.field.derivatives(f.u1,g,struct('poleRegularization',false));
    du2=ipm_c.field.derivatives(f.u2,g,struct('poleRegularization',false));
    records{level}=struct('nr',n,'ntheta',n,'poisson',info, ...
        'outerTraceError',max(abs(f.psi(end,:)-exact.psi(end,:))), ...
        'fullVelocityError',max([abs(f.u1-exact.u1),abs(f.u2-exact.u2)],[],'all'), ...
        'firstRingVelocityError',max([abs(f.u1(2,:)-exact.u1(2,:)),abs(f.u2(2,:)-exact.u2(2,:))]), ...
        'fullVelocityXDerivativeError',max([abs(du1.rx-exact.u1x),abs(du2.rx-exact.u2x)],[],'all'));
end
report=struct('radius',radius,'records',{records},'exactBoundaryOverrideUsed',false, ...
    'qualificationClaimed',false,'maximumGaussianEnvelopeBeyondRadius',exp(-radius^2), ...
    'compressionDisabledByCap',true,'sourceThresholdRetained',1e-14);
end

function e=manufacture(X,Y,beta)
P=Y+.2*X.*Y+.3*Y.^2+.1*X.^2.*Y;
Px=.2*Y+.2*X.*Y;Py=1+.2*X+.6*Y+.1*X.^2;
Pxx=.2*Y;Pxy=.2+.2*X;Pyy=.6*ones(size(X));
E=exp(-(X.^2+beta*Y.^2));
source=-E.*(Pxx+Pyy-4*(X.*Px+beta*Y.*Py)+ ...
    (4*X.^2+4*beta^2*Y.^2-2-2*beta).*P);
e=struct('psi',P.*E,'source',source, ...
    'u1',-E.*(Py-2*beta*Y.*P),'u2',E.*(Px-2*X.*P), ...
    'u1x',-E.*(Pxy-2*beta*Y.*Px-2*X.*Py+4*beta*X.*Y.*P), ...
    'u2x',E.*(Pxx-4*X.*Px+(4*X.^2-2).*P));
end

function p=maximum(value,g,mask)
indices=find(mask);[m,k]=max(value(mask));index=indices(k);
[i,j]=ind2sub(size(value),index);
p=struct('infinity',m,'radialIndex',i,'angularIndex',j,'r',g.r(i), ...
    'theta',g.theta(j),'X',g.X(i,j),'Y',g.Y(i,j));
end
