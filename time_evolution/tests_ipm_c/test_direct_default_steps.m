function report=test_direct_default_steps()
%TEST_DIRECT_DEFAULT_STEPS Measure ten CFL-selected steps on the default grid.
cfg=ipm_c.config();cfg.targetTau=1;cfg.time.finalTime=1;cfg.runtime.threads=1;
cfg.output.verbose=false;
threadCount=maxNumCompThreads(1);cleanup=onCleanup(@()maxNumCompThreads(threadCount)); %#ok<NASGU>
setup=tic;[state,~]=ipm_c.initialize(cfg);setupSeconds=toc(setup);
records=cell(1,10);geometry=state.ops.spatialGeometryKey;
assert(~isfield(state.ops,'timeIntegrationContract')&& ...
    ~isfield(state.ops.spatialOperators,'preconditioner'));
for k=1:numel(records)
    timer=tic;[state,reason]=ipm_c.evolve.advance(state);elapsed=toc(timer);
    assert(isempty(reason)&&state.step==k&&strcmp(state.timeStep.activeLimiter,'cfl'), ...
        'ipm_c:DirectDefaultStep');
    assert(abs(state.timeStep.dt*state.timeStep.rate-cfg.time.cfl)<1e-12&& ...
        isequaln(state.ops.spatialGeometryKey,geometry)&&state.ops.remeshCount==0, ...
        'ipm_c:DirectDefaultCfl');
    records{k}=struct('step',k,'tau',state.scale.canonicalTime, ...
        'dt',state.timeStep.dt,'seconds',elapsed,'timeStep',state.timeStep);
end
times=cellfun(@(r)r.seconds,records);steps=cellfun(@(r)r.dt,records);
report=struct('kind','default_polar_grid_direct_cfl_ten_steps_v3','passed',true, ...
    'nr',cfg.grid.nr,'ntheta',cfg.grid.ntheta,'independentDofs',1+(cfg.grid.nr-1)*cfg.grid.ntheta, ...
    'steps',numel(records),'canonicalTime',state.scale.canonicalTime, ...
    'physicalTime',state.scale.physicalTime,'minimumStep',min(steps),'maximumStep',max(steps), ...
    'totalAdvanceSeconds',sum(times),'meanAdvanceSeconds',mean(times), ...
    'medianAdvanceSeconds',median(times),'initializationSeconds',setupSeconds, ...
    'records',{records},'threads',1,'automaticRemeshPreserved',true,'remeshCount',state.ops.remeshCount,'stepRetries',0, ...
    'implicitSolves',0,'fullQ',max(abs(state.flow.fullQ),[],'all'), ...
    'trajectoryQualificationClaimed',false);
end
