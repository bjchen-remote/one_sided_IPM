function report=test_uniform_core_mesh(cfg)
%TEST_UNIFORM_CORE_MESH Domain, core spacing, adaptive transfer and LU reuse.
if nargin<1,cfg=ipm_c.config();end
cfg.runtime.threads=1;cfg.output.verbose=false;
[state,~]=ipm_c.initialize(cfg);g=state.ops.polarGrid;h=cfg.grid.firstSpacing;
assert(strcmp(g.radialMap,'uniform_core')&&g.r(end)==1e10&&g.r(1)==0&&g.r(2)==h);
gap=diff(g.r);core=gap(g.r(2:end)<=cfg.grid.coreRadius);
assert(min(core)>=h*(1-1e-12)&&max(core)/min(core)<1.1&& ...
    numel(core)<=ceil(cfg.grid.coreRadius/h)&&g.originFit.degree==6, ...
    'ipm_c:UniformCoreSpacing','The core must stay near uniform without gaps smaller than its declared spacing.');
% Growing complete-source envelopes must reserve a smooth outer tail rather
% than drive the old fixed-spacing map into its 11.52-radius hard limit.
growingCore=struct([]);
for radius=[12,20,100]
    settings=struct('nr',385,'ntheta',128,'rmax',1e10,'firstSpacing',.03, ...
        'radialMap','uniform_core','coreRadius',radius,'coreTailFraction',.01);
    [axis,axisInfo]=ipm_c.mesh.uniformCoreAxis(settings);
    gaps=diff(axis);coreGaps=gaps(axis(2:end)<=radius);
    assert(axis(1)==0&&axis(end)==1e10&&axis(2)>=.03&& ...
        axisInfo.requestedFirstSpacing==.03&&axisInfo.firstSpacingAdjusted&& ...
        axisInfo.positiveCoreNodeFraction<=.6&&axisInfo.tailIntervalCount>=.4*384&& ...
        axisInfo.maximumAdjacentGapRatio<1.3&& ...
        min(coreGaps)>=axis(2)*(1-1e-10)&&max(coreGaps)/min(coreGaps)<1.3, ...
        'ipm_c:UniformCoreTailAllocation','Growing cores must retain uniform spacing and enough tail intervals.');
    if radius==12
        growingGrid=ipm_c.mesh.build(settings);
        assert(isequal(growingGrid.r,axis)&&growingGrid.firstSpacing==axis(2), ...
            'ipm_c:UniformCoreBuildSpacing','The geometry builder must retain the selected first spacing.');
    end
    growingCore=append_record(growingCore,axisInfo);
end
rows=g.originFit.rows;X=g.X(rows,:);Y=g.Y(rows,:);
v=.3*X-.2*Y+.11*X.^2+.07*X.*Y+.013*X.^5-.004*Y.^6;
coefficients=g.originFit.map*v(:);
originError=abs(coefficients(1)/g.originFit.scale-.3);
assert(originError<1e-10,'ipm_c:UniformCoreOriginPolynomial');
exact=ipm_c_legacy_fixture('background',cfg.physics,g.X,g.Y,state.scale);
sourceError=max(abs(state.flow.source(g.R<=2)-exact.rx(g.R<=2)));
assert(sourceError<1e-7,'ipm_c:UniformCoreAnalyticSource');
features=ipm_c.diagnostics.sourceFeatures(state.flow.source,g,[.1,.2,.5]);
% A lower configured floor exercises a genuinely changed peak-driven axis;
% a growing low-amplitude tail alone need not change an adequate core.
state.ops.polarCfg.grid.coreRadius=1;state.config.grid.coreRadius=1;
state.ops.rescaling.referenceLevelSetAreas=features.areas/1.3;
state.ops.rescaling.referenceLevelSetRadialBounds=features.radialProjectionBounds;
% Force only the area observer; the real source-driven proposal is unchanged.
[adapted,info]=ipm_c.remesh.apply(state);
assert(info.requested&&info.applied&&info.geometryChanged&& ...
    adapted.ops.remeshCount==1&&adapted.ops.polarGrid.r(end)==1e10&& ...
    adapted.ops.polarGrid.r(2)>=h&&isequaln(adapted.scale,state.scale), ...
    'ipm_c:UniformCoreAutomaticRemesh','The actual source-driven proposal must commit without changing time.');
newGrid=adapted.ops.polarGrid;
radius=min(cfg.grid.coreRadius,info.proposal.uniformCoreInfo.coreRadius);
newGap=diff(newGrid.r);newCore=newGap(newGrid.r(2:end)<=radius);
assert(max(newCore)/min(newCore)<1.15&&min(newCore)>=h*(1-1e-10), ...
    'ipm_c:UniformCoreAdaptiveSpacing');
assert(adapted.flow.poissonSolveInfo.factorCacheRebuilt,'ipm_c:UniformCoreFactorRebuild');
[~,warm]=ipm.evolve.flow(adapted.rho,adapted.ops,adapted.scale);
assert(~warm.poissonSolveInfo.factorCacheRebuilt&& ...
    isequaln(warm.psi,adapted.flow.psi)&&isequaln(warm.u1,adapted.flow.u1)&& ...
    isequaln(warm.u2,adapted.flow.u2),'ipm_c:UniformCoreFactorReuse');
report=struct('kind','uniform_core_geometry_source_adaptive_transfer_cache_v1', ...
    'passed',true,'rEnd',g.r(end),'firstSpacing',h,'coreRadius',cfg.grid.coreRadius, ...
    'corePositiveNodeCount',numel(core),'minimumCoreGap',min(core),'maximumCoreGap',max(core), ...
    'coreGapRatio',max(core)/min(core),'originPolynomialDerivativeError',originError, ...
    'analyticSourceCoreError',sourceError,'realAdaptiveProposal',info, ...
    'growingCoreAllocation',growingCore, ...
    'adaptiveCoreGapRatio',max(newCore)/min(newCore), ...
    'changedGeometryFactorsRebuilt',true,'unchangedGeometryFactorsReused',true, ...
    'areaTriggerExplicitlyForced',true,'timeAdvanced',0,'longTrajectoryQualified',false);
end

function records=append_record(records,row)
if isempty(records),records=row;else,records(end+1)=row;end
end
