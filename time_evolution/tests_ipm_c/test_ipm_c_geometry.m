function report = test_ipm_c_geometry()
%TEST_IPM_C_GEOMETRY Manufactured geometry checks; no native PDE/Poisson.
% Covers coordinate identities, the Cartesian origin jet, and the signed wall.
defaults=ipm_c.mesh.build();
assert(defaults.nr==129&&defaults.ntheta==129&&defaults.rmax==1e10);
assert(defaults.r(1)==0&&defaults.r(2)==.02&&defaults.r(end)==1e10);
assert(strcmp(defaults.radialMap,'sinh')&&defaults.signedWallMapSmoothAtOrigin, ...
    'polar:DefaultRadialMap','The default radial map must have a smooth odd signed-wall continuation.');
assert(all(defaults.Y(:,[1,end])==0,'all'));
assert(all(defaults.X(:,1)==defaults.r)&&all(defaults.X(:,end)==-defaults.r));
assert(all(diff(defaults.r)>0)&&defaults.originIsSinglePhysicalPoint);
assert(defaults.originFit.degree==4&&numel(defaults.originFit.rows)==4&& ...
    size(defaults.originFit.map,1)==14, ...
    'polar:OriginFitDegree','The shared-origin closure must contain all degree-one through degree-four Cartesian terms.');
grid=ipm_c.mesh.build(struct('nr',41,'ntheta',129,'rmax',4,'firstSpacing',.02));
X=grid.X;Y=grid.Y;zero=zeros(size(X));one=ones(size(X));
cases={ ...
    struct('name','constant','f',3.25*one,'gx',zero,'gy',zero,'lap',zero), ...
    struct('name','linear_x','f',X,'gx',one,'gy',zero,'lap',zero), ...
    struct('name','linear_y','f',Y,'gx',zero,'gy',one,'lap',zero), ...
    struct('name','quadratic_x_squared','f',X.^2,'gx',2*X,'gy',zero,'lap',2*one), ...
    struct('name','quadratic_xy','f',X.*Y,'gx',Y,'gy',X,'lap',zero), ...
    struct('name','quadratic_y_squared','f',Y.^2,'gx',zero,'gy',2*Y,'lap',2*one), ...
    struct('name','general_cartesian_quadratic', ...
        'f',3+2*X-.75*Y+.4*X.^2-.3*X.*Y+.6*Y.^2, ...
        'gx',2+.8*X-.3*Y,'gy',-.75-.3*X+1.2*Y,'lap',2*one), ...
    struct('name','wall_streamfunction_y_times_one_plus_x', ...
        'f',Y.*(1+X),'gx',Y,'gy',1+X,'lap',zero)};
gradientTolerance=2e-6;laplaceTolerance=2e-5;originTolerance=2e-10;
records=cell(size(cases));
for k=1:numel(cases)
    exact=cases{k};d=ipm_c.field.derivatives(exact.f,grid, ...
        struct('computeLaplacian',true,'poleRegularization',false));
    radialExact=exact.gx.*grid.cosTheta+exact.gy.*grid.sinTheta;
    thetaExact=-Y.*exact.gx+X.*exact.gy;
    errors=struct('rx',relative_max(d.rx,exact.gx),'ry',relative_max(d.ry,exact.gy), ...
        'radial',relative_max(d.rr,radialExact),'theta',relative_max(d.theta,thetaExact), ...
        'laplace',relative_max(d.laplace,exact.lap), ...
        'originRx',abs(d.origin.rx-exact.gx(1,1)), ...
        'originRy',abs(d.origin.ry-exact.gy(1,1)), ...
        'originLaplace',abs(d.origin.laplace-exact.lap(1,1)));
    assert(max([errors.rx,errors.ry,errors.radial,errors.theta])<gradientTolerance, ...
        'polar:ManufacturedGradient','Gradient manufacture failed: %s.',exact.name);
    assert(errors.laplace<laplaceTolerance,'polar:ManufacturedLaplacian', ...
        'Laplacian manufacture failed: %s.',exact.name);
    assert(max([errors.originRx,errors.originRy,errors.originLaplace])<originTolerance, ...
        'polar:ManufacturedOrigin','Cartesian origin closure failed: %s.',exact.name);
    assert(all(d.rx(1,:)==d.origin.rx)&&all(d.ry(1,:)==d.origin.ry));
    assert(all(d.theta(1,:)==0)&&all(d.laplace(1,:)==d.origin.laplace));
    records{k}=struct('name',exact.name,'passed',true,'errors',errors);
end
% Higher-degree manufactures test only the origin derivative jet.  The
% angular finite-difference error away from zero is a separate requirement.
cubic=.25*X.^3-.5*X.^2.*Y+.2*X.*Y.^2-.15*Y.^3;
quartic=.1*X.^4-.2*X.^3.*Y+.3*X.^2.*Y.^2-.4*X.*Y.^3+.5*Y.^4;
low=2*X-.75*Y+.4*X.^2-.3*X.*Y+.6*Y.^2;
jetCases={ ...
    struct('name','general_cartesian_cubic_origin_jet','f',low+cubic, ...
        'jet',[2,-.75,.8,-.3,1.2]), ...
    struct('name','general_cartesian_quartic_origin_jet','f',low+cubic+quartic, ...
        'jet',[2,-.75,.8,-.3,1.2]), ...
    struct('name','poisson_cubic_y_times_one_minus_radius_squared_origin_jet', ...
        'f',Y.*(1-X.^2-Y.^2),'jet',[0,1,0,0,0])};
jetRecords=cell(size(jetCases));
for k=1:numel(jetCases)
    exact=jetCases{k};d=ipm_c.field.derivatives(exact.f,grid,struct('poleRegularization',false));
    actual=[d.origin.rx,d.origin.ry,d.origin.xx,d.origin.xy,d.origin.yy];
    jetError=max(abs(actual-exact.jet));
    assert(jetError<originTolerance,'polar:ManufacturedHigherOrigin', ...
        'Cartesian degree-four origin jet failed: %s.',exact.name);
    jetRecords{k}=struct('name',exact.name,'passed',true, ...
        'expectedJet',exact.jet,'actualJet',actual,'maximumJetError',jetError);
end
linear=ipm_c.field.derivatives(X,grid,struct('poleRegularization',false));
assert(abs(linear.rr(1,1)-1)<originTolerance&& ...
    abs(linear.rr(1,end)+1)<originTolerance, ...
    'polar:OriginRadialSlope','The shared origin must retain a nonzero Cartesian x slope.');
assert(~isfield(linear,'laplace'),'polar:OptionalLaplacian','The Laplacian is opt-in.');
bad=X;bad(1,2)=1;
must_fail(@()ipm_c.field.derivatives(bad,grid),'polar:OriginValueMismatch');
must_fail(@()ipm_c.mesh.build(struct('domain','rectangle')),'polar:RectangleDomainNotImplemented');
wallGeometry=sinh_wall_checks();
report=struct('kind','polar_geometry_manufactured_tests_v1','passed',true, ...
    'nativePdeCalls',0,'poissonCalls',0,'manufactures',{records}, ...
    'scope','unregularized coordinate geometry; production pole partition has separate spatial tests', ...
    'originFitDegree',4,'higherDegreeOriginJetManufactures',{jetRecords}, ...
    'gradientTolerance',gradientTolerance,'laplaceTolerance',laplaceTolerance, ...
    'originTolerance',originTolerance,'rectangleUnsupportedGuardPassed',true, ...
    'singleOriginGuardPassed',true,'originNonzeroCartesianSlopePassed',true, ...
    'signedSinhWall',wallGeometry);
end

function error=relative_max(actual,reference)
error=max(abs(actual-reference)./max(1,abs(reference)),[],'all');
end

function must_fail(callback,expectedIdentifier)
caught=false;
try
    callback();
catch exception
    caught=strcmp(exception.identifier,expectedIdentifier);
    if ~caught,rethrow(exception);end
end
assert(caught,'polar:ExpectedFailure','Expected guard %s did not reject.',expectedIdentifier);
end

function report=sinh_wall_checks()
% Hold the analytic signed map X(s)=R*sinh(alpha*s)/sinh(alpha) fixed while
% refining its logical axis.  Changing ntheta cannot change this 1D wall
% geometry or either signed-unit WENO result at the shared origin.
radialCounts=[33,65,129];angularCounts=[17,65];radius=4;alpha=3;
records=cell(numel(radialCounts),numel(angularCounts));
errors=zeros(size(radialCounts));
for level=1:numel(radialCounts)
    nr=radialCounts(level);first=radius*sinh(alpha/(nr-1))/sinh(alpha);
    previous=[];
    for angularIndex=1:numel(angularCounts)
        g=ipm_c.mesh.build(struct('nr',nr,'ntheta',angularCounts(angularIndex), ...
            'rmax',radius,'firstSpacing',first,'radialMap','sinh'));
        x=[-flipud(g.r(2:end));g.r]';logical=linspace(-1,1,numel(x));
        J=(ipm.mesh.fdMatrix(logical,1,7)*x')';
        Jsecond=(ipm.mesh.fdMatrix(logical,2,7)*x')';
        near=nr+(-3:3);
        exactX=radius*sinh(alpha*logical)/sinh(alpha);
        exactJ=radius*alpha*cosh(alpha*logical)/sinh(alpha);
        exactSecond=radius*alpha^2*sinh(alpha*logical)/sinh(alpha);
        axisError=relative_max(x,exactX);
        evenMetricError=relative_max(J,fliplr(J));
        nearMetricError=max(abs(J(near)-exactJ(near)));
        nearSecondError=max(abs(Jsecond(near)-exactSecond(near)));
        assert(axisError<1e-12&&evenMetricError<1e-10&&all(J>0), ...
            'polar:SignedWallSmoothMetric','The signed sinh wall must be odd with a positive even metric.');
        assert(nearMetricError<2e-6&&nearSecondError<2e-5, ...
            'polar:SignedWallSmoothOrigin','The signed metric and second derivative must resolve the smooth origin.');
        opts=struct('lowerBoundary','extrapolate','upperBoundary','extrapolate', ...
            'extrapolationDegree',5,'inflowDensityDegree',5, ...
            'epsilon',1e-12,'alphaMode','local', ...
            'physicalLowerInflow',false,'physicalUpperInflow',false);
        positive=ipm.field.weno5FluxDerivative(x,ones(size(x)),1,1/(nr-1),opts)./J;
        negative=-ipm.field.weno5FluxDerivative(x,-ones(size(x)),1,1/(nr-1),opts)./J;
        nearError=max([abs(positive(near)-1),abs(negative(near)-1)]);
        current=[x;J;positive;negative];
        if angularIndex>1
            assert(isequaln(current,previous),'polar:WallThetaIndependence', ...
                'The signed-wall unit-speed WENO result must be independent of angular node count.');
        end
        previous=current;errors(level)=max(errors(level),nearError);
        records{level,angularIndex}=struct('nr',nr,'ntheta',g.ntheta, ...
            'axisError',axisError,'evenMetricError',evenMetricError, ...
            'nearOriginMetricError',nearMetricError,'nearOriginSecondError',nearSecondError, ...
            'nearOriginBothSignedUnitWenoError',nearError);
    end
end
assert(errors(end)<2e-6&&errors(end)<max(errors(1)/4,1e-11), ...
    'polar:WallWenoRefinement','Refining the smooth signed wall must improve its near-origin linear-X WENO derivative.');
legacy=ipm_c.mesh.build(struct('nr',33,'ntheta',17,'rmax',4,'firstSpacing',.02,'radialMap','exp_gaps'));
assert(strcmp(legacy.radialMap,'exp_gaps')&&~legacy.signedWallMapSmoothAtOrigin);
report=struct('radialMap','sinh','records',{records}, ...
    'signedUnitWenoNearOriginErrors',errors,'angularNodeCountIndependencePassed',true, ...
    'smoothOddSignedMapPassed',true,'explicitHistoricalExpGapsPreserved',true);
end
