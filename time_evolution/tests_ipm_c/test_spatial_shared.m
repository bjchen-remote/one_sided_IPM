function report=test_spatial_shared()
%TEST_SPATIAL_SHARED Total-rho derivatives and cached direct polar Poisson.
[g,cart,rho]=ipm_c_test_fixture(17);cfg=ipm_c.config();
cfg.physics=cart.originalMetadata.config.physics;cfg.grid=struct();
ops=ipm_c.spatial.build(cfg,cart,g);
f=.3+2*g.X-.4*g.Y+.2*g.X.^2+.13*g.X.*g.Y+.05*g.Y.^2+ ...
    .004*g.X.^3-.006*g.Y.^3;
exact=2+.4*g.X+.13*g.Y+.012*g.X.^2;
actual=ops.spatialOperators.derivativeX(f);
derivativeError=max(abs(actual-exact),[],'all');
originDerivativeError=max(abs(actual(1,:)-exact(1,:)));
% Cartesian polynomials contain angular trigonometric modes. Seven-point
% angular finite differences converge on them; only the origin jet is exact.
fine=ipm_c.mesh.build(struct('nr',g.nr,'ntheta',129,'rmax',g.rmax,'firstSpacing',g.r(2)));
ff=.3+2*fine.X-.4*fine.Y+.2*fine.X.^2+.13*fine.X.*fine.Y+.05*fine.Y.^2+ ...
    .004*fine.X.^3-.006*fine.Y.^3;
fineExact=2+.4*fine.X+.13*fine.Y+.012*fine.X.^2;
fineDerivatives=ipm_c.field.derivatives(ff,fine,cfg.rhsOptions);fineActual=fineDerivatives.rx;
fineDerivativeError=max(abs(fineActual-fineExact),[],'all');
assert(originDerivativeError<1e-10&&fineDerivativeError<2e-6&& ...
    fineDerivativeError<derivativeError/100,'ipm_c:SharedSpatialDerivative');
assert(~isfield(ops.spatialOperators,'pack')&&~isfield(ops.spatialOperators,'unpack'), ...
    'ipm_c:DirectNoImplicitPacking');
bad=f;bad(1,end)=bad(1,end)+1;caught=false;
try,ops.spatialOperators.derivativeX(bad);catch err,caught=strcmp(err.identifier,'polar:OriginValueMismatch');end
assert(caught,'ipm_c:SharedSpatialOriginRejected');
assert(~isfield(ops.spatialOperators,'preconditioner'),'ipm_c:DirectNoPreconditioner');
n=ops.independentDofCount;
% The complete rescaled autonomous equation depends on total rho and its
% solved gauge, not the separately integrated scale or either clock.
[F0,flow0,info0]=ops.spatialOperators.evaluate(rho,ops,cart.scale);
other=cart.scale;other.logC_l=.31;other.logC_omega=-.27;
other.X_shift=.6;other.physicalTime=3.1;other.canonicalTime=2.4;
[F1,flow1,info1]=ops.spatialOperators.evaluate(rho,ops,other);
assert(isequaln(F0,F1)&&isequaln(flow0.source,flow1.source)&& ...
    isequaln(flow0.fullQ,flow1.fullQ)&& ...
    isequaln([flow0.c_l,flow0.c_omega,flow0.c_r],[flow1.c_l,flow1.c_omega,flow1.c_r]), ...
    'ipm_c:SharedSpatialAutonomous');
assert(isequaln(flow0.source,ops.spatialOperators.derivativeX(rho))&& ...
    isequaln(flow0.fullQ,ops.spatialOperators.derivativeX(F0))&& ...
    max(abs(info0.gauge.auditResidual))<=1e-5&& ...
    info1.poisson.linearSolveBackwardError<=1e-10&& ...
    all(F0(1,:)==F0(1,1)), 'ipm_c:SharedSpatialFullAudit');
finiteState=struct('rho',rho,'flow',flow0,'scale',cart.scale);
assert(ipm.evolve.isFinite(finiteState),'ipm_c:SharedSpatialFiniteInterface');
[direct,directInfo]=ipm_c.spatial.poisson(flow0.source,g,cfg.elliptic);
poissonDifference=max(abs([direct.psi-flow0.psi,direct.u1-flow0.u1,direct.u2-flow0.u2]),[],'all');
assert(poissonDifference==0&&~directInfo.factorCacheRebuilt&& ...
    directInfo.bsplineOrder==4&&directInfo.bsplineDegree==3,'ipm_c:DirectPoissonCache');
transforms=ipm_c.spatial.poisson('transform-test');assert(transforms.passed);
report=struct('kind','direct_total_rho_polar_spatial_manufacture_v3','passed',true, ...
    'dimension',n,'tensorEntries',numel(rho),'derivativeError',derivativeError, ...
    'fineDerivativeError',fineDerivativeError,'originDerivativeError',originDerivativeError, ...
    'cachedPoissonDifference',poissonDifference,'fixedGeometryFactorCacheReused',true, ...
    'fftTransforms',transforms,'iterativeLinearSolverUsed',false,'fullRhsScaleClockIndependence',true, ...
    'gaugeResidual',max(abs(info0.gauge.auditResidual)), ...
    'poissonLinearBackwardError',info0.poisson.linearSolveBackwardError, ...
    'completeRhsCalls',2,'timeAdvanced',0,'trajectoryQualificationClaimed',false);
end

