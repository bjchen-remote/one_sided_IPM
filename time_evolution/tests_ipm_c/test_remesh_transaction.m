function report=test_remesh_transaction(state)
%TEST_REMESH_TRANSACTION Complete physical-area observer and transactional rollback.
% Supply one actual accepted state from the new total-rho polar architecture.
% All proposal overrides are explicitly manufactured. The smooth radial
% perturbation exercises a real different-geometry transfer and complete
% fresh audit; it does not claim an evolved/adaptive trajectory qualification.
g=ipm_c.mesh.build(struct('nr',17,'ntheta',33,'rmax',3,'firstSpacing',.08));
constant=ones(g.nr,g.ntheta);
[features,geometry]=ipm_c.diagnostics.sourceFeatures(constant,g,[.1,.2,.5]);
expected=.5*(g.ntheta-1)*sin(pi/(g.ntheta-1))*g.r(end)^2;
assert(max(abs(features.areas-expected))<=256*eps(expected)&&geometry.originPhysicalPointCount==1&& ...
    geometry.triangleCount==(2*g.nr-3)*(g.ntheta-1),'ipm_c:RemeshTestArea');
scaled=g;scaled.r=2*g.r;scaled.X=2*g.X;scaled.Y=2*g.Y;
larger=ipm_c.diagnostics.sourceFeatures(constant,scaled,[.1,.2,.5]);
assert(max(abs(larger.areas-4*features.areas))<=512*eps(4*expected), ...
    'ipm_c:RemeshTestAreaScaling','Physical area must scale quadratically, independent of node counts.');
assert(~ipm_c.diagnostics.areaChange(1.199*features.areas,features.areas)&& ...
    ipm_c.diagnostics.areaChange(1.2*features.areas,features.areas), ...
    'ipm_c:RemeshTestTrigger','Keep the exact twenty-percent area trigger.');
current=ipm_c.diagnostics.sourceFeatures(state.flow.source,state.ops.polarGrid,[.1,.2,.5]);
assert(current.usableForCdf,'ipm_c:RemeshTestState','The fixture requires nondegenerate positive source geometry.');
original=state;
original.config.remesh.adaptiveRemesh=true;original.config.remesh.maxRemeshes=Inf;
original.ops.rescaling.referenceLevelSetAreas=current.areas/1.3;
original.ops.rescaling.referenceLevelSetRadialBounds=current.radialProjectionBounds;
original.ops.rescaling.areaRemeshObserver=struct('checks',0,'failures',0,'retryAt',0,'features',[]);
fixture=struct('manufactured',true,'proposalAxis',state.ops.polarGrid.r,'allowIdentity',true,'maximumRetries',0);
[committed,commit]=ipm_c.remesh.apply(original,fixture);
assert(commit.manufacturedFixture&&commit.applied&&~commit.pending&&~commit.geometryChanged&& ...
    committed.ops.remeshCount==option(original.ops,'remeshCount',0)+1&&commit.attempts(1).passed&& ...
    isequaln(committed.scale,original.scale)&&committed.step==original.step&& ...
    isequaln(committed.ops.cart.originalWallOps,original.ops.cart.originalWallOps), ...
    'ipm_c:RemeshTestCommit','An explicit identity fixture must still execute the complete fresh physical audit before commit.');
changed=fixture;logical=linspace(0,1,numel(state.ops.polarGrid.r))';
changed.proposalAxis=state.ops.polarGrid.r.*(1+1e-6*sin(pi*logical).^2);
changed.proposalAxis([1,end])=state.ops.polarGrid.r([1,end]);changed.allowIdentity=false;
[migrated,migration]=ipm_c.remesh.apply(original,changed);
assert(migration.applied&&~migration.pending&&migration.geometryChanged&& ...
    ~isequaln(migrated.ops.polarGrid.r,original.ops.polarGrid.r)&& ...
    isequaln(migrated.ops.polarGrid.r,changed.proposalAxis)&& ...
    isequaln(migrated.ops.polarGrid.theta,original.ops.polarGrid.theta)&& ...
    all(migrated.rho(1,:)==migrated.rho(1,1))&& ...
    migration.attempts(1).massRelativeJump<=1e-3&& ...
    migration.attempts(1).wallIntegralRelativeJump<=1e-3&& ...
    migration.attempts(1).poissonLinearBackwardError<=1e-10&& ...
    migration.attempts(1).gaugeResidual<=1e-5&& ...
    isequaln(migrated.rhsCache.rho,migrated.rho)&& ...
    isequaln(migrated.rhsCache.spatialGeometryKey,migrated.ops.spatialGeometryKey)&& ...
    migrated.rhsCache.remeshCount==migrated.ops.remeshCount&& ...
    isequaln(migrated.scale,original.scale)&&migrated.step==original.step&& ...
    isequaln(migrated.ops.cart.originalWallOps,original.ops.cart.originalWallOps), ...
    'ipm_c:RemeshTestDifferentGeometry','A real radial transfer must rebuild operators, preserve physical clocks/references and pass every complete candidate gate.');
fixture.rejectAfterFullAudit=true;
[rejected,reject]=ipm_c.remesh.apply(original,fixture);
assert(~reject.applied&&reject.pending&&strcmp(reject.status,'candidate_rejected')&& ...
    strcmp(reject.rejectionReason,'ipm_c:AreaRemeshManufacturedRejection')&& ...
    reject.attempts(1).poissonLinearBackwardError<=1e-10&&reject.attempts(1).gaugeResidual<=1e-5, ...
    'ipm_c:RemeshTestReject','The deliberate rejection must happen after a complete passing physical audit.');
oldOps=original.ops;newOps=rejected.ops;
oldOps.rescaling=rmfield(oldOps.rescaling,'areaRemeshObserver');
newOps.rescaling=rmfield(newOps.rescaling,'areaRemeshObserver');
assert(isequaln(oldOps,newOps)&&isequaln(rejected.rho,original.rho)&& ...
    isequaln(rejected.flow,original.flow)&&isequaln(rejected.scale,original.scale)&& ...
    rejected.step==original.step&&isequaln(rejected.config,original.config), ...
    'ipm_c:RemeshTestRollback','A rejected candidate must preserve every accepted physical field, grid, clock and reference.');
bad=fixture;bad.proposalAxis(2)=0;bad.rejectAfterFullAudit=false;
[unchanged,invalid]=ipm_c.remesh.apply(original,bad);
assert(~invalid.applied&&invalid.pending&&strcmp(invalid.rejectionReason,'ipm_c:AreaRemeshAxis')&& ...
    isequaln(unchanged.rho,original.rho)&&isequaln(unchanged.ops.polarGrid,original.ops.polarGrid), ...
    'ipm_c:RemeshTestInvalidAxis');
report=struct('kind','polar_area_observer_identity_commit_full_audit_rollback_fixtures_v1', ...
    'passed',true,'constantAreas',features.areas,'expectedPolygonArea',expected, ...
    'physicalAreaScalingPassed',true,'twentyPercentTriggerPassed',true, ...
    'identityCommit',commit,'differentGeometryTransfer',migration, ...
    'postFullAuditRollback',reject,'invalidAxisRollback',invalid, ...
    'completeCandidateRhsEvaluations',3,'actualGeometryMigrationPassed',true, ...
    'timeAdvanced',0,'trajectoryQualificationClaimed',false);
end
function result=option(s,key,fallback)
if isfield(s,key),result=s.(key);else,result=fallback;end
end
