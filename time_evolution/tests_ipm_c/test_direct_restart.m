function report=test_direct_restart(folder)
%TEST_SHARED_RESTART Must be called in a new MATLAB process after workflow.
loaded=load(fullfile(folder,'resume_request.mat'));cfg=loaded.cfg;split=loaded.split;
r=ipm_c.solve(cfg,split);assert(r.steps==2&&strcmp(r.status,'target_reached'));
[a,~]=ipm_c.output.loadCheckpoint(fullfile(folder,'direct'));
[b,~]=ipm_c.output.loadCheckpoint(split);
error=max(abs(a.state.rho-b.state.rho),[],'all');
scaleError=max(abs([a.state.scale.logC_l-b.state.scale.logC_l, ...
    a.state.scale.logC_omega-b.state.scale.logC_omega, ...
    a.state.scale.X_shift-b.state.scale.X_shift, ...
    a.state.scale.physicalTime-b.state.scale.physicalTime]));
assert(error<=1e-8&&scaleError<=1e-8&& ...
    a.state.scale.canonicalTime==b.state.scale.canonicalTime&& ...
    isequaln(a.authority.shared.references,b.authority.shared.references), ...
    'ipm_c:SharedColdReplay','Fresh-process replay must retain the same accepted total-density trajectory.');
report=struct('kind','direct_cfl_polar_new_process_replay_v3','passed',true, ...
    'rhoInfinityDifference',error,'scaleClockInfinityDifference',scaleError, ...
    'tau',b.state.scale.canonicalTime,'steps',b.state.step,'resume',r, ...
    'originalReferencesUnchanged',true,'spatialTrajectoryQualified',false);
ipm_c.output.atomicJson(fullfile(folder,'restart_report.json'),report);
end
