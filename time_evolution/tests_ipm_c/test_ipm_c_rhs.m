function report=test_ipm_c_rhs()
%TEST_IPM_C_RHS Complete background/remainder assembly and full gauge audit.
% Finite-disk boundary data isolate the internal equation and gauge contract;
% this test does not qualify the production Green boundary or a trajectory.
[g,cart,rho,reference]=ipm_c_test_fixture(33);saved=cart;
options=struct('manufactured',true,'outerPsi',zeros(1,g.ntheta), ...
    'poleRegularization',false,'measurementInterpolation','linear', ...
    'rootTolerance',1e-9,'auditTolerance',1e-8);
[F,flow,info]=ipm_c_legacy_fixture('rhs',rho,g,cart,options);
bg=ipm_c_legacy_fixture('background',cart.originalMetadata.config.physics,g.X,g.Y,cart.scale);
assert(isequaln(flow.source,bg.rx)&&all(flow.remainderState==0,'all'), ...
    'ipm_c:RhsZeroRemainderSource','The analytic background must remain in the physical source.');
assert(isequaln(F,flow.backgroundRate+flow.remainderRate), ...
    'ipm_c:RhsCompleteAssembly','Returned F must equal the complete direct remainder assembly.');
d=ipm_c.field.derivatives(flow.remainderRate,g,options);
assert(isequaln(flow.fullQ,d.rx+flow.backgroundRateX), ...
    'ipm_c:RhsCompleteQ','Q must contain both the background and remainder time derivatives.');
assert(all(isfinite(F),'all')&&all(isfinite(flow.fullQ),'all')&& ...
    max(abs(info.gauge.auditResidual))<=info.gauge.auditTolerance, ...
    'ipm_c:RhsFiniteAudit','The actual returned complete RHS must satisfy the full I/P/C audit.');
assert(isequaln(cart,saved)&&~info.referencesReset&&~info.physicalTimeReparameterized, ...
    'ipm_c:RhsStatePreservation','RHS evaluation must preserve injected references, state, and clocks.');
primaryOptions=options;primaryOptions.remainderState=zeros(size(rho));
[Fprimary,flowPrimary,primaryInfo]=ipm_c_legacy_fixture('rhs',rho,g,cart,primaryOptions);
assert(isequaln(Fprimary,F)&&isequaln(flowPrimary.fullQ,flow.fullQ)&& ...
    primaryInfo.primaryRemainderSupplied&&~primaryInfo.remainderRateRecoveredBySubtraction, ...
    'ipm_c:RhsPrimaryZero','Supplying the primary zero remainder must preserve the complete equation.');

v=.003*g.X.*exp(-g.R.^2);total=bg.rho+v;
primaryOptions.remainderState=v;
[perturbed,perturbedFlow,perturbedInfo]=ipm_c_legacy_fixture('rhs',total,g,cart,primaryOptions);
dv=ipm_c.field.derivatives(v,g,options);
assert(isequaln(perturbedFlow.source,bg.rx+dv.rx)&& ...
    isequaln(perturbedFlow.remainderState,v)&&all(isfinite(perturbed),'all')&& ...
    max(abs(perturbedInfo.gauge.auditResidual))<=perturbedInfo.gauge.auditTolerance, ...
    'ipm_c:RhsPrimaryNonzero','A supplied nonzero primary remainder must use the same total source and audit.');
badOptions=primaryOptions;badOptions.remainderState=v+1e-4;rejected=false;
try
    ipm_c_legacy_fixture('rhs',total,g,cart,badOptions);
catch problem
    rejected=strcmp(problem.identifier,'polar:PrimaryRemainderIdentity');
end
assert(rejected,'ipm_c:RhsPrimaryIdentityGuard','A mismatched primary remainder must be rejected.');
report=struct('passed',true,'kind','complete_background_remainder_rhs_contract_v1', ...
    'zeroRemainderGaugeAuditResidual',info.gauge.auditResidual, ...
    'primaryRemainderGaugeAuditResidual',perturbedInfo.gauge.auditResidual, ...
    'completeAssemblyDifferenceInfinity',info.completeRhsAssemblyDifferenceInfinity, ...
    'primaryAssemblyDifferenceInfinity',perturbedInfo.completeRhsAssemblyDifferenceInfinity, ...
    'originalIPC',reference.IPC,'referencesPreserved',isequaln(cart,saved), ...
    'primaryIdentityGuardPassed',rejected,'poissonCalls',3,'timeAdvanced',0, ...
    'nativeTrajectoryQualificationClaimed',false,'boundary','finite_disk_zero_Dirichlet');
end
