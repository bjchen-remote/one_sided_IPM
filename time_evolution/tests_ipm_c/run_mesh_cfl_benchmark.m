function report=run_mesh_cfl_benchmark(baselineCfg,candidateCfg,outputPath)
%RUN_MESH_CFL_BENCHMARK Equal-horizon ABBA timing of the direct polar solver.
% Timing encloses only advance (including the enabled automatic remesher).
% Initialization, validation, JSON and endpoint MAT publication are excluded.
assert(ischar(outputPath)||isstring(outputPath),'ipm_c:BenchmarkOutput');
outputPath=char(outputPath);parent=fileparts(outputPath);
assert(~isempty(parent)&&startsWith(parent,filesep),'ipm_c:BenchmarkOutput', ...
    'Supply an absolute JSON path.');
if ~isfolder(parent),mkdir(parent);end
assert(~isfile(outputPath),'ipm_c:BenchmarkOutput','Preserve previous benchmark evidence.');
horizon=.02;maximumSteps=1000;
baselineCfg=prepare(baselineCfg,horizon,maximumSteps);
candidateCfg=prepare(candidateCfg,horizon,maximumSteps);
sameFields={'physics','transport','elliptic','scaling','rhsOptions'};
for k=1:numel(sameFields)
    key=sameFields{k};
    assert(isequaln(baselineCfg.(key),candidateCfg.(key)), ...
        'ipm_c:BenchmarkControls','Baseline and candidate must retain the same %s.',key);
end
baselineRemesh=baselineCfg.remesh;candidateRemesh=candidateCfg.remesh;
for name={'minimumFirstSpacing'}
    if isfield(baselineRemesh,name{1}),baselineRemesh=rmfield(baselineRemesh,name{1});end
    if isfield(candidateRemesh,name{1}),candidateRemesh=rmfield(candidateRemesh,name{1});end
end
assert(isequaln(baselineCfg.time,candidateCfg.time)&& ...
    isequaln(baselineRemesh,candidateRemesh)&& ...
    strcmp(baselineCfg.authorityFile,candidateCfg.authorityFile), ...
    'ipm_c:BenchmarkControls','Change only the mesh in a controlled comparison.');
threads=maxNumCompThreads(1);threadCleanup=onCleanup(@()maxNumCompThreads(threads)); %#ok<NASGU>
report=struct('kind','direct_polar_mesh_equal_tau_ABBA_benchmark_v1', ...
    'passed',false,'status','running','order',{{'baseline','candidate','candidate','baseline'}}, ...
    'horizonCanonicalTau',horizon,'maximumSteps',maximumSteps,'threads',1, ...
    'timeIntegrator','ssprk3','stepRetryEnabled',false,'implicitSolverEnabled',false, ...
    'automaticRemeshEnabled',true,'poissonFactorization','decomposition_lu_cached_by_actual_geometry', ...
    'timingScope','sum of advance calls including automatic remesh; excludes setup, validation and output', ...
    'configuration',struct('baseline',jsonSafe(baselineCfg),'candidate',jsonSafe(candidateCfg)), ...
    'sourceAndCacheQualification',struct( ...
        'fullRhsIncludesPoissonGaugeTransportAndFullQ',true, ...
        'sourceEquation','minus_polar_laplacian_psi_equals_rho_X', ...
        'originalWallAuthorityRetained',true, ...
        'counterScope','explicit stage RHS plus remesh candidates that completed a full audit', ...
        'failedRemeshRhsCountsAreNotInstrumented',true, ...
        'cacheObservationScope','initialization and accepted step endpoints', ...
        'innerStageCacheEventsNotInstrumented',true), ...
    'cases',{{}},'longTrajectoryQualified',false,'spatialAccuracyQualified',false);
ipm_c.output.atomicJson(outputPath,report);
endpoints=struct();endpointPath=fullfile(parent,'endpoint.mat');
for run=1:4
    label=report.order{run};
    if strcmp(label,'baseline'),cfg=baselineCfg;else,cfg=candidateCfg;end
    setup=tic;[state,~]=ipm_c.initialize(cfg);setupSeconds=toc(setup);
    assert(strcmp(state.config.time.timeIntegrator,'ssprk3')&& ...
        state.config.remesh.adaptiveRemesh&& ...
        ~isfield(state.ops,'timeIntegrationContract')&& ...
        ~isfield(state.ops.spatialOperators,'preconditioner'), ...
        'ipm_c:BenchmarkArchitecture','Use the direct explicit architecture.');
    validateEndpoint(state);
    initialCacheRebuilt=logical(state.flow.poissonSolveInfo.factorCacheRebuilt);
    rows=cell(1,maximumSteps);steps=0;explicitRhs=0;remeshAuditedRhs=0;
    remeshAttempts=0;retryCount=0;implicitSolves=0;advanceSeconds=0;
    while state.scale.canonicalTime<horizon
        assert(steps<maximumSteps,'ipm_c:BenchmarkStepBudget', ...
            'The common horizon must be reached within the declared step budget.');
        oldGrid=state.ops.polarGrid;oldCount=state.ops.remeshCount;
        timer=tic;[next,reason]=ipm_c.evolve.advance(state);elapsed=toc(timer);
        assert(isempty(reason),'ipm_c:BenchmarkAdvance','Direct advance stopped: %s',reason);
        assert(next.step==state.step+1,'ipm_c:BenchmarkAdvance');
        state=next;steps=steps+1;advanceSeconds=advanceSeconds+elapsed;
        ts=state.timeStep;validateEndpoint(state);
        assert(ts.attemptedSteps==1&&ts.retryCount==0&&ts.implicitStageSolves==0, ...
            'ipm_c:BenchmarkUnexpectedRetry','Each accepted step must use one explicit attempt.');
        retryCount=retryCount+ts.retryCount;implicitSolves=implicitSolves+ts.implicitStageSolves;
        explicitRhs=explicitRhs+ts.rhsEvaluations;
        attempts=0;audited=0;remeshStatus='not_observed';
        if isfield(ts,'remesh')
            remeshStatus=ts.remesh.status;attempts=numel(ts.remesh.attempts);
            for j=1:attempts
                audited=audited+isfinite(ts.remesh.attempts(j).poissonLinearBackwardError);
            end
        end
        remeshAttempts=remeshAttempts+attempts;remeshAuditedRhs=remeshAuditedRhs+audited;
        changed=~isequaln(oldGrid.r,state.ops.polarGrid.r)|| ...
            ~isequaln(oldGrid.theta,state.ops.polarGrid.theta);
        rebuilt=logical(state.flow.poissonSolveInfo.factorCacheRebuilt);
        assert(~rebuilt||changed,'ipm_c:BenchmarkPoissonCache', ...
            'An accepted unchanged-grid endpoint should reuse its Poisson factors.');
        rows{steps}=struct('step',state.step,'canonicalTau',state.scale.canonicalTime, ...
            'physicalTime',state.scale.physicalTime,'dt',ts.dt,'advanceSeconds',elapsed, ...
            'activeLimiter',ts.activeLimiter,'initialCflRate',ts.rate, ...
            'initialTransportRate',ts.transportRate,'initialReactionRate',ts.reactionRate, ...
            'realizedCfl',ts.realizedCfl,'terminalCfl',ts.terminalCfl, ...
            'explicitFullRhsEvaluations',ts.rhsEvaluations, ...
            'initialStageCacheHit',ts.initialStageCacheHit, ...
            'remeshAttemptCount',attempts,'remeshAuditedFullRhsEvaluations',audited, ...
            'remeshStatus',remeshStatus,'remeshApplied',state.ops.remeshCount>oldCount, ...
            'actualGeometryChanged',changed,'terminalPoissonFactorCacheRebuilt',rebuilt, ...
            'terminalPoissonResidual',state.flow.poissonResidual, ...
            'terminalGaugeResidual',max(abs(state.flow.gaugeResidual)), ...
            'retryCount',ts.retryCount,'implicitSolves',ts.implicitStageSolves);
    end
    assert(abs(state.scale.canonicalTime-horizon)<=64*eps(max(1,horizon)), ...
        'ipm_c:BenchmarkCommonHorizon','Compare endpoints at exactly the common canonical time.');
    rows=rows(1:steps);dt=cellfun(@(x)x.dt,rows);seconds=cellfun(@(x)x.advanceSeconds,rows);
    green=state.flow.poissonSolveInfo.green;
    record=struct('run',run,'label',label,'nr',state.ops.polarGrid.nr, ...
        'ntheta',state.ops.polarGrid.ntheta, ...
        'independentDofs',1+(state.ops.polarGrid.nr-1)*state.ops.polarGrid.ntheta, ...
        'actualFirstRadius',state.ops.polarGrid.r(2), ...
        'steps',steps,'canonicalTau',state.scale.canonicalTime,'physicalTime',state.scale.physicalTime, ...
        'setupSeconds',setupSeconds,'advanceSeconds',advanceSeconds, ...
        'minimumStep',min(dt),'maximumStep',max(dt),'meanStep',mean(dt), ...
        'meanAdvanceSecondsPerStep',mean(seconds),'medianAdvanceSecondsPerStep',median(seconds), ...
        'canonicalTauPerSecond',horizon/advanceSeconds, ...
        'initialFullRhsEvaluations',1,'explicitFullRhsEvaluations',explicitRhs, ...
        'remeshAuditedFullRhsEvaluations',remeshAuditedRhs, ...
        'fullRhsEvaluationsLowerBound',1+explicitRhs+remeshAuditedRhs, ...
        'evaluationCountExact',remeshAttempts==0&&state.ops.remeshCount==0, ...
        'remeshAttemptCount',remeshAttempts,'remeshCount',state.ops.remeshCount, ...
        'automaticRemeshWasExercised',state.ops.remeshCount>0, ...
        'initialPoissonFactorCacheRebuilt',initialCacheRebuilt, ...
        'terminalPoissonFactorCacheRebuilt',logical(state.flow.poissonSolveInfo.factorCacheRebuilt), ...
        'terminalPoissonResidual',state.flow.poissonResidual, ...
        'terminalGaugeResidual',max(abs(state.flow.gaugeResidual)), ...
        'terminalGaugeTolerance',state.flow.ipmCInfo.gauge.auditTolerance, ...
        'terminalGreen',green,'retryCount',retryCount,'implicitSolves',implicitSolves, ...
        'noUnexpectedRetry',retryCount==0&&implicitSolves==0,'stepsDetail',{rows});
    report.cases{run}=record;
    if ~isfield(endpoints,label)
        endpoints.(label)=packEndpoint(state,cfg,run); %#ok<AGROW>
        temp=[endpointPath,'.writing.mat'];save(temp,'endpoints','-v7.3');
        [ok,message]=movefile(temp,endpointPath,'f');assert(ok,'ipm_c:BenchmarkEndpoint','%s',message);
    end
    ipm_c.output.atomicJson(outputPath,report);
end
b1=report.cases{1};c1=report.cases{2};c2=report.cases{3};b2=report.cases{4};
paired=[c1.canonicalTauPerSecond/b1.canonicalTauPerSecond, ...
    c2.canonicalTauPerSecond/b2.canonicalTauPerSecond];
baselineSeconds=b1.advanceSeconds+b2.advanceSeconds;
candidateSeconds=c1.advanceSeconds+c2.advanceSeconds;
report.comparison=struct('pairedCanonicalThroughputSpeedup',paired, ...
    'pairedArithmeticMeanSpeedup',mean(paired),'pairedGeometricMeanSpeedup',sqrt(prod(paired)), ...
    'aggregateCanonicalThroughputSpeedup',baselineSeconds/candidateSeconds, ...
    'baselineCanonicalTauPerSecond',2*horizon/baselineSeconds, ...
    'candidateCanonicalTauPerSecond',2*horizon/candidateSeconds, ...
    'baselineMeanSecondsPerStep',baselineSeconds/(b1.steps+b2.steps), ...
    'candidateMeanSecondsPerStep',candidateSeconds/(c1.steps+c2.steps), ...
    'baselineMeanStep',2*horizon/(b1.steps+b2.steps), ...
    'candidateMeanStep',2*horizon/(c1.steps+c2.steps), ...
    'baselineTotalSteps',b1.steps+b2.steps,'candidateTotalSteps',c1.steps+c2.steps, ...
    'endpointFile',endpointPath, ...
    'interpretation','Performance comparison at equal canonical tau; spatial error requires independent validation.');
report.passed=true;report.status='complete';
ipm_c.output.atomicJson(outputPath,report);
end

function cfg=prepare(cfg,horizon,maximumSteps)
assert(strcmp(cfg.time.timeIntegrator,'ssprk3'),'ipm_c:BenchmarkArchitecture');
cfg.targetTau=horizon;cfg.time.finalTime=horizon;cfg.time.physicalFinalTime=Inf;
cfg.maxSteps=maximumSteps;cfg.time.maxSteps=maximumSteps;
cfg.runtime.threads=1;cfg.output.verbose=false;cfg.remesh.adaptiveRemesh=true;
end

function validateEndpoint(state)
assert(isfinite(state.flow.poissonResidual)&&state.flow.poissonResidual<=1e-5&& ...
    all(isfinite(state.flow.gaugeResidual))&& ...
    max(abs(state.flow.gaugeResidual))<=state.flow.ipmCInfo.gauge.auditTolerance&& ...
    state.flow.ipmCInfo.gauge.auditTolerance<=1e-5&& ...
    all(isfinite(state.rho),'all')&&all(isfinite(state.flow.fullQ),'all'), ...
    'ipm_c:BenchmarkEndpointAudit','The complete endpoint must pass original Poisson and gauge gates.');
end

function endpoint=packEndpoint(state,cfg,run)
flow=struct('F',state.rhsCache.rhoRate,'Q',state.flow.fullQ,'source',state.flow.source, ...
    'u1',state.flow.u1,'u2',state.flow.u2,'psi',state.flow.psi, ...
    'transportU1',state.flow.transportU1,'transportU2',state.flow.transportU2, ...
    'c_l',state.flow.c_l,'c_omega',state.flow.c_omega,'c_r',state.flow.c_r, ...
    'poissonResidual',state.flow.poissonResidual,'gaugeResidual',state.flow.gaugeResidual, ...
    'poissonSolveInfo',state.flow.poissonSolveInfo);
endpoint=struct('run',run,'rho',state.rho,'scale',state.scale, ...
    'actualGrid',state.ops.polarGrid,'cfg',cfg,'flow',flow,'step',state.step, ...
    'canonicalTau',state.scale.canonicalTime,'remeshCount',state.ops.remeshCount);
end

function result=jsonSafe(value)
% JSON null would hide intentional Inf configuration bounds.
if isstruct(value)
    result=value;names=fieldnames(value);
    for element=1:numel(value)
        for k=1:numel(names)
            key=names{k};result(element).(key)=jsonSafe(value(element).(key));
        end
    end
elseif iscell(value)
    result=cellfun(@jsonSafe,value,'UniformOutput',false);
elseif isnumeric(value)&&any(~isfinite(value),'all')
    result=arrayfun(@numericValue,value,'UniformOutput',false);
    if isscalar(result),result=result{1};end
else,result=value;
end
end

function result=numericValue(value)
if isfinite(value),result=value;
elseif isnan(value),result='NaN';
elseif value>0,result='Inf';else,result='-Inf';end
end
