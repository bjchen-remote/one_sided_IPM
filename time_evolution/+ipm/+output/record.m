    end
    gauge = copy_finite_fields( ...
        struct(),flow,unique(gaugeNames,'stable'));
    gauge.cOmegaOverCL = guarded_rate_ratio(flow.c_omega,flow.c_l);
    gauge.cLMinusCOmegaOverCL = guarded_rate_ratio( ...
        flow.c_l-flow.c_omega,flow.c_l);
