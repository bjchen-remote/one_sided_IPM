        'gridRatio(x/y)=%.4f/%.4f remesh=%d%s\n'], ...
        scale.canonicalTime,scale.physicalTime, ...
        flow.c_l,flow.c_omega,flow.c_r,cs, ...
        fullRateNorm,coreRateNorm,common.physicalMassDrift, ...
        mesh.maximumCellRatioX,mesh.maximumCellRatioY,ops.remeshCount,integralText);
end
end

function target = append_scalars(target,values)
existingNames = fieldnames(target);
valueNames = fieldnames(values);
names = [existingNames;setdiff(valueNames,existingNames,'stable')];
count = 0;
for index = 1:numel(existingNames)
    count = max(count,numel(target.(existingNames{index})));
end
for index = 1:numel(names)
    name = names{index};
    if isfield(target,name)
        series = target.(name)(:);
        if numel(series) < count
            padded = missing_series(series,count);
            padded(1:numel(series)) = series;
            series = padded;
        end
    else
        series = missing_series(values.(name),count);
    end
    if isfield(values,name)
        value = values.(name);
        if ~isscalar(value)
            error('ipm:HistoryScalar', ...
                'History field "%s" must be scalar at each record.',name);
        end
    else
        value = missing_value(series);
    end
    nextSeries = missing_series(series,count+1);
    if count > 0
        nextSeries(1:count) = series;
    end
    nextSeries(end) = value;
    target.(name) = nextSeries;
end
end

function series = missing_series(template,count)
if isstring(template)
    series = strings(count,1);
elseif islogical(template)
    series = false(count,1);
elseif isfloat(template)
    series = NaN(count,1,'like',template);
else
    series = zeros(count,1,'like',template);
end
end

function value = missing_value(series)
if isstring(series)
    value = "";
elseif islogical(series)
    value = false;
elseif isfloat(series)
    value = cast(NaN,'like',series);
else
    value = cast(0,'like',series);
end
end

function target = merge_scalars(target,source)
names = fieldnames(source);
for index = 1:numel(names)
    target.(names{index}) = source.(names{index});
end
end

function target = copy_finite_fields(target,source,names)
for index = 1:numel(names)
    name = names{index};
    if isfield(source,name) && isscalar(source.(name)) && ...
            isnumeric(source.(name)) && isfinite(source.(name))
        target.(name) = source.(name);
    end
end
end

function value = anisotropic_gradient_effective_length( ...
        rho,ops,Cx,Cy,amplitudeInverse)
rhoX = rho*ops.Dx';
rhoY = ops.Dy*rho;
physicalSquared = amplitudeInverse^2 * ...
    (Cx^2*rhoX.^2+Cy^2*rhoY.^2);
weights = ops.integrationWeights;
energy = sum(physicalSquared.*weights,'all')/(Cx*Cy);
fourthMoment = sum(physicalSquared.^2.*weights,'all')/(Cx*Cy);
value = energy/sqrt(max(fourthMoment,eps));
end

function ratio = maximum_cell_ratio(faces)
if numel(faces) < 2
    ratio = 1;
else
    ratio = max(max(faces(2:end)./faces(1:end-1), ...
        faces(1:end-1)./faces(2:end)));
end
end

function value = guarded_rate_ratio(numerator,denominator)
scale = max([1,abs(numerator),abs(denominator)]);
if abs(denominator) <= 100*eps(scale)
    value = NaN;
else
    value = numerator/denominator;
end
end

function telemetry = quadratic_peak_telemetry( ...
        scaling,flow,scale,d,scaleRatio)
% Algebraic read-only telemetry for the selected quadratic-peak gauge.
telemetry = struct( ...
    'physicalQuadraticPeak',NaN, ...
    'inversePhysicalQuadraticPeak',NaN, ...
    'quadraticInverseSlopeAlgebraic',NaN, ...
    'quadraticLocalTerminalTime',NaN, ...
    'rescaledRhoXInfToQuadraticPeak',NaN);
if ~any(strcmp(scaling.cOmegaGauge, ...
        {'wall_omega_quadratic_peak','wall_omega_tracked_spline_peak'})) || ...
        ~isfield(flow,'omegaGaugeQuadraticPeakValue')
    return;
end
peak = flow.omegaGaugeQuadraticPeakValue;
rescaledMaximum = d.rhoXInf;
if ~all(isfinite([peak,rescaledMaximum,scaleRatio])) || ...
        peak <= 0 || rescaledMaximum <= 0 || scaleRatio <= 0
    return;
end
physicalPeak = scaleRatio*peak;
if ~isfinite(physicalPeak) || physicalPeak <= 0
    return;
end
telemetry.physicalQuadraticPeak = physicalPeak;
telemetry.inversePhysicalQuadraticPeak = 1/physicalPeak;
telemetry.rescaledRhoXInfToQuadraticPeak = rescaledMaximum/peak;
kappa = flow.canonicalCL-flow.canonicalCOmega;
if ~isfinite(kappa)
    return;
end
telemetry.quadraticInverseSlopeAlgebraic = -kappa/peak;
if kappa > 0
    terminalTime = scale.physicalTime + peak/(kappa*physicalPeak);
    if isfinite(terminalTime)
        telemetry.quadraticLocalTerminalTime = terminalTime;
    end
end
end
