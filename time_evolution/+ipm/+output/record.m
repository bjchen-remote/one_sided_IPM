function [log,d] = record(log,state)
%IPM.OUTPUT.RECORD Append one state to the version-2 grouped run history.

rho = state.rho;
flow = state.flow;
scale = state.scale;
ops = state.ops;
scaling = state.config.scaling;
output = state.config.output;
d = ipm.diagnostics.measure(rho,flow,ops,state.mass0);

isAnisotropic = strcmp(ops.dynamicScaleGeometry,'anisotropic');
Cx = exp(scale.logC_l);
if isAnisotropic
    Cy = exp(scale.logC_y);
else
    Cy = Cx;
end
Comega = exp(scale.logC_omega);
amplitudeInverse = 1/Comega;

common = struct( ...
    'acceptedStep',state.step, ...
    't',state.normalizedTime, ...
    'canonicalTau',scale.canonicalTime, ...
    'physicalTime',scale.physicalTime, ...
    'C_l',Cx,'C_x',Cx,'C_y',Cy,'L_x',1/Cx,'L_y',1/Cy, ...
    'aspect',Cy/Cx,'C_omega',Comega,'X_shift',scale.X_shift, ...
    'c_l',flow.c_l,'c_x',flow.c_l,'c_y',flow.c_l, ...
    'c_omega',flow.c_omega,'c_r',flow.c_r, ...
    'canonicalCL',flow.canonicalCL, ...
    'canonicalCX',flow.canonicalCL,'canonicalCY',flow.canonicalCL, ...
    'canonicalCOmega',flow.canonicalCOmega, ...
    'canonicalCR',flow.canonicalCR, ...
    'timeSpeed',flow.timeSpeed, ...
    'canonicalRateMagnitude',flow.canonicalRateMagnitude, ...
    'aspectRate',0,'canonicalAspectRate',0, ...
    'conservativeSource',2*flow.c_l+flow.c_omega, ...
    'canonicalConservativeSource', ...
        2*flow.canonicalCL+flow.canonicalCOmega, ...
    'physicalRhoInf',amplitudeInverse*max(abs(rho),[],'all'), ...
    'physicalRhoMin',amplitudeInverse*d.rhoMin, ...
    'physicalRhoMax',amplitudeInverse*d.rhoMax, ...
    'physicalOmegaInf',Cx*amplitudeInverse*d.omegaInf, ...
    'physicalRhoXInf', ...
        ipm.diagnostics.physicalRhoXInf(flow,scale), ...
    'physicalRhoYInf',Cy*amplitudeInverse*d.rhoYInf, ...
    'physicalWallDensityMax',amplitudeInverse*d.wallDensityMax, ...
    'physicalWallOmegaPeak',Cx*amplitudeInverse*d.wallPeak, ...
    'physicalWallPeak',Cx*amplitudeInverse*d.wallPeak, ...
    'physicalWallPeakWidth',d.wallPeakWidth/Cx);
common = merge_scalars(common,quadratic_peak_telemetry( ...
    scaling,flow,scale,d,Cx/Comega));
if isfield(state.config.remesh,'autonomousMesh') && ...
        state.config.remesh.autonomousMesh.enabled && any(state.config.remesh.autonomousMesh.version == [2,3,4,5])
    common.nodeCountX=ops.nx;
    common.nodeCountY=ops.ny;
    common.meshLevelId=state.runMetadata.autonomousMesh.currentLevelId;
end

% Keep the evolving physical coverage explicit.  A computational endpoint
% of 1e6 is not a terminal physical endpoint once C_l has changed.
common.physicalDomainXMinimum = (ops.x(1)-scale.X_shift)/Cx;
common.physicalDomainXMaximum = (ops.x(end)-scale.X_shift)/Cx;
common.physicalDomainXRadius = max(abs([ ...
    common.physicalDomainXMinimum,common.physicalDomainXMaximum]));
common.physicalDomainYMaximum = ops.y(end)/Cy;
common.physicalMinimumDx = min(ops.dxFaces)/Cx;
common.physicalMinimumDy = min(ops.dyFaces)/Cy;

if isfield(state,'timeStep') && isstruct(state.timeStep) && ...
        isscalar(state.timeStep)
    timeStep = state.timeStep;
else
    timeStep = ipm.evolve.emptyTimestep( ...
        state.config.time,scale,'unavailable');
end
common.acceptedCanonicalDt = timeStep.dt;
common.transportRate = timeStep.rate;
common.cflDtLimit = timeStep.dtCfl;
common.maximumDtLimit = timeStep.maxDtLimit;
common.canonicalEndpointDtLimit = timeStep.canonicalLimit;
common.physicalEndpointDtLimit = timeStep.physicalLimit;
common.physicalClockSpeed = timeStep.physicalClockSpeed;
common.realizedCfl = timeStep.realizedCfl;
common.timestepActiveLimiter = string(timeStep.activeLimiter);
common.amplitudeSourceStep = timeStep.dt*abs(flow.c_omega);
common.conservativeSourceStep = timeStep.dt* ...
    abs(2*flow.c_l+flow.c_omega);

common.physicalRangeViolation = max([state.rhoRange0(1)- ...
    common.physicalRhoMin,common.physicalRhoMax-state.rhoRange0(2),0]);
if isAnisotropic
    common.c_x = flow.c_x;
    common.c_y = flow.c_y;
    common.canonicalCX = flow.canonicalCX;
    common.canonicalCY = flow.canonicalCY;
    common.aspectRate = flow.aspectRate;
    common.canonicalAspectRate = flow.canonicalAspectRate;
    common.conservativeSource = flow.conservativeSource;
    common.canonicalConservativeSource = ...
        flow.canonicalConservativeSource;
end

if isAnisotropic
    common.physicalGradientEnergyX = amplitudeInverse^2 * ...
        (Cx/Cy)*d.gradientEnergyX;
    common.physicalGradientEnergyY = amplitudeInverse^2 * ...
        (Cy/Cx)*d.gradientEnergyY;
    common.physicalGradientEffectiveLength = ...
        anisotropic_gradient_effective_length( ...
            rho,ops,Cx,Cy,amplitudeInverse);
    common.physicalMass = amplitudeInverse*d.mass/(Cx*Cy);
else
    common.physicalGradientEnergyX = ...
        amplitudeInverse^2*d.gradientEnergyX;
    common.physicalGradientEnergyY = ...
        amplitudeInverse^2*d.gradientEnergyY;
    common.physicalGradientEffectiveLength = ...
        d.gradientEffectiveLength/Cx;
    common.physicalMass = amplitudeInverse*d.mass/Cx^2;
end
common.physicalGradientEnergy = common.physicalGradientEnergyX + ...
    common.physicalGradientEnergyY;
common.physicalGradInf = ...
    ipm.diagnostics.physicalGradientInf(d,scale,rho,ops);
common.physicalMassDrift = ...
    (common.physicalMass-state.mass0)/max(abs(state.mass0),eps);

if ops.rescaling.enabled
    common.physicalPinX = (ops.rescaling.pinX-scale.X_shift)/Cx;
    common.physicalTrackedPeakX = (flow.trackedPeakX-scale.X_shift)/Cx;
    common.physicalTrackedWallOmegaPeak = ...
        Cx*amplitudeInverse*flow.trackedWallPeak;
    common.physicalTrackedWallPeakWidth = ...
        flow.trackedWallPeakWidth/Cx;
else
    common.physicalTrackedPeakX = d.wallPeakX;
    common.physicalTrackedWallOmegaPeak = common.physicalWallOmegaPeak;
    common.physicalTrackedWallPeakWidth = common.physicalWallPeakWidth;
end

diagnostics = d;
if ~strcmp(ops.symmetryMode,'double_odd_omega')
    diagnostics = rmfield(diagnostics,{'rhoEvenDefect','omegaOddDefect'});
end
if ~ops.rescaling.enabled
    diagnostics = rmfield(diagnostics,{'pinDensity','pinOmega','pinOffset'});
end
common = merge_scalars(common,diagnostics);
log.history.common = append_scalars(log.history.common,common);
if ~isfield(log.history,'wallCore')
    % Schema-4 checkpoints created before compact wall tracing remain
    % resumable; their new trace begins at the first post-resume record.
    log.history.wallCore = ipm.output.emptyWallCoreHistory();
end
log.history.wallCore = ipm.output.recordWallCore( ...
    log.history.wallCore,state,numel(log.history.common.t));

mesh = struct('remeshCount',ops.remeshCount, ...
    'minimumDx',min(ops.dxFaces),'minimumDy',min(ops.dyFaces), ...
    'maximumCellRatioX',maximum_cell_ratio(ops.dxFaces), ...
    'maximumCellRatioY',maximum_cell_ratio(ops.dyFaces), ...
    'globalGridRatioX',max(ops.dxFaces)/min(ops.dxFaces), ...
    'globalGridRatioY',max(ops.dyFaces)/min(ops.dyFaces));
[~,originIndex] = min(abs(ops.x));
if originIndex < ops.nx
    mesh.originDx = ops.x(originIndex+1)-ops.x(originIndex);
end
if isfinite(flow.omegaGaugePeakX)
    [~,peakIndex] = min(abs(ops.x-flow.omegaGaugePeakX));
    peakLeft = max(peakIndex-1,1);
    peakRight = min(peakIndex+1,ops.nx);
    mesh.peakDx = (ops.x(peakRight)-ops.x(peakLeft)) / ...
        max(peakRight-peakLeft,1);
end
meshNames = {'peakGridPoints','supportGridPoints','coreGridPoints', ...
    'verticalPeakGridPoints','verticalSupportGridPoints', ...
    'verticalCoreGridPoints','targetPeakGridPoints', ...
    'targetSupportGridPoints','targetCoreGridPoints', ...
    'peakExpansionRatio','resolutionFactor','safetyFactor', ...
    'trackedWallPeak','trackedWallPeakWidth','trackedWallCoreWidth', ...
    'trackedVerticalPeakWidth','trackedVerticalCoreWidth'};
mesh = copy_finite_fields(mesh,flow,meshNames);
log.history.mesh = append_scalars(log.history.mesh,mesh);

if ops.rescaling.enabled && ~isAnisotropic
    gaugeNames = {'c_lNominal','canonicalCLNominal','lengthScaleGain', ...
        'widthCorrection','canonicalWidthCorrection','widthRateScale', ...
        'widthControlMode','pinGaugeResidual','pinTransportVelocity', ...
        'lengthGaugeStrain','lengthGaugeResidual','trackedPeakX', ...
        'trackedPeakOffset','peakTransportVelocity', ...
        'travelingWaveResidual'};
    if strcmp(scaling.lengthGauge,'transport_anchor')
        gaugeNames = [gaugeNames,{'transportAnchorX', ...
            'canonicalTransportAnchorVelocity','transportAnchorVelocity'}];
    end
    if strcmp(scaling.lengthGauge,'wall_gradient_integral')
        gaugeNames = [gaugeNames,{'wallIntegral','wallIntegralRadius', ...
            'wallIntegralSupportPoints','wallIntegralCondition', ...
            'wallIntegralRate','wallIntegralRelativeDrift', ...
            'peakHeightRate'}];
        if ~strcmp(scaling.scalingContract,'wall_integral_centroid_practical_v1')
            gaugeNames=[gaugeNames,{'peakPositionTargetRate','peakPositionRate'}];
        end
    end
    if strcmp(scaling.scalingContract,'wall_integral_centroid_practical_v1')
        gaugeNames=[gaugeNames,{'globalWallPeak','globalWallPeakX','globalWallPeakTie', ...
            'wallCentroid','wallCentroidReference','wallCentroidEnergy', ...
            'wallCentroidRate','wallCentroidRateResidual','generatorCflRate', ...
            'generatorReferenceVelocity','generatorTranslationRate', ...
            'generatorRootTolerance','generatorRootResidual'}];
    end
    if strcmp(scaling.lengthGauge,'omega_peak_location')
        gaugeNames = [gaugeNames,{ ...
            'peakLocationRhoXX','peakLocationRhoXXScale', ...
            'peakLocationPhaseDefect', ...
            'peakLocationResponseCondition', ...
            'peakLocationFullPhaseResidual', ...
            'peakLocationNormalizedFullPhaseResidual'}];
    elseif strcmp(scaling.lengthGauge,'wall_density_width')
        gaugeNames = [gaugeNames,{ ...
            'wallDensityLowerSlope','wallDensityUpperSlope', ...
            'wallDensityLowerCondition','wallDensityUpperCondition', ...
            'wallDensityLowerBracket','wallDensityUpperBracket'}];
    end
    if strcmp(scaling.lengthGauge,'local_strain') || ...
            strcmp(scaling.cOmegaGauge,'strain_point')
        gaugeNames = [gaugeNames, ...
            {'strain','strainError','strainCondition'}];
    end
    switch scaling.cOmegaGauge
        case 'wall_omega_global_spline_maximum'
            gaugeNames=[gaugeNames,{'omegaGaugeEnergy','omegaGaugeResidual', ...
                'omegaPeakRateResidual','omegaGaugePeakX','omegaGaugePeakCondition'}];
        case 'wall_omega_peak'
            gaugeNames = [gaugeNames,{'omegaGaugeEnergy', ...
                'omegaGaugeResidual','omegaPeakRateResidual', ...
                'omegaGaugePeakX','omegaGaugePeakCondition'}];
        case {'wall_omega_quadratic_peak','wall_omega_tracked_spline_peak'}
            gaugeNames = [gaugeNames,{'omegaGaugeEnergy', ...
                'omegaGaugeResidual','omegaPeakRateResidual', ...
                'omegaGaugePeakX','omegaGaugePeakCondition', ...
                'omegaGaugeQuadraticPeakX', ...
                'omegaGaugeQuadraticPeakValue', ...
                'omegaGaugeQuadraticForcing', ...
                'omegaGaugeQuadraticCurvature', ...
                'omegaGaugeQuadraticStationarityResidual', ...
                'omegaGaugeQuadraticNormalizedStationarityResidual', ...
                'omegaGaugeQuadraticCurvatureCondition', ...
                'omegaGaugeQuadraticWeightCondition', ...
                'omegaGaugeQuadraticActiveNodeMargin', ...
                'omegaGaugeQuadraticActiveSelectionMargin', ...
                'omegaGaugeQuadraticStencilCenterX', ...
                'omegaGaugeQuadraticVertexInteriorFraction', ...
                'omegaGaugeQuadraticRelativeSubgridLift', ...
                'omegaGaugeQuadraticRateResidual', ...
                'omegaGaugeQuadraticRateScale'}];
        case 'none'
            % The selected zero rate is prescribed.  These quadratic
            % fields are an independent counterfactual peak diagnostic,
            % not a hidden amplitude feedback.
            gaugeNames = [gaugeNames,{'omegaGaugeEnergy', ...
                'omegaGaugeResidual','omegaPeakRateResidual', ...
                'omegaGaugePeakX','omegaGaugePeakCondition', ...
                'omegaGaugeQuadraticPeakX', ...
                'omegaGaugeQuadraticPeakValue', ...
                'omegaGaugeQuadraticForcing', ...
                'omegaGaugeQuadraticCurvature', ...
                'omegaGaugeQuadraticStationarityResidual', ...
                'omegaGaugeQuadraticNormalizedStationarityResidual', ...
                'omegaGaugeQuadraticCurvatureCondition', ...
                'omegaGaugeQuadraticWeightCondition', ...
                'omegaGaugeQuadraticActiveNodeMargin', ...
                'omegaGaugeQuadraticActiveSelectionMargin', ...
                'omegaGaugeQuadraticStencilCenterX', ...
                'omegaGaugeQuadraticVertexInteriorFraction', ...
                'omegaGaugeQuadraticRelativeSubgridLift', ...
                'omegaGaugeQuadraticRateResidual', ...
                'omegaGaugeQuadraticRateScale'}];
        case 'gradient_energy'
            gaugeNames = [gaugeNames, ...
                {'omegaGaugeEnergy','omegaGaugeEnergyX', ...
                'omegaGaugeEnergyY','omegaGaugeForcingX', ...
                'omegaGaugeForcingY','omegaGaugeForcing', ...
                'omegaGaugeAbsoluteForcing', ...
                'omegaGaugeForcingCancellationRatio', ...
                'omegaGaugeResidual'}];
        case 'strain_point'
            gaugeNames = [gaugeNames,{'strainRateResidual', ...
                'omegaGaugeEnergy','omegaGaugeResidual'}];
        case {'anchor_wall_slope','anchor_wall_strain'}
            gaugeNames = [gaugeNames,{'omegaGaugeEnergy', ...
                'omegaGaugeResidual','omegaGaugeAnchorX', ...
                'omegaGaugeAnchorValue','omegaGaugeAnchorCondition', ...
                'omegaGaugeAnchorRateResidual', ...
                'omegaGaugeReferenceAnchorValue'}];
        case {'anchor_wall_window_l2','anchor_wall_window_l4', ...
                'outer_wall_density_window_l2'}
            gaugeNames = [gaugeNames,{'omegaGaugeEnergy', ...
                'omegaGaugeResidual','omegaGaugeWindowCenter', ...
                'omegaGaugeWindowRadius','omegaGaugeWindowValue', ...
                'omegaGaugeWindowCondition','omegaGaugeWindowEnergy', ...
                'omegaGaugeWindowRateResidual', ...
                'omegaGaugeReferenceWindowValue', ...
                'omegaGaugeWindowMomentOrder','omegaGaugeWindowMoment', ...
                'omegaGaugeWindowSupportPoints', ...
                'omegaGaugeWindowRateScale'}];
        case 'anchor_wall_template_projection'
            gaugeNames = [gaugeNames,{'omegaGaugeEnergy', ...
                'omegaGaugeResidual','omegaGaugeTemplateCenter', ...
                'omegaGaugeTemplateRadius', ...
                'omegaGaugeTemplateSupportPoints', ...
