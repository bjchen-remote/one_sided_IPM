function data=withResidualNorm(data)
%IPM.OUTPUT.WITHRESIDUALNORM Expose the recorded full-domain infinity norm.
% This is a column-vector alias, not a recomputation or a selected-frame norm.
assert(isfield(data,'tau') && isfield(data,'fullRateNorm') && ...
    isnumeric(data.fullRateNorm) && isreal(data.fullRateNorm) && ...
    isvector(data.fullRateNorm) && numel(data.fullRateNorm)==numel(data.tau), ...
    'ipm:DatasetResidualNorm','fullRateNorm must align with the scalar tau history.');
values=data.fullRateNorm(:);
if isfield(data,'residual_inf')
    assert(isequaln(data.residual_inf(:),values), ...
        'ipm:DatasetResidualNormConflict','residual_inf disagrees with fullRateNorm.');
end
data.residual_inf=values;
if ~isfield(data,'meta'),data.meta=struct();end
if ~isfield(data.meta,'definitions'),data.meta.definitions=struct();end
data.meta.definitions.residual_inf= ...
    ['Full native domain max(abs(partial_tau(R_X))), including boundary nodes; ' ...
     'absolute, unweighted, aligned to data.tau; alias of fullRateNorm; ' ...
     'NaN denotes an unrecorded observation.'];
end
