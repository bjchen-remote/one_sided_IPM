function data = dataSeries(state,solverLog,observations)
%IPM.OUTPUT.DATASERIES Publish canonical scalar history without duplicate logs.
% Observations are a scalar structure of column vectors tau, step,
% fullRateNorm, and coreRateNorm. Older history rows without an observation
% remain NaN; this function never reconstructs a residual from output frames.

if nargin < 3 || isempty(observations)
    observations = struct('tau',[],'step',[], ...
        'fullRateNorm',[],'coreRateNorm',[]);
end
history = solverLog.history;
common = history.common;
assert(isstruct(common) && isscalar(common) && ...
    isfield(common,'canonicalTau') && ~isempty(common.canonicalTau), ...
    'ipm:DataSeriesEmpty','At least one recorded accepted state is required.');
count = numel(common.canonicalTau);
data = struct('schemaVersion',2,'kind','ipm_plot_dataset');

% Each raw common vector has one authoritative location. These concise
% plotting names replace their source names rather than copying common.
mapping = { ...
    'tau','canonicalTau';'t','physicalTime';'normalizedTime','t'; ...
    'step','acceptedStep';'cl','canonicalCL';'co','canonicalCOmega'; ...
    'cr','canonicalCR';'cx','canonicalCX';'cy','canonicalCY'; ...
    'Cx','C_x';'Cy','C_y';'Comega','C_omega';'Xshift','X_shift'; ...
    'M','physicalRhoXInf';'MR','rhoXInf'; ...
    'xp','physicalTrackedPeakX'; ...
    'gradientPhysicalInf','physicalGradInf'; ...
    'velocityRescaledInf','uInf'; ...
    'minimumDx','physicalMinimumDx';'minimumDy','physicalMinimumDy'};
consumed = cell(0,1);
aliases = struct();
for k = 1:size(mapping,1)
    target = mapping{k,1};
    source = mapping{k,2};
    data.(target) = series(common,source,count);
    if isfield(common,source)
        consumed{end+1,1} = source; %#ok<AGROW>
        aliases.(source) = target;
    end
end
assert(all(isfinite(data.tau)) && all(diff(data.tau) > 0), ...
    'ipm:DataSeriesClock','Recorded canonical times must be finite and increasing.');
assert(all(isfinite(data.step)) && all(diff(data.step) > 0), ...
    'ipm:DataSeriesStep','Recorded accepted steps must be finite and increasing.');
data.Cs = data.cx./(data.cx-data.co);
data.logM = log(data.M);
data.inverseM = 1./data.M;
data.Xp = data.Cx.*data.xp+data.Xshift;

% A scalar max hypot(U1,U2) cannot recover the anisotropic physical speed
% maximum. Preserve an exact recorded physical maximum if one is available;
% otherwise only isotropic rows admit the scalar conversion.
if isfield(common,'physicalUInf')
    data.velocityPhysicalInf = series(common,'physicalUInf',count);
    consumed{end+1,1} = 'physicalUInf';
    aliases.physicalUInf = 'velocityPhysicalInf';
else
    data.velocityPhysicalInf = NaN(count,1);
    isotropic = data.Cx == data.Cy;
    data.velocityPhysicalInf(isotropic) = ...
        data.velocityRescaledInf(isotropic)./data.Comega(isotropic);
end

% Remove only known aliases with exactly equal values. Distinct clocks or
% normalized rates in older histories remain intact in diagnostics.common.
equivalent = {'C_l','Cx';'c_l','cl';'c_x','cx';'c_y','cy'; ...
    'c_omega','co';'c_r','cr';'omegaInf','MR';'physicalOmegaInf','M'};
for k = 1:size(equivalent,1)
    source = equivalent{k,1}; target = equivalent{k,2};
    if isfield(common,source) && ...
            isequaln(common.(source)(:),data.(target))
        consumed{end+1,1} = source; %#ok<AGROW>
        aliases.(source) = target;
    end
end
data.diagnostics = struct('common',struct());
names = fieldnames(common);
for k = 1:numel(names)
    name = names{k};
    if ~ismember(name,consumed)
        data.diagnostics.common.(name) = common.(name);
    end
end
groups = fieldnames(history);
for k = 1:numel(groups)
    if ~strcmp(groups{k},'common')
        data.diagnostics.(groups{k}) = history.(groups{k});
    end
end

mesh = history.mesh;
data.wxCore = series(mesh,'trackedWallCoreWidth',count)./data.Cx;
data.wyCore = series(mesh,'trackedVerticalCoreWidth',count)./data.Cy;
data.coreLevel = state.config.scaling.adaptiveLevels(end);
data.fullRateNorm = NaN(count,1);
data.coreRateNorm = NaN(count,1);
validateObservations(observations);
if ~isempty(observations.tau)
    keys = [observations.tau(:),observations.step(:)];
    [~,last] = unique(keys,'rows','last');
    [found,row] = ismember(keys(last,:),[data.tau,data.step],'rows');
    latest = last(found);
    data.fullRateNorm(row(found)) = observations.fullRateNorm(latest);
    data.coreRateNorm(row(found)) = observations.coreRateNorm(latest);
end
data.trustedMask = ipm.output.trustedMask(history,state.config);
data.continuousTrustedPrefix = ...
    ipm.output.continuousTrustedPrefix(data.trustedMask);
data.analysis = struct();
data.meta = struct('caseId',state.runMetadata.caseId, ...
    'config',state.config,'runMetadata',state.runMetadata, ...
    'sourceCommonNames',aliases, ...
    'scalarSampling','accepted solver history; all top-level series are column vectors aligned to tau', ...
    'fieldSampling','independent sparse accepted-state frames on their own native grids', ...
    'fieldAxisOrder','y,x', ...
    'nativeCoordinates','X=Cx*x_physical+Xshift; Y=Cy*y_physical; frame.x and frame.y contain X and Y', ...
    'densityDefinition','R(X,Y,tau)=Comega*rho_physical', ...
    'wDefinition','R_X; the solver Poisson source', ...
    'residualDefinition','rho_xt=partial_tau(R_X)=accepted rhoRate*Dx transpose at fixed computational X,Y', ...
    'rho_tDefinition','rho_t=partial_tau R; the name denotes the saved native density RHS', ...
    'residualClock','canonical tau; no time or space interpolation and no neighbouring-frame differences', ...
    'residualCore','native nodes satisfying -2<=X<=2 and 0<=Y<=2', ...
    'scalarAvailability','fullRateNorm/coreRateNorm are NaN where no native accepted-state observation was recorded; NaN is not convergence', ...
    'velocityPhysicalAvailability','exact recorded physicalUInf if available; otherwise uInf/Comega for Cx=Cy and NaN for anisotropic rows', ...
    'compositeVelocityDefinition','saved transport_u1=U1+cx*X+cr and transport_u2=U2+cy*Y; computational X,Y per canonical tau; selectTime exposes vx/vy/vmag', ...
    'physicalVelocityDefinition','u1_physical=U1/Comega; u2_physical=(Cx/Cy)*U2/Comega; speed=max hypot(u1_physical,u2_physical)', ...
    'widthDefinition','wxCore/wyCore are tracked widths at config.scaling.adaptiveLevels(end), not 90 percent widths', ...
    'CsDefinition','Cs=cx/(cx-co), the exponent based on the horizontal density gradient', ...
    'rateDefinition','cl/co/cr/cx/cy are canonical rates; unequal normalized rates are retained in diagnostics.common', ...
    'timeDefinition','tau is canonical time; t is physical time; normalizedTime preserves the solver history t', ...
    'missingValue','NaN means unavailable or an unmeasured quantity');
data=ipm.output.withResidualNorm(data);
end

function values = series(group,name,count)
if isfield(group,name)
    values = group.(name);
    assert(isnumeric(values) && isreal(values) && numel(values) == count, ...
        'ipm:DataSeriesShape','Recorded series %s must have %d values.',name,count);
    values = values(:);
else
    values = NaN(count,1);
end
end

function validateObservations(observations)
assert(isstruct(observations) && isscalar(observations), ...
    'ipm:DataSeriesObservations','Observations must be one structure of column vectors.');
names = {'tau','step','fullRateNorm','coreRateNorm'};
for k = 1:numel(names)
    name = names{k};
    assert(isfield(observations,name) && ...
        isnumeric(observations.(name)) && isreal(observations.(name)), ...
        'ipm:DataSeriesObservations','Observation field %s must be numeric and real.',name);
    assert(isempty(observations.(name)) || isvector(observations.(name)), ...
        'ipm:DataSeriesObservations','Observation field %s must be a vector.',name);
    assert(numel(observations.(name)) == numel(observations.tau), ...
        'ipm:DataSeriesObservations','Observation vectors must have equal lengths.');
end
assert(all(isfinite(observations.tau(:))) && ...
    all(isfinite(observations.step(:))), ...
    'ipm:DataSeriesObservations','Observation times and steps must be finite.');
assert(all(isfinite(observations.fullRateNorm(:))) && ...
    all(observations.fullRateNorm(:) >= 0) && ...
    all(isnan(observations.coreRateNorm(:)) | ...
        (isfinite(observations.coreRateNorm(:)) & observations.coreRateNorm(:) >= 0)), ...
    'ipm:DataSeriesObservations','Residual norms must be nonnegative; only unavailable core norms may be NaN.');
end
