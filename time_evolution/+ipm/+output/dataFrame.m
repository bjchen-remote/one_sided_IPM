function frame = dataFrame(state)
%IPM.OUTPUT.DATAFRAME Read one accepted state as native plotting fields.
% No flow, RHS, or time integration is recomputed here. Every array is [y,x]
% on this frame's own mesh; different frames may have different node counts.

if ~isfield(state,'rhsCache') || ~isstruct(state.rhsCache) || ...
        ~isscalar(state.rhsCache)
    error('ipm:DataFrameMissingCache', ...
        'An exact accepted-state RHS cache is required to publish a frame.');
end
cache = state.rhsCache;
ops = state.ops;
flow = state.flow;
scale = state.scale;
required = {'rho','scale','x','y','remeshCount','rhoRate'};
for k = 1:numel(required)
    assert(isfield(cache,required{k}),'ipm:DataFrameCacheField', ...
        'The accepted RHS cache is missing %s.',required{k});
end
assert(isequal(cache.rho,state.rho) && isequal(cache.scale,scale) && ...
    isequal(cache.x,ops.x) && isequal(cache.y,ops.y) && ...
    isequal(cache.remeshCount,ops.remeshCount), ...
    'ipm:DataFrameStaleCache', ...
    'The RHS cache must match the accepted field, scale, mesh, and remesh count.');

x = ops.x(:).';
y = ops.y(:);
shape = [numel(y),numel(x)];
assert(isequal(size(state.rho),shape) && ...
    isequal(size(cache.rhoRate),shape), ...
    'ipm:DataFrameShape','Accepted fields must have shape [y,x].');
assert(all(isfinite(state.rho),'all') && ...
    all(isfinite(cache.rhoRate),'all'), ...
    'ipm:DataFrameNonfinite','Only finite accepted fields can be published.');

Cx = exp(scale.logC_l);
if strcmp(ops.dynamicScaleGeometry,'anisotropic')
    Cy = exp(scale.logC_y);
else
    Cy = Cx;
end
Comega = exp(scale.logC_omega);
rhoRate = cache.rhoRate;
rhoXRate = rhoRate*ops.Dx';
coreX = x >= -2 & x <= 2;
coreY = y >= 0 & y <= 2;
if any(coreX) && any(coreY)
    coreRateNorm = max(abs(rhoXRate(coreY,coreX)),[],'all');
else
    coreRateNorm = NaN;
end
if isfield(flow,'psiLow') && ~isempty(flow.psiLow)
    psiLow = flow.psiLow;
else
    psiLow = zeros(shape,'like',state.rho);
end

frame = struct('schemaVersion',1, ...
    'tau',scale.canonicalTime,'t',scale.physicalTime,'step',state.step, ...
    'x',x,'y',y,'rho',state.rho,'w',flow.source, ...
    'rho_t',rhoRate,'rho_xt',rhoXRate,'rho_y',ops.Dy*state.rho, ...
    'psi',flow.psi,'psiLow',psiLow,'u1',flow.u1,'u2',flow.u2, ...
    'transport_u1',flow.transportU1,'transport_u2',flow.transportU2, ...
    'Cx',Cx,'Cy',Cy,'Comega',Comega,'Xshift',scale.X_shift, ...
    'remeshCount',ops.remeshCount, ...
    'fullRateNorm',max(abs(rhoXRate),[],'all'), ...
    'coreRateNorm',coreRateNorm,'caseId',state.runMetadata.caseId);

fieldNames = {'rho','w','rho_t','rho_xt','rho_y','psi','psiLow', ...
    'u1','u2','transport_u1','transport_u2'};
for k = 1:numel(fieldNames)
    values = frame.(fieldNames{k});
    assert(isequal(size(values),shape) && all(isfinite(values),'all'), ...
        'ipm:DataFrameField','Frame field %s must be finite and [y,x].', ...
        fieldNames{k});
end
assert(all(isfinite([Cx,Cy,Comega])) && all([Cx,Cy,Comega] > 0), ...
    'ipm:DataFrameScale','Frame scale factors must be finite and positive.');
end
