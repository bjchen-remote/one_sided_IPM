function cache = makeRhsCache(rho,rhoRate,flow,ops,scale)
%IPM.EVOLVE.MAKERHSCACHE Pack a transient exact accepted-state RHS cache.
%   The cache is derived data. Checkpoints deliberately omit it and rebuild
%   it from the restored accepted field, grid, and scale.

isAnisotropic = strcmp(ops.dynamicScaleGeometry,'anisotropic');
if isAnisotropic
    scaleRate = [flow.c_x;flow.c_y;flow.c_omega; ...
        exp(scale.logC_omega-scale.logC_l); ...
        flow.c_x*scale.X_shift+flow.c_r;1];
else
    scaleRate = [flow.c_l;flow.c_omega; ...
        exp(scale.logC_omega-scale.logC_l); ...
        flow.c_l*scale.X_shift+flow.c_r;1];
end
if isfield(scale,'densityOrigin')
    assert(~isAnisotropic,'ipm:PrecisionStateGeometry', ...
        'Optional densityOrigin requires isotropic SSPRK3.');
    validateattributes(scale.densityOrigin,{'double'}, ...
        {'real','finite','scalar'},mfilename,'scale.densityOrigin');
    validateattributes(flow.densityOriginRate,{'double'}, ...
        {'real','finite','scalar'},mfilename,'flow.densityOriginRate');
    scaleRate = [scaleRate;flow.densityOriginRate];
end
if isfield(scale,'physicalTimeLow')
    assert(~isAnisotropic,'ipm:PrecisionStateGeometry', ...
        'Optional physicalTimeLow requires isotropic SSPRK3.');
    validateattributes(scale.physicalTimeLow,{'double'}, ...
        {'real','finite','scalar'},mfilename,'scale.physicalTimeLow');
end
% The clock low is not an ODE component. The cached scalar-rate vector
% contains only the original five/six entries and optional densityOrigin.
expectedRates = 5+double(isAnisotropic)+double(isfield(scale,'densityOrigin'));
assert(isequal(size(scaleRate),[expectedRates,1]), ...
    'ipm:RhsCacheScaleRateSize','Cached scalar rates must match the packed state.');
if isfield(ops,'spatialOperators')
    assert(isfield(ops,'spatialGeometryKey')&&~isempty(ops.spatialGeometryKey), ...
        'ipm:SpatialGeometryKey','A spatial backend must bind its actual geometry and operator version.');
    cache = struct('schemaVersion',1,'geometry',ops.dynamicScaleGeometry, ...
        'remeshCount',ops.remeshCount,'spatialGeometryKey',ops.spatialGeometryKey, ...
        'spatialOperators',ops.spatialOperators,'rho',rho,'scale',scale, ...
        'rhoRate',rhoRate,'scaleRate',scaleRate,'gaugeRates',[flow.c_l,flow.c_r]);
else
    cache = struct('schemaVersion',1, ...
        'geometry',ops.dynamicScaleGeometry, ...
        'remeshCount',ops.remeshCount,'x',ops.x,'y',ops.y, ...
        'rho',rho,'scale',scale,'rhoRate',rhoRate, ...
        'scaleRate',scaleRate,'gaugeRates',[flow.c_l,flow.c_r]);
end
if isfield(flow,'peakTrackingAnchor')
    cache.peakTrackingAnchor = flow.peakTrackingAnchor;
end
end
