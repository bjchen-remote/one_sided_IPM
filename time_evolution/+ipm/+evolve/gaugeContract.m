function contract = gaugeContract(config,ops)
%IPM.EVOLVE.GAUGECONTRACT Serializable description of the active gauges.
%   This is provenance only.  It contains no state and cannot feed back into
%   the evolution.  Formula strings name the exact discrete quantities used
%   by isotropicGauge so saved results remain interpretable after a campaign.

scaling = config.scaling;
contract = struct( ...
    'schemaVersion',2, ...
    'scalingContract',scaling.scalingContract, ...
    'clock','canonical_tau_direct', ...
    'timeSpeed',1, ...
    'rateEvolution',struct( ...
        'logCl','d(log(C_l))/d(tau)=c_l', ...
        'logComega','d(log(C_omega))/d(tau)=c_omega', ...
        'physicalTime','dt/d(tau)=C_omega/C_l'), ...
    'rescaledEquation', ...
        'R_tau=-(U+(c_l*X+c_r,c_l*Y))*grad(R)+c_omega*R', ...
    'physicalGradient', ...
        'max_abs_rho_x=(C_l/C_omega)*max_abs_R_X', ...
    'feedback',struct('lengthScaleGain',1,'widthGaugeGain',0, ...
        'omegaGaugeGain',0,'travelingWaveGain',0, ...
        'rateLimiter','absent'), ...
    'length',length_contract(scaling,ops), ...
    'amplitude',amplitude_contract(scaling), ...
    'travelingWave',traveling_wave_contract(scaling));
if any(strcmp(scaling.lengthGauge, ...
        {'wall_gradient_curvature','wall_gradient_integral'}))
    contract.feedback.peakPositionRestoringRate = ...
        scaling.peakPositionRestoringRate;
end
if strcmp(scaling.cOmegaGauge,'wall_omega_tracked_spline_peak')
    contract.peakReconstruction='tracked_natural_cubic_spline';
    contract.peakObservablePreserved=false;
    contract.travelingWave.observable='continued_stationary_spline_peak_phase';
    contract.travelingWave.formula='S_x[B_X](a)/(-S_xx[R_X](a))+kappa*a=0';
end
if strcmp(scaling.scalingContract,'wall_integral_generators_v2')
    % The signed split changes spatial transport and preserves the declared
    % integral, peak-amplitude, and phase constraints. Spline provenance
    % above remains active when both candidate selectors are enabled.
    contract.productionSpatialOperatorPreserved=false;
    contract.transport = struct( ...
        'name','fixed_signed_generator_weno5_fd', ...
        'physical','assemble_WENO(U,R)_once_per_field', ...
        'length','assemble_WENO(plus_or_minus_(X,Y),R)_once_per_field', ...
        'translation','assemble_WENO(plus_or_minus_(1,0),R)_once_per_field', ...
        'assembly','combine_fixed_basis_with_absolute_generator_rates', ...
        'gaugeSolve','one_linear_3_by_3_system_per_sign_quadrant', ...
        'acceptance','sign_consistency_and_original_full_RHS_gauge_defects', ...
        'cfl','physical_rate_plus_absolute_generator_rate_sum');
end
if strcmp(scaling.scalingContract,'wall_integral_centered_generators_v3')
    % Uref depends on the current field's declared peak and is frozen before
    % solving the rates. The signed translation rate is delta, while the
    % persisted scaling trajectory continues to use c_r=delta-Uref.
    contract.productionSpatialOperatorPreserved=false;
    contract.transport = struct( ...
        'name','centered_signed_generator_weno5_fd', ...
        'referenceVelocity','Uref=interp1(x,U1(1,:),a,''linear'')', ...
        'referenceEvaluation','frozen_once_per_field_at_declared_peak', ...
        'physical','assemble_WENO((U1-Uref,U2),R)_once_per_field', ...
        'length','assemble_WENO(plus_or_minus_(X,Y),R)_once_per_field', ...
        'translation','assemble_WENO(plus_or_minus_(1,0),R)_once_per_field', ...
        'translationRate','delta=c_r+Uref', ...
        'physicalTranslationRate','c_r=delta-Uref', ...
        'assembly','combine_fixed_basis_with_absolute_c_l_and_delta_rates', ...
        'gaugeSolve','one_linear_3_by_3_system_per_c_l_delta_sign_quadrant', ...
        'gaugeUnknowns','abs(c_l),abs(delta),c_omega', ...
        'acceptance','sign_consistency_and_original_full_RHS_gauge_defects', ...
        'cfl','centered_physical_max_plus_absolute_dilation_and_delta_translation_maxima', ...
        'cflMask','forbidden');
end
if strcmp(scaling.scalingContract,'wall_integral_centroid_practical_v1')
    contract.peakReconstruction='global_full_domain_C2_natural_cubic_spline_maximum';
    contract.peakObservablePreserved=false;
    contract.productionSpatialOperatorPreserved=false;
    contract.exactPeakPinning=false;
    contract.feedback=rmfield(contract.feedback,'peakPositionRestoringRate');
    contract.feedback.centroidRestoringRate=scaling.peakPositionRestoringRate;
    contract.length.formula= ...
        'solve I_B/I=P_B/P; c_omega=-P_B/P, I=int_{-L}^{L}R_X(X,0)dX';
    contract.length.registeredParameters=struct('wallIntegralRadius',scaling.wallIntegralRadius);
    contract.amplitude.formula='c_omega=-S[B_X](a_max)/S[R_X](a_max)';
    contract.amplitude.observable='global_full_domain_C2_natural_cubic_spline_maximum';
    contract.amplitude.evaluation='all_nodes_endpoints_and_real_stationary_points';
    contract.amplitude.tieDerivative='selected_maximizer_evaluation_not_a_unique_maximum_derivative';
    contract.travelingWave.observable='fixed_window_wall_R_X_squared_centroid';
    contract.travelingWave.formula='C_tau=-kappa*(C-C0)';
    contract.travelingWave.definition='C=sum(w*X*q^2)/sum(w*q^2), q=R_X on clipped [-L,L]';
    contract.travelingWave.evaluation='positive_trapezoidal_weights_and_piecewise_linear_endpoint_samples';
    contract.travelingWave.reference='C0=initial_C_persisted_as_referenceWallGradientCentroid';
    contract.travelingWave.exactPeakPinning=false;
    contract.transport=struct( ...
        'name','centered_signed_generator_weno5_fd', ...
        'referenceVelocity','Uref=interp1(x,U1(1,:),C,''linear'')', ...
        'referenceEvaluation','frozen_once_per_field_at_wall_gradient_centroid', ...
        'physical','assemble_WENO((U1-Uref,U2),R)_once_per_field', ...
        'length','assemble_WENO(plus_or_minus_(X,Y),R)_once_per_field', ...
        'translation','assemble_WENO(plus_or_minus_(1,0),R)_once_per_field', ...
        'translationRate','delta=c_r+Uref', ...
        'physicalTranslationRate','c_r=delta-Uref', ...
        'gaugeSolve','one_linear_3_by_3_system_per_c_l_delta_sign_quadrant', ...
        'gaugeUnknowns','abs(c_l),abs(delta),c_omega', ...
        'cfl','centered_physical_max_plus_absolute_dilation_and_delta_translation_maxima', ...
        'cflMask','forbidden');
    contract.acceptance=struct('gaugeRootGate',1e-6,'fullRhsGaugeAuditGate',1e-5, ...
        'quality','finite_state_full_generator_CFL_valid_mesh', ...
        'diagnosticOnly',{{'wall_TV','wall_peak_count','density_range', ...
        'positiveWallNegativeRatio','feature_point_count'}}, ...
        'peakCurvatureOrBranchGate','absent');
    assembly='signed_generators';
    if isfield(scaling,'gaugeTransportAssembly'),assembly=scaling.gaugeTransportAssembly;end
    contract.transport.assemblySelector=assembly;
    if ismember(assembly,{'net_velocity','net_velocity_density_centered', ...
            'net_velocity_density_centered_advective'})
        contract.transport=struct('name','centered_net_velocity_weno5_fd', ...
            'assemblySelector',assembly, ...
            'referenceVelocity','Uref=interp1(x,U1(1,:),C,''linear'')', ...
            'referenceEvaluation','frozen_once_per_field_at_wall_gradient_centroid', ...
            'assembly','one_WENO_assembly_at_(U1-Uref+c_l*X+delta,U2+c_l*Y)', ...
            'translationRate','delta=c_r+Uref','physicalTranslationRate','c_r=delta-Uref', ...
            'gaugeSolve','finite_difference_Newton_on_original_I_over_P_and_centroid_equations', ...
            'gaugeUnknowns','c_l,delta; c_omega=-P_B/P', ...
            'rootEvaluation','complete_wall_only_operator_exactly_equivalent_to_full_assembly', ...
            'acceptance','one_complete_2D_RHS_assembly_and_I_P_C_audit', ...
            'cfl','maximum_actual_net_velocity_over_J_times_computational_spacing', ...
            'legacyGeneratorCflRateColumn','actual_net_transport_rate_in_this_selected_assembly', ...
            'cflMask','forbidden');
        contract.acceptance.quality='finite_state_full_net_CFL_valid_mesh';
        if ismember(assembly,{'net_velocity_density_centered','net_velocity_density_centered_advective'})
            contract.transport.name='density_centered_net_velocity_weno5_fd';
            contract.transport.transportDensity='R-R(1,argmin(abs(X)))_inside_WENO_only';
            contract.transport.densityAnchor='wall_node_nearest_origin_recomputed_on_current_mesh';
            contract.transport.amplitudeSource='c_omega_times_original_R';
            contract.transport.physicalVelocityAndObservables='original_R_unchanged';
            contract.transport.constantOffsetSymmetry='transport_invariant_up_to_roundoff';
        end
        if strcmp(assembly,'net_velocity_density_centered_advective')
            contract.transport.name='density_centered_net_velocity_advective_weno5_fd';
            contract.transport.assembly='minus_(Vplus_Dplus_R_plus_Vminus_Dminus_R)_per_direction';
            contract.transport.gradient='computational_WENO5_density_derivatives_with_dummy_plus_or_minus_1_and_metric_1_then_divide_by_physical_J';
            contract.transport.nonlinearWeights='density_only; physical_net_velocity_does_not_enter_WENO_weights';
            contract.transport.boundary='both_derivative_directions_share_actual_net_velocity_inflow_masks; original_density_degree_on_artificial_inflow_only';
            contract.transport.wall='same_density_gradient_transport_with_exact_zero_normal_velocity';
        end
    end
end
end

function value = traveling_wave_contract(scaling)
value = struct('name',scaling.travelingWaveGauge,'formula','', ...
    'observable','wall_gradient_peak_phase');
if strcmp(scaling.travelingWaveGauge,'gradient_peak')
    if any(strcmp(scaling.lengthGauge, ...
            {'wall_gradient_curvature','wall_gradient_integral'}))
        value.formula = ...
            ['c_r solves vertex_phase(D_x baseRhs)=' ...
            'kappa*X_peak*vertex_curvature'];
    else
        value.formula = ...
            ['c_r solves derivative_at_quadratic_vertex(' ...
            'D_x baseRhs(c_r))=0'];
    end
    value.observable = 'discrete_wall_gradient_peak_phase';
else
    value.formula = 'c_r=-U1(X_peak,0)-c_l*X_peak';
    value.observable = 'zero_peak_transport_velocity';
end
end

function value = length_contract(scaling,ops)
value = struct('name',scaling.lengthGauge,'formula','', ...
    'observable','','evaluation','discrete_algebraic', ...
    'registeredParameters',struct(), ...
    'phaseInterpretation','not_applicable', ...
    'anchorX',NaN,'nearestGridNode',NaN,'anchorNodeDistance',NaN, ...
    'anchorIsGridNode',false);
switch scaling.lengthGauge
    case 'omega_peak_location'
        value.formula = ...
            'c_l=physicalRhs_XX(X_peak)/(X_peak*R_XXX(X_peak))';
        value.observable = 'wall_omega_peak_location';
        value.evaluation = ...
            'quadratic_R_X_peak_then_linear_Dx_field_interpolation';
        value.registeredParameters = struct( ...
            'peakTrackingWidthFactor',scaling.peakTrackingWidthFactor);
        value.phaseInterpretation = ...
            'algebraic_candidate_with_recorded_full_phase_defect';
    case 'wall_omega_width'
        value.formula = 'c_l=-physical_width_rate/current_width';
        value.observable = 'wall_omega_level_width';
        value.evaluation = 'piecewise_linear_level_crossings';
        selectedLevel = max(scaling.adaptiveLevels);
        value.registeredParameters = struct( ...
            'adaptiveLevels',scaling.adaptiveLevels(:)', ...
            'selectedWidthLevel',selectedLevel, ...
            'selectionRule','maximum_adaptive_level');
    case 'wall_gradient_curvature'
        value.formula = ...
            ['solve c_l,c_r so Kdot_base/K=Pdot_base/P and ' ...
            'a_tau=-kappa*a; K is fixed-window polynomial ' ...
            'curvature evaluated at moving peak'];
        value.observable = 'tracked_wall_gradient_peak_curvature';
        value.evaluation = ...
            'fixed_origin_window_degree_four_weighted_least_squares';
        value.registeredParameters = struct( ...
            'peakPositionRestoringRate', ...
            scaling.peakPositionRestoringRate, ...
            'peakCurvatureRadius',scaling.peakCurvatureRadius);
    case 'wall_gradient_integral'
        value.formula = ...
            ['solve c_l,c_r so I_B/I=P_B/P and a_tau=-kappa*a; ' ...
            'c_omega=-P_B/P, I=int_{-L}^{L}R_X(X,0)dX'];
        value.observable = 'fixed_origin_wall_gradient_integral';
        value.evaluation = 'clipped_piecewise_linear_DxR_wall_quadrature';
        value.registeredParameters = struct( ...
            'peakPositionRestoringRate',scaling.peakPositionRestoringRate, ...
            'wallIntegralRadius',scaling.wallIntegralRadius);
    case 'symmetry_peak'
        value.formula = ...
            'c_l=-(U1(X_peak,0)-U1(0,0))/(X_peak-0)';
        value.observable = 'peak_separation';
        value.evaluation = ...
            'quadratic_R_X_peak_then_linear_velocity_interpolation';
        value.registeredParameters = struct( ...
            'peakTrackingWidthFactor',scaling.peakTrackingWidthFactor);
    case 'transport_anchor'
        anchorX = scaling.transportAnchorX;
        [distance,index] = min(abs(ops.x-anchorX));
        tolerance = 128*eps(max(1,max(abs(ops.x))));
        value.formula = 'c_l=-U1(X_anchor,0)/X_anchor';
        value.observable = 'V1(X_anchor,0)=0';
        value.evaluation = 'fixed_coordinate_linear_interpolation';
        value.anchorX = anchorX;
        value.registeredParameters = struct('transportAnchorX',anchorX);
        value.nearestGridNode = ops.x(index);
        value.anchorNodeDistance = distance;
        value.anchorIsGridNode = distance <= tolerance;
    case 'wall_density_width'
        value.formula = ...
            'c_l=-(U1(X_upper,0)-U1(X_lower,0))/(X_upper-X_lower)';
        value.observable = 'wall_density_level_width';
        value.evaluation = 'piecewise_linear_level_crossings';
        value.registeredParameters = struct( ...
            'lengthGaugeLevels',scaling.lengthGaugeLevels(:)');
    case 'local_strain'
        value.formula = 'c_l=-d_X(U1)(X_peak,0)';
        value.observable = 'wall_peak_local_strain';
        value.evaluation = ...
            'quadratic_R_X_peak_then_linear_strain_interpolation';
        value.registeredParameters = struct( ...
            'peakTrackingWidthFactor',scaling.peakTrackingWidthFactor);
end
end

function value = amplitude_contract(scaling)
value = struct('name',scaling.cOmegaGauge,'formula','', ...
    'observable','','evaluation','discrete_algebraic');
switch scaling.cOmegaGauge
    case 'gradient_energy'
        value.formula = [ ...
            'c_omega=-sum(w*(R_X*B_X+R_Y*B_Y))/' ...
            'sum(w*(R_X^2+R_Y^2))'];
        value.observable = 'global_discrete_gradient_energy';
        value.evaluation = 'fixed_grid_quadrature';
    case 'wall_omega_peak'
        value.formula = 'c_omega=-B_X(wall_peak)/R_X(wall_peak)';
        value.observable = 'wall_omega_peak';
        value.evaluation = 'active_peak_node';
    case 'wall_omega_quadratic_peak'
        value.formula = ...
            'c_omega=-Q[B_X](X_vertex)/Q[R_X](X_vertex)';
        value.observable = 'tracked_wall_omega_quadratic_peak';
        value.evaluation = ...
            'active_nonuniform_three_node_quadratic_vertex';
    case 'wall_omega_tracked_spline_peak'
        value.formula = 'c_omega=-S[B_X](a)/S[R_X](a)';
        value.observable = 'tracked_wall_omega_natural_cubic_spline_peak';
        value.evaluation = 'continued_C2_stationary_peak_fixed_physical_window';
    case 'strain_point'
        value.formula = ...
            'c_omega=-d_X(U1[B])(0,0)/d_X(U1[R])(0,0)';
        value.observable = 'origin_strain';
    case 'anchor_wall_slope'
        value.formula = 'c_omega=-B_X(X_anchor,0)/R_X(X_anchor,0)';
        value.observable = 'fixed_anchor_wall_slope';
        value.evaluation = 'fixed_coordinate_linear_interpolation';
    case 'anchor_wall_window_l2'
        value.formula = 'c_omega=-<R_X,B_X>_w/<R_X,R_X>_w';
        value.observable = 'fixed_wall_window_l2';
    case 'anchor_wall_window_l4'
        value.formula = 'c_omega=-<R_X^3,B_X>_w/<R_X^4>_w';
        value.observable = 'fixed_wall_window_l4';
    case 'outer_wall_density_window_l2'
        value.formula = 'c_omega=-<R,B>_w/<R,R>_w';
        value.observable = 'fixed_X2_wall_density_l2';
        value.evaluation = ...
            'raised_cosine_window_X2_radius_omegaGaugeWindowRadius';
    case 'anchor_wall_template_projection'
        value.formula = 'c_omega=-<B_X,T>_w/<R_X,T>_w';
        value.observable = 'fixed_wall_template_projection';
    case 'anchor_bulk_gradient_l2'
        value.formula = ...
            'c_omega=-<grad(R),grad(B)>_W/<grad(R),grad(R)>_W';
        value.observable = 'fixed_bulk_window_gradient_l2';
    case 'none'
        value.formula = 'C_omega=1, c_omega=0 (prescribed)';
        value.observable = 'material_density_identity_scale';
        value.evaluation = ...
            'prescribed_identity_scale_with_counterfactual_peak_diagnostic';
end
end
