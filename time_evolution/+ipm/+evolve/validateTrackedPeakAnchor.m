function validateTrackedPeakAnchor(anchor,x,window,expectedTau,allowTransferredGrid)
%VALIDATETRACKEDPEAKANCHOR Validate the persisted identity of one peak branch.
if nargin<4,expectedTau=[];end
if nargin<5,allowTransferredGrid=false;end
x=x(:)';window=window(:)';
required={'version','definition','x','tau','gridX','window','basin','cellWidth'};
valid=isstruct(anchor) && isscalar(anchor) && ...
    isempty(setxor(fieldnames(anchor),required)) && ...
    isequal(anchor.version,1) && ...
    ischar(anchor.definition) && strcmp(anchor.definition,'tracked_natural_cubic_spline') && ...
    isnumeric(anchor.x) && isreal(anchor.x) && isscalar(anchor.x) && isfinite(anchor.x) && ...
    isnumeric(anchor.tau) && isreal(anchor.tau) && isscalar(anchor.tau) && ...
    isfinite(anchor.tau) && anchor.tau>=0 && ...
    isnumeric(anchor.gridX) && isreal(anchor.gridX) && isrow(anchor.gridX) && ...
    numel(anchor.gridX)==numel(x) && all(isfinite(anchor.gridX)) && ...
    all(diff(anchor.gridX)>0) && ...
    isnumeric(anchor.window) && isreal(anchor.window) && isequal(anchor.window,window) && ...
    isnumeric(anchor.basin) && isreal(anchor.basin) && ...
    isequal(size(anchor.basin),[1,2]) && all(isfinite(anchor.basin)) && ...
    anchor.basin(1)<anchor.x && anchor.x<anchor.basin(2) && ...
    anchor.basin(1)>=window(1) && anchor.basin(2)<=window(2) && ...
    isnumeric(anchor.cellWidth) && isreal(anchor.cellWidth) && ...
    isscalar(anchor.cellWidth) && isfinite(anchor.cellWidth) && anchor.cellWidth>0;
if ~allowTransferredGrid,valid=valid && isequal(anchor.gridX,x);end
if ~isempty(expectedTau),valid=valid && isequal(anchor.tau,expectedTau);end
assert(valid,'ipm:TrackedPeakAnchor','Invalid continued-peak anchor.');
end
