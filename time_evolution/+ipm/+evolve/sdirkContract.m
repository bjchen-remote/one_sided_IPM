function contract=sdirkContract(method)
%SDIRKCONTRACT Shared versioned temporal controls, independent of geometry.
assert(any(strcmp(method,{'sdirk3_alexander_practical_v1', ...
    'sdirk3_alexander_practical_v2','sdirk3_alexander_practical_v3', ...
    'sdirk2_alexander_practical_v1','sdirk2_alexander_practical_v2'})), ...
    'ipm:SdirkContract','Select a supported versioned SDIRK method.');
gamma=.43586652150845899941601945;
A=[gamma,0,0;(1-gamma)/2,gamma,0; ...
    (-6*gamma^2+16*gamma-1)/4,(6*gamma^2-20*gamma+5)/4,gamma];
contract=struct('id','sdirk3_alexander_practical_v1','order',3, ...
    'A',A,'b',A(3,:),'c',[gamma;(1+gamma)/2;1],'gamma',gamma, ...
    'maximumNewtonIterations',5,'gmresRestart',12,'gmresCycles',1, ...
    'linearTolerance',.1,'jacobianDifferenceStep',1e-4, ...
    'maximumLineSearchBacktracks',6,'maximumStepRetries',6, ...
    'densityToleranceFloor',1e-10,'densityToleranceCeiling',1e-8, ...
    'densityToleranceCoefficient',1e-3, ...
    'rxToleranceFloor',1e-8,'rxToleranceCeiling',1e-7, ...
    'rxToleranceCoefficient',1e-2,'iluDropTolerance',1e-3, ...
    'nonlinearResidual','rho-known-gamma*h*complete_native_F', ...
    'jacobian','central_difference_complete_native_F_including_Darcy_and_gauge', ...
    'preconditioner','row_balanced_I_minus_gamma_h_frozen_first_order_upwind_plus_comega_ILU', ...
    'stabilityScope','classical_linear_L_stability_not_SSP_or_nonlinear_unconditional_stability', ...
    'primaryCoefficientSource','https://www.math.auckland.ac.nz/~butcher/ODE-book-2008/Tutorials/IRK.pdf#page=22');
if any(strcmp(method,{'sdirk3_alexander_practical_v2','sdirk3_alexander_practical_v3'}))
    contract.id=method;
    contract.maximumNewtonIterations=10;
    contract.preconditionerDefectTrials=4;
    contract.preconditionerDefectRequiredReduction=.5;
    contract.directionPolicy='first_four_ILU_defect_trials_require_actual_full_native_merit_halving; otherwise_complete_central_Jv_GMRES';
    contract.realizedCflDefinition='maximum_initial_converged_implicit_stages_and_terminal_full_rates; timeStep.rate remains initial full rate';
end
if strcmp(method,'sdirk3_alexander_practical_v3')
    % Same converged stage equations; reduce complete-native Jv truncation.
    contract.jacobianDifferenceStep=1e-5;
end
if any(strcmp(method,{'sdirk2_alexander_practical_v1','sdirk2_alexander_practical_v2'}))
    gamma=1-1/sqrt(2);A=[gamma,0;1-gamma,gamma];
    contract.id=method;contract.order=2;contract.A=A;contract.b=A(2,:);
    contract.c=[gamma;1];contract.gamma=gamma;
    contract.maximumNewtonIterations=10;contract.jacobianDifferenceStep=1e-5;
    contract.preconditionerDefectTrials=4;contract.preconditionerDefectRequiredReduction=.5;
    contract.directionPolicy='first_four_ILU_defect_trials_require_actual_full_native_merit_halving; otherwise_complete_central_Jv_GMRES';
    contract.realizedCflDefinition='maximum_initial_converged_implicit_stages_and_terminal_full_rates; timeStep.rate remains initial full rate';
    contract.stageResidualPower=3;
    contract.primaryCoefficientSource='https://ntrs.nasa.gov/api/citations/20160005923/downloads/20160005923.pdf#page=76';
end
if strcmp(method,'sdirk2_alexander_practical_v2')
    contract.maximumNewtonIterations=24;
    contract.preconditionerDefectTrials=20;
    contract.directionPolicy='up_to_twenty_ILU_defect_trials_require_actual_full_native_merit_halving; otherwise_complete_central_Jv_GMRES';
end
end
