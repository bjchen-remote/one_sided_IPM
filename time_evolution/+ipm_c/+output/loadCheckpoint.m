function [cp,pointer]=loadCheckpoint(folder)
%LOADCHECKPOINT Versioned accepted-state restore, without migration.
pointer=jsondecode(fileread(fullfile(folder,'latest.json')));
assert(strcmp(pointer.kind,'ipm_c_centered_density_pointer_v4')&& ...
    any(strcmp(pointer.path,{fullfile(folder,'rolling_0.mat'),fullfile(folder,'rolling_1.mat')}))&& ...
    strcmp(ipm_c.output.sha256(pointer.path),pointer.sha256),'ipm_c:SharedCheckpointIdentity');
loaded=load(pointer.path,'checkpoint');cp=loaded.checkpoint;
assert(strcmp(cp.kind,'ipm_c_centered_density_checkpoint_v4')&& ...
    strcmp(cp.cfg.kind,'ipm_c_centered_density_direct_cfl_v4')&& ...
    cp.sequence==pointer.sequence&&cp.state.scale.canonicalTime==pointer.tau&& ...
    cp.state.scale.physicalTime==pointer.physicalTime&& ...
    cp.state.scale.physicalTimeLow==pointer.physicalTimeLow&& ...
    cp.state.scale.densityOrigin==pointer.densityOrigin&& ...
    strcmp(cp.stateRepresentation,'density_minus_origin')&& ...
    all(cp.state.rho(1,:)==0),'ipm_c:SharedCheckpointKind');
end
