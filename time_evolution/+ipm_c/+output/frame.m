function frame=frame(folder,state,history,saveFields)
%FRAME Publish an immutable native slice, its actual mesh, and scalar catalog.
% Geometry is shared by all slices on the same mesh. This reads numerical
% state only; data.mat stores trajectories without duplicating field arrays.
if nargin<4,saveFields=true;end
if ~saveFields
    saved=load(fullfile(folder,'data.mat'),'data');
    frames=saved.data.frames([saved.data.frames.step]<=state.step);
    assert(~isempty(frames),'ipm_c:DatasetEmpty');
    write_catalog(folder,trajectory(history,frames,saved.data.meta));frame=[];return;
end
g=state.ops.polarGrid;s=state.scale;flow=state.flow;
meshId=mesh_key(g.r,g.theta);meshFile=fullfile('grids',['mesh_',meshId,'.mat']);
publish_mesh(folder,meshFile,meshId,g);
derivatives=ipm_c.field.derivatives(state.rho,g,state.config.rhsOptions);
frame=struct('kind','ipm_c_centered_density_polar_frame_v4','schemaVersion',4, ...
    'step',state.step,'tau',s.canonicalTime,'t',s.physicalTime,'scale',s, ...
    'meshId',meshId,'meshFile',meshFile,'rho',state.rho+s.densityOrigin, ...
    'rho_centered',state.rho,'rho_origin',s.densityOrigin, ...
    'rho_tau_centered',state.rhsCache.rhoRate,'rho_origin_tau',flow.densityOriginRate, ...
    'transportOrigin',flow.transportOrigin, ...
    'rho_X',flow.source,'rho_Y',derivatives.ry, ...
    'rho_tau',state.rhsCache.rhoRate+flow.densityOriginRate, ...
    'Q',flow.fullQ,'psi',flow.psi,'u1',flow.u1,'u2',flow.u2, ...
    'vx',flow.transportU1,'vy',flow.transportU2, ...
    'c_l',flow.c_l,'c_omega',flow.c_omega,'c_r',flow.c_r, ...
    'remeshCount',state.ops.remeshCount,'diagnostics',diagnostics(state));
directory=fullfile(folder,'data_frames');if ~isfolder(directory),mkdir(directory);end
primary=state_key(state,meshId);
relative=fullfile('data_frames',sprintf('frame_step%012d_tau%s_%s.mat', ...
    state.step,num2hex(s.canonicalTime),primary(1:16)));
target=fullfile(folder,relative);
if isfile(target)
    old=load(target,'frame');
    assert(isequaln(old.frame.rho_centered,frame.rho_centered)&& ...
        isequaln(old.frame.rho_origin,frame.rho_origin)&&isequaln(old.frame.scale,frame.scale)&& ...
        strcmp(old.frame.meshId,meshId),'ipm_c:SharedImmutableFrame', ...
        'An immutable slice must retain its primary state and geometry.');
    for name={'rho_X','rho_Y','rho_tau','Q','psi','u1','u2','vx','vy'}
        previous=old.frame.(name{1});fresh=frame.(name{1});
        assert(isequal(size(previous),size(fresh))&& ...
            max(abs(previous-fresh),[],'all')<=1e-8*max(1,max(abs(previous),[],'all')), ...
            'ipm_c:SharedImmutableDerivedFrame','Restored fields disagree with the retained native slice.');
    end
    frame=old.frame;
else
    temporary=[target,'.writing.mat'];save(temporary,'frame','-v7.3');
    [ok,message]=movefile(temporary,target,'f');assert(ok,'ipm_c:FrameRename','%s',message);
end
catalog=struct('file',relative,'step',frame.step,'tau',frame.tau,'t',frame.t, ...
    'meshId',frame.meshId,'meshFile',frame.meshFile);
frames=catalog;datasetFile=fullfile(folder,'data.mat');previousMeta=struct();
if isfield(state,'runMetadata'),previousMeta=state.runMetadata;end
if isfile(datasetFile)
    old=load(datasetFile,'data');
    assert(isfield(old.data,'schemaVersion')&&old.data.schemaVersion==4, ...
        'ipm_c:DatasetSchema','Start a new output folder for a schema-4 trajectory.');
    % Restore can discard a published frame beyond the durable checkpoint.
    % Its immutable file remains intact; the catalog follows accepted history.
    previousMeta=old.data.meta;
    keep=[old.data.frames.step]<state.step;
    frames=[old.data.frames(keep),catalog];
end
write_catalog(folder,trajectory(history,frames,previousMeta));
% Return convenient coordinates without duplicating them in immutable files.
frame.r=g.r;frame.theta=g.theta;frame.X=g.X;frame.Y=g.Y;
end

function write_catalog(folder,data)
temporary=fullfile(folder,'data.writing.mat');save(temporary,'data','-v7.3');
[ok,message]=movefile(temporary,fullfile(folder,'data.mat'),'f');
assert(ok,'ipm_c:DatasetRename','%s',message);
end

function publish_mesh(folder,relative,id,g)
target=fullfile(folder,relative);if isfile(target),return;end
directory=fileparts(target);if ~isfolder(directory),mkdir(directory);end
grid=struct('kind','ipm_c_saved_polar_mesh_v1','meshId',id, ...
    'r',g.r(:),'theta',g.theta(:).','nr',g.nr,'ntheta',g.ntheta, ...
    'rmax',g.r(end),'firstSpacing',g.r(2),'domain','upper_half_disk', ...
    'coordinates','canonical_rescaled_cartesian','originIsSinglePhysicalPoint',true, ...
    'stencilWidth',g.stencilWidth,'originFitDegree',g.originFit.degree);
for name={'radialMap','radialMapParameter','uniformCoreInfo'}
    if isfield(g,name{1}),grid.(name{1})=g.(name{1});end
end
temporary=[target,'.writing.mat'];save(temporary,'grid','-v7.3');
[ok,message]=movefile(temporary,target,'f');assert(ok,'ipm_c:MeshRename','%s',message);
end

function id=mesh_key(r,theta)
d=java.security.MessageDigest.getInstance('SHA-256');
d.update(typecast(uint64([numel(r),numel(theta)]),'uint8'));
d.update(typecast(r(:),'uint8'));d.update(typecast(theta(:),'uint8'));
id=lower(reshape(dec2hex(typecast(d.digest(),'uint8'),2)',1,[]));
end

function id=state_key(state,meshId)
d=java.security.MessageDigest.getInstance('SHA-256');d.update(uint8(meshId));
d.update(typecast(state.rho(:),'uint8'));s=state.scale;
d.update(typecast([s.logC_l,s.logC_omega,s.X_shift,s.canonicalTime,s.physicalTime, ...
    s.physicalTimeLow,s.densityOrigin],'uint8'));
id=lower(reshape(dec2hex(typecast(d.digest(),'uint8'),2)',1,[]));
end

function result=diagnostics(state)
f=state.flow;
result=struct('poissonResidual',f.poissonResidual,'gaugeResidual',f.gaugeResidual, ...
    'wallIntegral',f.wallIntegral,'wallPeak',f.globalWallPeak,'wallCentroid',f.wallCentroid, ...
    'fullQInf',max(abs(f.fullQ),[],'all'), ...
    'rhoTauInf',max(abs(state.rhsCache.rhoRate+f.densityOriginRate),[],'all'), ...
    'mass',sum((state.rho+state.scale.densityOrigin).*state.ops.integrationWeights,'all'), ...
    'referenceVelocity',f.generatorReferenceVelocity, ...
    'translationRate',f.generatorTranslationRate,'mappedPolarCflRate',f.generatorCflRate, ...
    'poissonSolveInfo',f.poissonSolveInfo, ...
    'cflPosition',f.ipmCInfo.cflPosition,'gaugeRootCondition',f.generatorRootCondition, ...
    'wallPeakX',f.ipmCInfo.gauge.initialMeasurement.peak.x, ...
    'wallPeakTie',f.ipmCInfo.gauge.initialMeasurement.peak.tieNonunique);
end

function data=trajectory(history,frames,previousMeta)
names={'step','tau','t','H','Qinf','Finf','cl','cw','cr','rhoInf','poisson','gauge', ...
    'remesh','logC_l','logC_omega','X_shift','rhoXinf','rhoYinf','uInf','mass'};
assert(ismember(size(history,2),[13,16,20]),'ipm_c:HistorySchema');
data=struct('kind','ipm_c_polar_native_data_v4','schemaVersion',4, ...
    'history',history,'historyColumns',{names(1:size(history,2))}, ...
    'frames',frames,'latestFrame',frames(end).file, ...
    'fieldTau',reshape([frames.tau],[],1),'frameStep',reshape([frames.step],[],1));
for k=1:numel(names)
    if k<=size(history,2),data.(names{k})=history(:,k);else,data.(names{k})=NaN(size(history,1),1);end
end
data.dt=data.H;data.c_l=data.cl;data.c_omega=data.cw;data.c_r=data.cr;
data.c=[data.cl,data.cw,data.cr];data.residual_inf=data.Qinf;
data.C_l=exp(data.logC_l);data.C_omega=exp(data.logC_omega);
denominator=data.cl-data.cw;threshold=32*eps(max(1,max(abs([data.cl,data.cw]),[],2)));
data.C_s=NaN(size(denominator));usable=abs(denominator)>threshold;
data.C_s(usable)=data.cl(usable)./denominator(usable);
data.meta=struct('coordinateSystem','canonical_rescaled_polar_half_disk', ...
    'spatialStorage','immutable_native_frames_with_content_addressed_actual_meshes', ...
    'primaryState','density_minus_origin_with_scalar_origin', ...
    'scalarSampling','each_accepted_step','spatialSampling','frames_catalog', ...
    'definitions',struct('tau','canonical time; one entry per accepted state', ...
    't','physical time; dt/dtau=exp(logC_omega-logC_l)', ...
    'rho_X','d rho / dX on the actual saved mesh', ...
    'rho_Y','d rho / dY on the actual saved mesh', ...
    'rho_tau','complete density RHS at fixed canonical X,Y', ...
    'rho_centered','W=R-rho_origin; authoritative spatial state', ...
    'rho_origin','a=R(0), advanced with the same SSPRK3 stages', ...
    'rho_tau_centered','W_tau; zero at the origin', ...
    'transportOrigin','T(W)(0); permits stable physical rho_t reconstruction', ...
    'Q','d(rho_tau)/dX; rho_xt is a compatibility alias', ...
    'u1_u2','Darcy velocity components in rescaled Cartesian coordinates', ...
    'vx_vy','complete transport velocity including dilation and translation', ...
    'vmag','hypot(u1,u2), the Darcy speed', ...
    'transport_speed','hypot(vx,vy), the complete transport speed', ...
    'C_s','cl/(cl-cw); NaN when denominator is within 32 eps of its rate scale', ...
    'poisson','linear solve backward error; spatial residuals belong to selected.diagnostics.poissonSolveInfo', ...
    'physicalCoordinates','x=(X-X_shift)/C_l, y=Y/C_l', ...
    'physicalFields','rho_phys=rho/C_omega, u_phys=u/C_omega, psi_phys=psi/(C_l*C_omega)'));
if nargin>=3
 for name=fieldnames(previousMeta).'
  key=name{1};
  if startsWith(key,'parent')||strcmp(key,'mixedFrameSchemas')||startsWith(key,'transition')
   data.meta.(key)=previousMeta.(key);
  end
 end
end
end
