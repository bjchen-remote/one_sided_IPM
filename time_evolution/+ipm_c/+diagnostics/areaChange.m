function [requested,maximumChange]=areaChange(current,reference,threshold)
%AREACHANGE Same complete positive-level area trigger as the practical +ipm case.
if nargin<3,threshold=.2;end
assert(isnumeric(current)&&isreal(current)&&isvector(current)&& ...
    all(isfinite(current))&&all(current>=0)&&isnumeric(reference)&&isreal(reference)&& ...
    isvector(reference)&&numel(current)==numel(reference)&&~isempty(reference)&& ...
    all(isfinite(reference))&&all(reference>0), ...
    'ipm_c:LevelSetAreaReference','Areas must be finite; accepted references must be positive and match the levels.');
assert(isnumeric(threshold)&&isreal(threshold)&&isscalar(threshold)&&isfinite(threshold)&& ...
    threshold>0&&threshold<1,'ipm_c:AreaThreshold','Use a relative area trigger in (0,1).');
maximumChange=max(abs(current(:)./reference(:)-1));
requested=maximumChange>=threshold-64*eps(threshold);
end
