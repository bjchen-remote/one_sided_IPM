function [cart,polar,shared] = initialAuthority(config,originalWallOps,grid,shared)
%POLAR_INITIAL_STATE Original analytic Gaussian IVP at physical/canonical t=0.
% [CART,POLAR,SHARED]=POLAR_INITIAL_STATE(CONFIG,OLDWALLOPS,GRID) constructs
% one immutable reference authority. Subsequent spatial levels MUST pass
% that same SHARED as argument four. No reference is computed on a polar
% grid, no late-state density is interpolated, and no velocity/RHS is run.
%
% CONFIG is the actual saved Gaussian configuration, not activeCase. The
% original t0 axes are CONFIG.grid.customX/customY. They are independently
% checked against the original step-zero Gaussian frame. OLDWALLOPS may
% carry late remeshed axes: those axes/Dx are never used. Only its declared
% fixed gauge settings and persisted I0/C0 are checked for compatibility.
% Optional OLDWALLOPS.t0AuthorityFile overrides the audited step-zero frame
% location (for a relocated copy or a synthetic test).
%
% Original high_order Dx, clipped wall I, complete-domain natural-spline P,
% and fixed-window q^2 centroid C define SHARED's I0/P0/C0 once. Direct calls
% to the unchanged ipm.field.initialDensity evaluate every polar node.

if nargin<4,shared=[];end
assert(isstruct(config) && isscalar(config) && ...
    all(isfield(config,{'physics','grid','transport','scaling'})), ...
    'polar:T0Configuration','Pass the actual original resolved configuration.');
assert(isstruct(originalWallOps) && isscalar(originalWallOps) && ...
    isfield(originalWallOps,'rescaling'), ...
    'polar:T0WallSettings','Original gauge settings/reference carrier is required.');
parameters=gaussian_parameters(config.physics);
assert(isstruct(grid) && isscalar(grid) && all(isfield(grid,{'X','Y','nr','ntheta'})) && ...
    isequal(size(grid.X),[grid.nr,grid.ntheta]) && isequal(size(grid.Y),size(grid.X)), ...
    'polar:T0PolarGrid','Supply matching Cartesian coordinates on the polar tensor.');
assert(all(isfinite(grid.X),'all') && all(isfinite(grid.Y),'all') && ...
    all(grid.Y>=0,'all'),'polar:T0PolarGrid','Polar coordinates must be finite and in Y>=0.');
assert(strcmp(config.transport.spatialDiscretization,'high_order') && ...
    strcmp(config.physics.symmetryMode,'half_plane'), ...
    'polar:T0OriginalSpatialMode','This authority reproduces the original high_order half-plane datum.');
fixedNames={'scalingContract','gaugeTransportAssembly','wallIntegralRadius', ...
    'peakPositionRestoringRate','cOmegaGauge','cOmegaGaugeFloor','pointStrainConditionFloor'};
assert(all(isfield(config.scaling,fixedNames)), ...
    'polar:T0GaugeSettings','The original fixed I/P/C configuration is incomplete.');
assert(strcmp(config.scaling.scalingContract,'wall_integral_centroid_practical_v1') && ...
    strcmp(config.scaling.gaugeTransportAssembly,'net_velocity_density_centered_advective'), ...
    'polar:T0GaugeSettings','Keep the original practical I/P/C and advective transport selectors.');
for j=1:numel(fixedNames)
    name=fixedNames{j};
    assert(isfield(originalWallOps.rescaling,name) && ...
        isequaln(originalWallOps.rescaling.(name),config.scaling.(name)), ...
        'polar:T0GaugeSettings','The carrier changed original fixed gauge setting %s.',name);
end

if isempty(shared)
    assert(isfield(config.grid,'customX') && isfield(config.grid,'customY') && ...
        ~isempty(config.grid.customX) && ~isempty(config.grid.customY), ...
        'polar:T0OriginalAxes','Original t0 customX/customY must be supplied explicitly.');
    x=config.grid.customX(:)';y=config.grid.customY(:);
    assert(numel(x)>=7 && numel(y)>=7 && all(isfinite(x)) && all(diff(x)>0) && ...
        all(isfinite(y)) && all(diff(y)>0) && y(1)==0, ...
        'polar:T0OriginalAxes','Original t0 Cartesian axes must be finite and increasing.');
    [frame,authorityFile]=read_authority(originalWallOps);
    assert(isequaln(frame.x(:)',x) && isequaln(frame.y(:),y), ...
        'polar:T0AxisProvenance','CONFIG custom axes differ from the original step-zero frame.');
    [XX,YY]=meshgrid(x,y);analytic=analytic_density(XX,YY);
    assert(isequal(size(frame.rho),size(analytic)) && all(isfinite(frame.rho),'all'), ...
        'polar:T0FrameDensity','The original step-zero density has an incompatible shape.');
    densityDifference=max(abs(analytic-frame.rho),[],'all');
    densityTolerance=256*eps(max(1,max(abs(frame.rho),[],'all')));
    assert(densityDifference<=densityTolerance, ...
        'polar:T0AnalyticProvenance','Supplied Gaussian parameters do not reproduce original t0 rho.');
    Dx=ipm.mesh.fdMatrix(x,1,7);
    wallRho=analytic(1,:);q=wallRho*Dx';
    sourceDifference=NaN;
    if isfield(frame,'w')
        sourceDifference=max(abs(q-frame.w(1,:)));
        assert(sourceDifference<=256*eps(max(1,max(abs(q)))), ...
            'polar:T0DerivativeProvenance','Rebuilt original wall Dx differs from the t0 source.');
    end
    settings=config.scaling;
    runtimeFields={'pinIndex','pinX','originIndex','strainTarget','trackedPeakAnchor', ...
        'gaugeRateGuess','peakEvaluationTime','referenceWallIntegral', ...
        'referenceWallGradientCentroid','referenceWallPeak'};
    present=runtimeFields(isfield(settings,runtimeFields));
    if ~isempty(present),settings=rmfield(settings,present);end
    settings.enabled=true;
    wallOps=struct('x',x,'Dx',Dx,'rescaling',settings);
    integral=ipm.evolve.wallGradientIntegral(q,wallOps,settings);
    peak=ipm.evolve.globalSplineMaximum(q,wallOps);
    centroid=ipm.evolve.wallGradientCentroid(q,wallOps);
    settings.referenceWallIntegral=integral.value;
    settings.referenceWallGradientCentroid=centroid.value;
    settings.pinX=peak.x;
    [~,settings.pinIndex]=min(abs(x-peak.x));
    [~,settings.originIndex]=min(abs(x));
    assert(x(settings.originIndex)==0,'polar:T0Origin','Original t0 wall must contain the exact origin.');
    wallOps.rescaling=settings;
    check_carried_references(settings,originalWallOps.rescaling);
    scale=struct('logC_l',0,'logC_omega',0,'physicalTime',0,'physicalTimeLow',0, ...
        'X_shift',0,'canonicalTime',0);
    refs=struct('I0',integral.value,'P0',peak.value,'C0',centroid.value, ...
        'peakX0',peak.x,'wallIntegralRadius',settings.wallIntegralRadius);
    guess=[0,0];originalUref=NaN;guessOrigin='zero cold numerical guess, not an evaluated flow';
    if all(isfield(frame,{'transport_u1','u1'}))
        difference=frame.transport_u1(1,:)-frame.u1(1,:);
        guess(1)=(difference(end)-difference(1))/(x(end)-x(1));
        guess(2)=difference(settings.originIndex);
        originalUref=interp1(x,frame.u1(1,:),centroid.value,'linear');
        guessOrigin='original t0 transport_u1 minus u1; root guess only';
    end
    carrierAxisMatches=false;
    if isfield(originalWallOps,'x'),carrierAxisMatches=isequaln(originalWallOps.x(:)',x);end
    evidence=struct('authorityFile',authorityFile,'authorityStep',frame.step, ...
        'authorityTau',frame.tau,'authorityPhysicalTime',frame.t, ...
        'customXMatchesAuthority',true,'customYMatchesAuthority',true, ...
        'carrierAxisMatchesOriginalT0',carrierAxisMatches, ...
        'carrierAxesAndDxUsed',false,'wallNodes',numel(x),'cartesianYNodes',numel(y), ...
        'xBounds',x([1,end]),'minimumWallSpacing',min(diff(x)), ...
        'wallDerivative','ipm.mesh.fdMatrix(original_t0_x,1,7)', ...
        'DxNonzeros',nnz(Dx),'analyticRhoFrameInfinityDifference',densityDifference, ...
        'rebuiltWallSourceFrameInfinityDifference',sourceDifference, ...
        'xSha256',numeric_hash(x),'DxSha256',sparse_hash(Dx), ...
        'referenceDefinition','original t0 fixed Cartesian measurement, shared across all polar levels', ...
        'nativePdeCalls',0,'poissonCalls',0,'lateStateInterpolation',false);
    shared=struct('schemaVersion',1,'kind','immutable_original_Gaussian_t0_IPC_authority', ...
        'parameters',parameters,'originalWallOps',wallOps,'references',refs, ...
        'I0',refs.I0,'P0',refs.P0,'C0',refs.C0, ...
        'wallRho',wallRho,'wallQ',q,'scale',scale,'evidence',evidence, ...
        'initialGaugeGuess',guess,'initialGaugeGuessOrigin',guessOrigin, ...
        'originalT0Uref',originalUref);
else
    assert(isstruct(shared) && isscalar(shared) && isfield(shared,'kind') && ...
        strcmp(shared.kind,'immutable_original_Gaussian_t0_IPC_authority') && ...
        all(isfield(shared,{'parameters','originalWallOps','references','scale','evidence'})), ...
        'polar:T0SharedAuthority','Pass the unchanged authority returned by the first level.');
    assert(isequaln(parameters,shared.parameters), ...
        'polar:T0ChangedInitialCondition','Spatial levels must share exactly the same Gaussian datum.');
    assert(isequaln(config.grid.customX(:)',shared.originalWallOps.x(:)'), ...
        'polar:T0ChangedMeasurementGrid','Spatial levels cannot replace the fixed original wall grid.');
    for j=1:numel(fixedNames)
        name=fixedNames{j};
        assert(isequaln(config.scaling.(name),shared.originalWallOps.rescaling.(name)), ...
            'polar:T0ChangedGauge','Spatial levels cannot change original fixed gauge settings.');
    end
    check_carried_references(shared.originalWallOps.rescaling,originalWallOps.rescaling);
end

rho=analytic_density(grid.X,grid.Y);
assert(all(isfinite(rho),'all'),'polar:T0NonfiniteDensity','Analytic polar t0 density must be finite.');
assert(all(rho(1,:)==rho(1,1)), ...
    'polar:T0SingleOrigin','Every polar origin entry must represent the same analytic scalar.');
z=(grid.X-parameters.gaussianCenterX)/parameters.gaussianWidthX;
analyticSource=parameters.gaussianAmplitude*((1-parameters.gaussianSkewWeight)*exp(-z.^2)+ ...
    (parameters.gaussianSkewWeight/1.25)*exp(-((z-.8)/1.25).^2)).* ...
    exp(-(grid.Y/parameters.gaussianWidthY).^2);
referenceBundle=struct('rescaling',shared.originalWallOps.rescaling, ...
    'datum',struct('I',shared.references.I0,'P',shared.references.P0,'C',shared.references.C0));
guess=shared.initialGaugeGuess;
cart=struct('kind','original_analytic_Gaussian_t0_measurement_authority', ...
    'originalWallOps',shared.originalWallOps,'originalReferences',referenceBundle, ...
    'scale',shared.scale,'wallRho',shared.wallRho,'wallQ',shared.wallQ, ...
    'flow',struct('c_l',guess(1),'c_r',guess(2),'guessOnly',true,'physicalFlowEvaluated',false), ...
    'originalMetadata',struct('step',0,'config',config,'t0Evidence',shared.evidence), ...
    'initialization',struct('directAnalyticInitialCondition',true,'stateAdvanced',false, ...
        'referencesFromPolarGrid',false,'referencesResetPerLevel',false, ...
        'lateStateInterpolation',false,'nativePdeCalls',0,'poissonCalls',0));
polar=struct('kind','direct_original_Gaussian_t0_on_polar_tensor', ...
    'rho',rho,'source',analyticSource,'analyticSource',analyticSource, ...
    'analyticRhoX',analyticSource, ...
    'analyticRhoY',(-2*grid.Y/parameters.gaussianWidthY^2).*rho, ...
    'X',grid.X,'Y',grid.Y,'scale',shared.scale,'originalReferences',referenceBundle, ...
    'initialization',cart.initialization);

    function value=analytic_density(X,Y)
        analyticOps=struct('X',X,'Y',Y,'ny',size(X,1),'nx',size(X,2));
        value=ipm.field.initialDensity(analyticOps,config.physics);
    end
end

function parameters=gaussian_parameters(physics)
names={'gaussianAmplitude','gaussianCenterX','gaussianWidthX','gaussianWidthY','gaussianSkewWeight'};
assert(isstruct(physics) && isfield(physics,'initialCondition') && ...
    strcmp(physics.initialCondition,'localized_gaussian_primitive') && all(isfield(physics,names)), ...
    'polar:T0GaussianConfiguration','The actual localized_gaussian_primitive parameters are required.');
parameters=struct('initialCondition','localized_gaussian_primitive');
for j=1:numel(names)
    name=names{j};value=physics.(name);
    validateattributes(value,{'numeric'},{'real','finite','scalar'});parameters.(name)=value;
end
assert(parameters.gaussianAmplitude>0 && parameters.gaussianWidthX>0 && ...
    parameters.gaussianWidthY>0 && parameters.gaussianSkewWeight>=0 && ...
    parameters.gaussianSkewWeight<=1,'polar:T0GaussianConfiguration','Invalid Gaussian datum parameters.');
end

function [frame,path]=read_authority(carrier)
% +gauge -> +ipm_c -> time_evolution -> project root (same depth as the retained source).
projectRoot=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
path=fullfile(projectRoot,'runs','local_validation_20261013','gaussian26_fresh_warm_01', ...
    'data_frames','frame_step000000000000_tau0000000000000000.mat');
if isfield(carrier,'t0AuthorityFile'),path=char(carrier.t0AuthorityFile);end
assert(isfile(path),'polar:T0AuthorityMissing','The original step-zero Gaussian frame is required.');
loaded=load(path,'frame');
assert(isfield(loaded,'frame'),'polar:T0AuthorityFrame','The authority file must contain frame.');
frame=loaded.frame;
required={'x','y','rho','step','tau','t','Cx','Cy','Comega','Xshift'};
assert(isstruct(frame) && isscalar(frame) && all(isfield(frame,required)), ...
    'polar:T0AuthorityFrame','The authority must be a complete original t0 frame.');
assert(isequal([frame.step,frame.tau,frame.t,frame.Xshift],[0,0,0,0]) && ...
    isequal([frame.Cx,frame.Cy,frame.Comega],[1,1,1]), ...
    'polar:T0AuthorityClock','The authority must have exact zero clocks/shift and identity scales.');
end

function check_carried_references(actual,carrier)
for name={'referenceWallIntegral','referenceWallGradientCentroid'}
    key=name{1};
    if isfield(carrier,key)
        expected=carrier.(key);value=actual.(key);
        assert(isnumeric(expected) && isscalar(expected) && isfinite(expected) && ...
            abs(value-expected)<=64*eps(max([1,abs(expected),abs(value)])), ...
            'polar:T0ReferenceMismatch','The original analytic t0 reference differs from persisted %s.',key);
    end
end
end

function value=numeric_hash(values)
% A reproducibility aid, not a substitute for the stored exact x/Dx values.
try
    digest=java.security.MessageDigest.getInstance('SHA-256');
    digest.update(typecast(double(values(:)),'uint8'));
    value=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
catch
    value='unavailable; exact numeric operators retained in shared.originalWallOps';
end
end

function value=sparse_hash(matrix)
[i,j,v]=find(matrix);value=numeric_hash([size(matrix),nnz(matrix),i',j',v']);
end
