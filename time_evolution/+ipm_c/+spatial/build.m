function ops=build(cfg,cart,g)
%BUILD Polar operators for W=R-a with the fixed original wall authority.
% Density origin a and the compensated physical clock use the shared SSPRK3
% state contract; neither changes the I/P/C definitions or spatial system.
if nargin<3,g=ipm_c.mesh.build(cfg.grid);end
assert(isstruct(cfg)&&isfield(cfg,'scaling')&&isfield(cfg,'rhsOptions')&& ...
    isstruct(cart)&&isfield(cart,'originalWallOps'), 'ipm_c:SpatialBuild', ...
    'Supply the numerical configuration and original wall authority.');
r=cart.originalWallOps.rescaling;names=fieldnames(cfg.scaling);
for k=1:numel(names)
    name=names{k};
    if startsWith(name,'reference')&&isfield(r,name)
        assert(isequaln(r.(name),cfg.scaling.(name)),'ipm_c:SpatialReferences', ...
            'The polar backend cannot replace the original persisted gauge references.');
    end
    r.(name)=cfg.scaling.(name);
end
r.enabled=true;r.lengthGauge='wall_gradient_integral';
if ~isfield(r,'pinX'),r.pinX=0;end
if ~isfield(r,'cOmegaGauge'),r.cOmegaGauge='wall_omega_global_spline_maximum';end
assert(strcmp(r.scalingContract,'wall_integral_centroid_practical_v1')&& ...
    strcmp(r.gaugeTransportAssembly,'net_velocity_density_centered_advective'), ...
    'ipm_c:SpatialGaugeContract','The polar adapter retains the original practical advective I/P/C contract.');
wr=[g.r(2)-g.r(1);g.r(3:end)-g.r(1:end-2);g.r(end)-g.r(end-1)]/2;
t=g.theta(:)';wt=[t(2)-t(1),t(3:end)-t(1:end-2),t(end)-t(end-1)]/2;
ops=struct('spatialCoordinateSystem','polar_half_disk','polarGrid',g,'cart',cart,'polarCfg',cfg, ...
    'dynamicScaleGeometry','isotropic','spatialDiscretization','high_order', ...
    'transportScheme','weno5_fd','transportBoundaryMode','open','wallTransportMode','advective_upwind', ...
    'symmetryMode','half_plane','remeshCount',0,'rescaling',r, ...
    'nr',g.nr,'ntheta',g.ntheta,'ny',g.nr,'nx',g.ntheta, ...
    'r',g.r,'theta',g.theta,'X',g.X,'Y',g.Y, ...
    'integrationWeights',(g.r.*wr)*wt,'radialIntegrationWeights',g.r.*wr, ...
    'angularIntegrationWeights',wt,'independentDofCount',1+(g.nr-1)*g.ntheta);
ops.spatialGeometryKey=struct('kind','polar_half_disk_centered_density_local_difference_v2', ...
    'r',g.r,'theta',g.theta,'Dr',g.Dr,'Drr',g.Drr,'originFit',g.originFit, ...
    'radialMetric',g.radialMetric,'signedWallMetric',g.signedWallMetric);
if isfield(cfg,'transport')
    names=fieldnames(cfg.transport);
    for k=1:numel(names),ops.(names{k})=cfg.transport.(names{k});end
end
ops.spatialOperators=struct('evaluate',@ipm_c.spatial.evaluate, ...
    'derivativeX',@(field)derivativeX(field,g,cfg.rhsOptions));
end

function value=derivativeX(field,g,options)
% Cartesian X derivative represented on the native polar tensor.
d=ipm_c.field.derivatives(field,g,options);value=d.rx;
end
