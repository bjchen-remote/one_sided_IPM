function [r,info]=firstSpacingFloor(r,minimumSpacing)
%FIRSTSPACINGFLOOR Smooth odd radial projection retaining origin and radius.
% When needed, f(r)=r+delta*tanh(r/a)*(1-(r/R)^2), with a the input
% first spacing. Its odd extension is smooth and f'(r)>=1-2*delta/R>0.
% This changes CDF quantiles; their original audit must remain separate.
assert(isnumeric(r)&&isreal(r)&&isvector(r)&&numel(r)>=3&& ...
    all(isfinite(r))&&r(1)==0&&all(diff(r(:))>0), ...
    'ipm_c:AreaRemeshFirstSpacing','Supply a finite increasing radial axis starting at zero.');
assert(isnumeric(minimumSpacing)&&isreal(minimumSpacing)&&isscalar(minimumSpacing)&& ...
    isfinite(minimumSpacing)&&minimumSpacing>=0, ...
    'ipm_c:AreaRemeshFirstSpacing','The first-spacing floor must be finite and nonnegative.');
r=r(:);a=r(2);R=r(end);
info=struct('kind','smooth_odd_first_spacing_floor_v1','applied',false, ...
    'originalFirstSpacing',a,'minimumFirstSpacing',minimumSpacing, ...
    'targetFirstSpacing',max(a,minimumSpacing),'projectedFirstSpacing',a, ...
    'radius',R,'projectionScale',a,'projectionAmplitude',0, ...
    'minimumDerivativeBound',1,'strictlyIncreasing',true, ...
    'smoothOddExtension',true,'originAndRadiusRetained',true, ...
    'exactCdfQuantilesClaimed',false, ...
    'projectionDefinition','r+delta*tanh(r/a)*(1-(r/R)^2)');
if minimumSpacing<=a,return;end
assert(minimumSpacing<R,'ipm_c:AreaRemeshFirstSpacing', ...
    'The first-spacing floor must lie inside the retained physical radius.');
denominator=tanh(1)*(1-(a/R)^2);
delta=(minimumSpacing-a)/denominator;
% A small upward roundoff margin applies to the smooth map coefficient,
% rather than modifying an individual radial node after the projection.
delta=delta+4*eps(delta);
assert(isfinite(delta)&&delta>0&&delta<R/2, ...
    'ipm_c:AreaRemeshFirstSpacing','The requested projection must retain a positive derivative bound.');
r=r+delta*tanh(r/a).*(1-(r/R).^2);
r([1,end])=[0,R];
assert(all(isfinite(r))&&all(diff(r)>0)&&r(2)>=minimumSpacing, ...
    'ipm_c:AreaRemeshFirstSpacing','The smooth projection must be increasing and satisfy the first-spacing floor.');
info.applied=true;info.projectedFirstSpacing=r(2);info.projectionAmplitude=delta;
info.minimumDerivativeBound=1-2*delta/R;
end
