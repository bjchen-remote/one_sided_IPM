function report=test_mainline_runtime(outputDir)
%TEST_MAINLINE_RUNTIME Real preset RHS, direct steps, storage and recovery.
root=fileparts(fileparts(mfilename('fullpath')));addpath(fullfile(root,'src'));
if nargin<1,outputDir=fullfile(root,'result','mainline_runtime');end
if ~isfolder(outputDir),mkdir(outputDir);end
report=struct('passed',false,'presets',struct([]),'source',ipm_cr.io.identity('source'));
for preset={'coarse','medium'}
    options=struct('geometry',struct('preset',preset{1}));timer=tic;
    [s,c]=ipm_cr.init(options);initialization=toc(timer);
    assert(strcmp(c.opts.poissonBackend,'fem')&&strcmp(c.opts.transport.reconstruction,'linear5')&& ...
        c.opts.remesh.enabled,'ipm_cr:MainlineDefault');
    poisson_gate(s.rhs.poisson);
    costs=zeros(1,3);
    for k=1:3,timer=tic;s.rhs=ipm_cr.rhs(s,c);costs(k)=toc(timer);end
    expectedDt=min([c.opts.maxDt,.95*c.opts.cfl/s.rhs.rate,.001-s.scale.canonicalTime]);
    [s,step]=ipm_cr.step(s,c,.001);poisson_gate(s.rhs.poisson);
    assert(s.scale.canonicalTime==.001&&step.realizedMaximumStageCfl<=c.opts.cfl&& ...
        step.dt==expectedDt&&step.cflStepFormulaApplied&& ...
        isequal(step.stageCfl,step.dt*step.stageRates)&& ...
        all(isfinite(s.rhs.F.core),'all')&&all(isfinite(s.rhs.F.polar),'all'), ...
        'ipm_cr:MainlineShortStep');
    if strcmp(preset{1},'coarse')
        % A maxDt-sized direct step leaves a genuine floating-point
        % remainder. A second direct step integrates that remainder.
        edgeMaxDt=min(1e-5,.1*c.opts.cfl/max(s.rhs.rate,realmin));
        target=s.scale.canonicalTime+edgeMaxDt+eps(s.scale.canonicalTime+edgeMaxDt);
        remainder=target-s.scale.canonicalTime;
        assert(remainder>edgeMaxDt&& ...
            remainder-edgeMaxDt<=4*eps(target)&&remainder<=edgeMaxDt*(1+1e-10), ...
            'ipm_cr:MainlineRoundedEndpointFixture', ...
            'Expected a positive roundoff remainder: start %.17g, target %.17g, maxDt %.17g, remainder %.17g.', ...
            s.scale.canonicalTime,target,edgeMaxDt,remainder);
        [edge,edgeInfo]=ipm_cr.step(s,c,target,struct('maxDt',edgeMaxDt));
        left=target-edge.scale.canonicalTime;
        assert(edgeInfo.dt==edgeMaxDt&&left>0&&left<=4*eps(target)&& ...
            edgeInfo.realizedMaximumStageCfl<=c.opts.cfl,'ipm_cr:MainlineRoundedEndpointFirst');
        [endpoint,finalInfo]=ipm_cr.step(edge,c,target,struct('maxDt',edgeMaxDt));
        poisson_gate(endpoint.rhs.poisson);
        assert(endpoint.scale.canonicalTime==target&&finalInfo.dt==left&& ...
            edgeInfo.physicalClockIncrement>0&&finalInfo.physicalClockIncrement>0&& ...
            finalInfo.realizedMaximumStageCfl<=c.opts.cfl&& ...
            finalInfo.physicalClockUpdate.wordCount==4, ...
            'ipm_cr:MainlineRoundedEndpoint','Two direct intervals must integrate the actual remainder.');
        report.roundedEndpoint=struct('startTau',s.scale.canonicalTime,'target',target, ...
            'nominalMaxDt',edgeMaxDt,'remainder',remainder, ...
            'firstInformation',edgeInfo,'finalInformation',finalInfo,'finalScale',endpoint.scale);
        clear edge endpoint
    end
    row=struct('preset',preset{1},'fullNodes',numel(s.W.core)+numel(s.W.polar), ...
        'transport',c.opts.transport, ...
        'initializationSeconds',initialization,'warmRhsSeconds',costs, ...
        'step',step,'poisson',s.rhs.poisson,'stats',c.stats());
    if isempty(report.presets),report.presets=row;else,report.presets(end+1)=row;end %#ok<AGROW>
    clear s c
end
case0=ipm_cr.config('case');case0.method.geometry=struct('preset','coarse');
case0.method.remesh=struct('enabled',true);
case0.run.outputDir=fullfile(outputDir,'coarse_run');case0.run.tauEnd=.002;
case0.run.wallSeconds=120;case0.run.verbose=false;
[a,s,c]=ipm_cr.run(case0);
assert(strcmp(a.status,'target_reached')&&s.scale.canonicalTime==.002);
[cp,~]=ipm_cr.io.checkpoint('load',case0.run.outputDir);
initialPointer=jsondecode(fileread(fullfile(case0.run.outputDir,'initial.json')));
initialFile=fullfile(case0.run.outputDir,initialPointer.path);initial=load(initialFile,'checkpoint');
assert(initial.checkpoint.state.scale.canonicalTime==0&&initialPointer.tau==0&& ...
    strcmp(ipm_cr.io.sha(initialFile),initialPointer.sha256),'ipm_cr:MainlineRetainedStart');
assert(isfield(cp.state,'remesh')&&isequaln(cp.state.scale,s.scale)&& ...
    isequaln(cp.geometry.geometryKey,c.mesh.geometryKey),'ipm_cr:MainlineStoredGeometry');
assert(isempty(cp.remeshHistory)&&cp.state.remesh.remeshCount==0&& ...
    ~isempty(cp.state.remesh.referenceShape)&& ...
    isequaln(cp.geometry.geometryKey,initial.checkpoint.geometry.geometryKey), ...
    'ipm_cr:MainlineInitialCalibration', ...
    'The first shape observation must calibrate without interpolating or changing geometry.');
triggerReference=cp.state.remesh.referenceShape;lastCheckTau=cp.state.remesh.lastCheckTau;
lastShape=cp.state.remesh.lastShape;nextCheckTau=cp.state.remesh.nextCheckTau;
case0.run.tauEnd=.003;[b,s,c]=ipm_cr.run(case0);
assert(b.resumed&&strcmp(b.status,'target_reached')&&s.scale.canonicalTime==.003&& ...
    b.resumeRefreshCenteredFInfinity<1e-10&&isfield(s,'remesh'),'ipm_cr:MainlineColdResume');
assert(isequaln(s.remesh.referenceShape,triggerReference)&& ...
    s.remesh.lastCheckTau==lastCheckTau&&isequaln(s.remesh.lastShape,lastShape)&& ...
    isequaln(s.remesh.nextCheckTau,nextCheckTau)&&s.remesh.remeshCount==0&& ...
    isequaln(c.mesh.geometryKey,initial.checkpoint.geometry.geometryKey), ...
    'ipm_cr:MainlineTriggerColdResume', ...
    'Cold recovery must preserve the calibrated shape, previous observation and next check clock without forcing interpolation.');
report.storage=struct('initial',a,'resumed',b,'controller',s.remesh, ...
    'actualMesh',size(c.mesh.core.X),'firstObservationCalibratedOnly',true, ...
    'coldTriggerReferencePreserved',true,'coldAdaptiveSchedulePreserved',true,'actualRemeshes',0);
[parent,pointer]=ipm_cr.io.checkpoint('load',case0.run.outputDir);
assert(strcmp(ipm_cr.io.sha(initialFile),initialPointer.sha256),'ipm_cr:MainlineRetainedStart');
seedCase=case0;seedCase.run.outputDir=fullfile(outputDir,'explicit_seed');seedCase.run.tauEnd=.004;
seedCase.run.seed=struct('file',fullfile(case0.run.outputDir,pointer.path), ...
    'sha256',pointer.sha256,'tau',.003);
[seedSummary,seedState]=ipm_cr.run(seedCase);
assert(strcmp(seedSummary.status,'target_reached')&&seedState.import.tau==.003&& ...
    ~seedState.import.timeRelabeled&&~seedState.import.sameMethodContinuationClaimed, ...
    'ipm_cr:MainlineSeedProvenance');
relocated=fullfile(outputDir,'relocated_seed.mat');copyfile(seedCase.run.seed.file,relocated);
seedCase.run.seed.file=relocated;seedCase.run.tauEnd=.0045;
[moved,movedState]=ipm_cr.run(seedCase);
assert(moved.resumed&&strcmp(moved.status,'target_reached')&& ...
    movedState.import.tau==.003&&strcmp(movedState.import.sha256,pointer.sha256), ...
    'ipm_cr:MainlineSeedLocation','Seed relocation must preserve content and time identity.');
changed=seedCase;changed.run.seed.sha256=repmat('0',1,64);
expect(@()ipm_cr.run(changed),'ipm_cr:SeedIdentity');
bad=seedCase;bad.run.outputDir=fullfile(outputDir,'bad_seed_tau');bad.run.seed.tau=390;
expect(@()ipm_cr.run(bad),'ipm_cr:Seed');
bad=seedCase;bad.run.outputDir=fullfile(outputDir,'bad_seed_background');
bad.method.background=struct('kind','none');
expect(@()ipm_cr.run(bad),'ipm_cr:SeedBackground');
assert(isempty(parent.remeshHistory),'ipm_cr:MainlineNoSpuriousLineage', ...
    'A calibrated short run must not invent a mesh event or perform scheduled interpolation.');
[again,~]=ipm_cr.run(case0);assert(strcmp(again.status,'target_reached'));
report.seed=seedState.import;report.seedRelocation=moved;
report.noUntriggeredMeshEvents=true;
report.sourcesUnchanged=isequaln(report.source,ipm_cr.io.identity('source'));
assert(report.sourcesUnchanged);report.passed=true;
test_report(outputDir,'mainline_runtime',report);
end

function expect(call,identifier)
try,call();catch problem,assert(strcmp(problem.identifier,identifier),'Unexpected %s',problem.identifier);return;end
error('ipm_cr:MainlineExpectedRejection','Expected %s.',identifier);
end
function poisson_gate(info)
assert(info.solverCompleted&&~info.accuracyAssessed&&info.finiteOutput&& ...
    ~isfield(info,'accepted'),'ipm_cr:MainlinePoissonCompletion');
assert(info.weakBackwardError<1e-10&&info.traceAbsolute<1e-9&& ...
    info.essentialBoundaryAbsolute<1e-9,'ipm_cr:MainlinePoissonAccuracy');
end
