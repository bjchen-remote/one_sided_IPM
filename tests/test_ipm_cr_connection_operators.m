function report=test_ipm_cr_connection_operators(outputDir,options)
%TEST_IPM_CR_CONNECTION_OPERATORS Static overset exchange/derivative diagnostics.
% Three fixed geometries are sampled independently from analytic fields.
% No Poisson solve, gauge solve, time step, remesh or active-value projection
% is performed. Analytic-field errors and observed orders are measurements,
% not assertions of a requested continuum accuracy or convergence order.
%
% A = D_x(S f), B = S(D_x f), where S changes ONLY ghost values and D_x
% is the physical Cartesian x derivative on each complete native grid.
% On ACTIVE nodes A-B isolates the derivative change caused by ghost
% injection, because B_active=(D_x f)_active. On GHOST nodes it compares
% differentiating the synchronized field with transferring the raw native
% derivatives. These are two explicitly distinct diagnostics.
if nargin<2,options=struct();end
root=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'src'));
if nargin<1||isempty(outputDir)
    outputDir=fullfile(root,'results','connection_operators');
end
assert(isstruct(options)&&isscalar(options)&& ...
    all(ismember(fieldnames(options),{'pinSources'})), ...
    'ipm_cr:ConnectionTestOptions','Only the optional pinSources flag is supported.');
pinSources=true;if isfield(options,'pinSources'),pinSources=options.pinSources;end
validateattributes(pinSources,{'logical'},{'scalar'});
assert(ischar(outputDir)||(isstring(outputDir)&&isscalar(outputDir)), ...
    'ipm_cr:ConnectionTestOutput','Use an absolute output directory.');
outputDir=char(outputDir);
assert(java.io.File(outputDir).isAbsolute(),'ipm_cr:ConnectionTestOutput', ...
    'Use an absolute output directory.');
if ~isfolder(outputDir),mkdir(outputDir);end
assert(~isfile(fullfile(outputDir,'connection_operators.json'))&& ...
    ~isfile(fullfile(outputDir,'connection_operators.mat')), ...
    'ipm_cr:ConnectionTestPreserve','Choose a fresh result directory.');
timer=tic;
report=struct('kind','static_overset_exchange_physical_derivative_tests_v1', ...
    'status','initializing','passedStructuralAndPolynomialChecks',false, ...
    'timeAdvanced',0,'poissonCalls',0,'gaugeCalls',0, ...
    'fixedRefinementLevels',true, ...
    'fieldNames',{{'nonradial_gaussian','nonradial_rational','x_independent_wall_layer'}}, ...
    'records',struct([]),'observedOrders',struct([]), ...
    'polynomialTolerancePerRowNorm',1e-10, ...
    'sourceInventory',struct([]),'sourceHashesUnchanged',false, ...
    'analyticAccuracyThresholdApplied',false,'spatialOrderCertified',false, ...
    'continuumAccuracyCertified',false,'trajectoryAccuracyCertified',false, ...
    'offset',1e8,'matlabVersion',version,'computer',computer, ...
    'commutatorDefinition',struct('A','D_x(S f)','B','S(D_x f)', ...
        'activeMeaning','Derivative change due to ghost injection; B_active equals the raw native derivative.', ...
        'ghostMeaning','Derivative of the synchronized complete field versus exchange of raw native derivatives.', ...
        'D_x','Physical Cartesian derivative: Cartesian Dx in core; cos(theta)*Dr-sin(theta)/r*Dtheta in annulus.', ...
        'singleGeometryPerComparison',true), ...
    'centeredRepresentationPrinciple', ...
        ['Maintain rho=a+W with a separate scalar and apply synchronization/differentiation to W. ', ...
         'The offset experiment first forms 1e8+f and deliberately exposes its quantization and ', ...
         'cancellation; subtracting that constant afterwards does not recover lost input bits. ', ...
         'No offset invariance or high-precision accuracy is automatically declared passed.'], ...
    'limitations',{{'This is a static connection component test, not a coupled transport stability test.', ...
        'Small A-B or agreement of the two patches is not sufficient: each path is also compared to an analytic derivative.', ...
        'All analytic errors and three-level orders are raw observations; no Richardson extrapolation is applied.', ...
        'The x-independent exp(-y^2) field diagnoses native coordinate-metric/remote wall underresolution as well as ghost injection. Its raw far-field source alias is not attributed to the interface.', ...
        'Large-constant diagnostics do not represent the separately stored centered production state.'}}, ...
    'elapsedSeconds',0);
if pinSources,report.sourceInventory=source_inventory();end
persist(outputDir,report);
plan=struct('h',{.06,.03,.015},'nr',{257,385,641},'ntheta',{64,128,256});
try
    for j=1:numel(plan)
        levelTimer=tic;level=plan(j);
        g=ipm_cr.mesh.build(struct('coreHalfWidth',1.2,'coreHeight',1.2, ...
            'coreSpacing',level.h,'polarStart',.72,'ghostWidth',3, ...
            'interpolationWidth',7,'grid',struct('nr',level.nr, ...
            'ntheta',level.ntheta,'firstSpacing',level.h,'rmax',1e10)));
        row=struct('h',level.h,'requestedGrid',level, ...
            'geometry',geometry_summary(g),'contract',check_contract(g), ...
            'polynomial',exchange_polynomials(g), ...
            'constant',constant_diagnostics(g), ...
            'fields',struct(),'elapsedSeconds',0);
        bands=derivative_ghost_bands(g);
        for name=report.fieldNames
            key=name{1};[f,q]=analytic_field(key,g);
            synced=ipm_cr.mesh.fill(f,g);
            rawDerivative=physical_dx(f,g);
            A=physical_dx(synced,g);
            B=ipm_cr.mesh.fill(rawDerivative,g);
            commutator=subtract(A,B);
            field=struct('definition',field_definition(key), ...
                'role',field_role(key), ...
                'rawDerivativeError',field_metrics(subtract(rawDerivative,q),g,bands), ...
                'synchronizedGhostValueError',field_metrics(subtract(synced,f),g,bands), ...
                'synchronizedDerivativeError',field_metrics(subtract(A,q),g,bands), ...
                'exchangedRawDerivativeError',field_metrics(subtract(B,q),g,bands), ...
                'commutator',field_metrics(commutator,g,bands), ...
                'offsetDiagnostics',offset_diagnostics(f,q,synced,g,bands,report.offset));
            row.fields.(key)=field;
        end
        row.elapsedSeconds=toc(levelTimer);report.records=append(report.records,row);
        report.elapsedSeconds=toc(timer);persist(outputDir,report);
        fprintf('CR CONNECTION h=%.4g core %dx%d annulus %dx%d: exchange norms %.5g/%.5g %.3fs\n', ...
            level.h,g.core.ny,g.core.nx,g.polar.nr,g.polar.ntheta, ...
            row.polynomial.coreFromPolar.operatorInfinityNorm, ...
            row.polynomial.polarFromCore.operatorInfinityNorm,row.elapsedSeconds);
    end
    report.observedOrders=observed_orders(report.records,report.fieldNames);
    if pinSources
        report.sourceHashesUnchanged=isequaln(report.sourceInventory,source_inventory());
        assert(report.sourceHashesUnchanged,'ipm_cr:ConnectionTestSources', ...
            'A recorded numerical source changed during the connection test.');
    end
    report.status='completed_static_connection_measurements';
    report.passedStructuralAndPolynomialChecks=true;
catch problem
    report.status='failed';report.errorIdentifier=problem.identifier;
    report.errorMessage=getReport(problem,'extended','hyperlinks','off');
    report.elapsedSeconds=toc(timer);persist(outputDir,report);rethrow(problem);
end
report.elapsedSeconds=toc(timer);persist(outputDir,report);
end

function info=check_contract(g)
e=g.exchange;c=g.core;p=g.polar;
assert(~any(c.ghost(e.coreDonorIndices))&&~any(p.ghost(e.polarDonorIndices)), ...
    'ipm_cr:ConnectionTestDonors','Exchange donors must be active values only.');
probe=struct('core',sin(c.X)+.3*c.Y,'polar',sin(p.X)+.3*p.Y./(1+p.Y));
normal=ipm_cr.mesh.fill(probe,g);
poisoned=probe;poisoned.core(c.ghost)=1e6;poisoned.polar(p.ghost)=-1e6;
clean=ipm_cr.mesh.fill(poisoned,g);
activePreserved=isequaln(normal.core(c.active),probe.core(c.active))&& ...
    isequaln(normal.polar(p.active),probe.polar(p.active));
poisonIndependent=isequaln(normal,clean);
idempotent=isequaln(normal,ipm_cr.mesh.fill(normal,g));
assert(activePreserved&&poisonIndependent&&idempotent, ...
    'ipm_cr:ConnectionTestSynchronization', ...
    'Synchronization must preserve all active values, ignore ghost donors, and be idempotent.');
info=struct('activeValuesPreservedExactly',activePreserved, ...
    'poisonedGhostsDoNotAffectExchange',poisonIndependent, ...
    'idempotent',idempotent,'allDonorsActive',true, ...
    'sourceFreeOuterRadiusUsedForPoisson',false);
end

function result=exchange_polynomials(g)
c=g.core;p=g.polar;e=g.exchange;
cx=c.X(e.coreGhostIndices);cy=c.Y(e.coreGhostIndices);
result.coreFromPolar=polynomial_map(e.coreFromPolar, ...
    p.r(p.activeRows),p.theta(p.activeColumns),hypot(cx,cy),atan2(cy,cx), ...
    'r','theta');
result.polarFromCore=polynomial_map(e.polarFromCore, ...
    c.y(c.activeRows),c.x(c.activeColumns),p.Y(e.polarGhostIndices), ...
    p.X(e.polarGhostIndices),'y','x');
end

function info=polynomial_map(M,axis0,axis1,query0,query1,name0,name1)
axis0=axis0(:);axis1=axis1(:);query0=query0(:);query1=query1(:);
nq=size(M,1);assert(size(M,2)==numel(axis0)*numel(axis1), ...
    'ipm_cr:ConnectionTestMapShape','A tensor map must match its active donor packing.');
degrees=(0:6)';tensorPowers=[1,1;2,1;1,2;2,2;3,2;2,3;3,3];
axisErrors=zeros(nq,7,2);tensorErrors=zeros(nq,size(tensorPowers,1));
rowMax=zeros(nq,1);rowAbs=zeros(nq,1);rowNeg=zeros(nq,1);
rowT1=zeros(nq,1);negativeCount=0;zeroSpan=[0,0];
for j=1:nq
    [~,columns,w]=find(M(j,:));w=w(:);columns=columns(:);
    i0=mod(columns-1,numel(axis0))+1;i1=floor((columns-1)/numel(axis0))+1;
    [z0,t0,collapsed0]=normalized(axis0(i0),query0(j));
    [z1,t1,collapsed1]=normalized(axis1(i1),query1(j));
    zeroSpan=zeroSpan+[collapsed0,collapsed1];
    rowMax(j)=max(abs(w));rowAbs(j)=sum(abs(w));
    rowNeg(j)=sum(abs(w(w<0)));negativeCount=negativeCount+nnz(w<0);
    rowT1(j)=abs(sum(w)-1);
    for k=1:7
        degree=degrees(k);
        axisErrors(j,k,1)=abs(sum(w.*z0.^degree)-t0^degree);
        axisErrors(j,k,2)=abs(sum(w.*z1.^degree)-t1^degree);
    end
    for k=1:size(tensorPowers,1)
        powers=tensorPowers(k,:);
        tensorErrors(j,k)=abs(sum(w.*z0.^powers(1).*z1.^powers(2))- ...
            t0^powers(1)*t1^powers(2));
    end
end
perRow=max([max(axisErrors(:,:,1),[],2),max(axisErrors(:,:,2),[],2), ...
    max(tensorErrors,[],2),rowT1],[],2);
assert(all(perRow<=1e-10*max(1,rowAbs)), ...
    'ipm_cr:ConnectionTestPolynomial', ...
    'A local polynomial or constant exchange failed its 1e-10 row-norm-scaled tolerance.');
info=struct('rowCount',nq,'donorCount',size(M,2),'nonzeroCount',nnz(M), ...
    'donorAxes',{{name0,name1}},'degrees',degrees', ...
    'normalization','Each query uses the min/max of its actual nonzero donor support, separately on each coordinate, mapped to [0,1]; an exact-hit collapsed axis uses z=0.', ...
    'collapsedSupportAxisCounts',zeroSpan,'T1InfinityResidual',max(rowT1), ...
    'axis0PolynomialInfinityErrors',max(axisErrors(:,:,1),[],1), ...
    'axis1PolynomialInfinityErrors',max(axisErrors(:,:,2),[],1), ...
    'tensorPowers',tensorPowers,'tensorPolynomialInfinityErrors',max(tensorErrors,[],1), ...
    'maximumRowNormScaledPolynomialError',max(perRow./max(1,rowAbs)), ...
    'operatorInfinityNorm',norm(M,inf),'negativeWeightCount',negativeCount, ...
    'rowsWithNegativeWeights',nnz(rowNeg>0),'maximumRowNegativeAbsoluteMass',max(rowNeg), ...
    'maximumAbsoluteWeight',max(rowMax),'rowMaximumAbsoluteWeight',rowMax, ...
    'rowAbsoluteWeightSum',rowAbs,'rowNegativeAbsoluteWeightSum',rowNeg, ...
    'rowT1AbsoluteResidual',rowT1,'negativeWeightsImplyInstabilityClaimed',false);
end

function [z,t,collapsed]=normalized(nodes,query)
lower=min(nodes);span=max(nodes)-lower;collapsed=span==0;
if collapsed
    assert(abs(query-lower)<=64*eps(max(1,abs(lower))), ...
        'ipm_cr:ConnectionTestExactHit','A collapsed donor axis must be an exact query hit.');
    z=zeros(size(nodes));t=0;
else,z=(nodes-lower)/span;t=(query-lower)/span;end
end

function info=constant_diagnostics(g)
value=1.23456789;
f=constant_field(g,value);synced=ipm_cr.mesh.fill(f,g);
error=subtract(synced,f);q=physical_dx(synced,g);
scale=max([1,g.exchange.coreMapInfinityNorm,g.exchange.polarMapInfinityNorm])*abs(value);
maximum=max([abs(error.core(:));abs(error.polar(:))]);
assert(maximum<=1e-10*scale,'ipm_cr:ConnectionTestConstant', ...
    'A moderate constant failed its row-norm-scaled exchange tolerance.');
bands=derivative_ghost_bands(g);
large=constant_field(g,1e8);largeSync=ipm_cr.mesh.fill(large,g);
info=struct('value',value,'synchronizationError',field_metrics(error,g,bands), ...
    'synchronizedPhysicalDx',field_metrics(q,g,bands), ...
    'rawPhysicalDx',field_metrics(physical_dx(f,g),g,bands), ...
    'largeConstant',1e8, ...
    'largeConstantSynchronizationPerturbation',field_metrics(subtract(largeSync,large),g,bands), ...
    'largeConstantSynchronizedPhysicalDx',field_metrics(physical_dx(largeSync,g),g,bands), ...
    'largeConstantThresholdApplied',false);
end

function bands=derivative_ghost_bands(g)
c=g.core;p=g.polar;
bands=struct();
bands.core=c.active&((spones(c.Dx)*double(c.ghost)')'>0);
bands.polar=p.active&((spones(p.Dr)*double(p.ghost)+ ...
    (spones(p.Dt)*double(p.ghost)')')>0);
end

function [f,q]=analytic_field(name,g)
[f.core,q.core]=analytic(name,g.core.X,g.core.Y);
[f.polar,q.polar]=analytic(name,g.polar.X,g.polar.Y);
end

function [value,qx]=analytic(name,x,y)
switch name
    case 'nonradial_gaussian'
        e=exp(-((x-.25)/.75).^2-((y-.55)/.6).^2);
        linear=1+.1*x+.05*y;
        value=linear.*e;
        qx=e.*(.1-2*(x-.25)/.75^2.*linear);
    case 'nonradial_rational'
        numerator=1+.15*x-.07*y;denominator=1+x.^2+.7*y.^2;
        value=numerator./denominator;
        qx=.15./denominator-2*x.*numerator./denominator.^2;
    case 'x_independent_wall_layer'
        value=exp(-y.^2);qx=zeros(size(x));
    otherwise,error('ipm_cr:ConnectionTestField','Unknown analytic field %s.',name);
end
end

function description=field_definition(name)
switch name
    case 'nonradial_gaussian'
        description='f=(1+.1*x+.05*y)*exp(-((x-.25)/.75)^2-((y-.55)/.6)^2); qx evaluated analytically.';
    case 'nonradial_rational'
        description='f=(1+.15*x-.07*y)/(1+x^2+.7*y^2); qx evaluated analytically.';
    case 'x_independent_wall_layer'
        description='f=exp(-y^2), exact physical qx=0 everywhere. Raw annular differentiation may contain coordinate-cancellation/remote wall underresolution error; no zero-error assertion or radius mask is imposed.';
end
end

function description=field_role(name)
if strcmp(name,'x_independent_wall_layer')
    description=['Native source-nullspace and far-wall angular alias diagnostic. ', ...
        'Compare rawDerivativeError against synchronizedDerivativeError and the active commutator ', ...
        'to separate preexisting native-operator error from ghost-injection error. ', ...
        'active covers the complete domain including remote physical wall nodes; ', ...
        'activeNear additionally reports r<=3 without replacing the global metric.'];
else
    description='Nonradial smooth value/physical-derivative exchange diagnostic.';
end
end

function info=offset_diagnostics(f,q,synced,g,bands,offset)
large=struct('core',offset+f.core,'polar',offset+f.polar);
largeSync=ipm_cr.mesh.fill(large,g);
quantized=struct('core',large.core-offset,'polar',large.polar-offset);
postSync=struct('core',largeSync.core-offset,'polar',largeSync.polar-offset);
info=struct('offset',offset,'offsetFirstAddedToInput',true, ...
    'quantizedInputDifferenceFromAnalyticSample',field_metrics(subtract(quantized,f),g,bands), ...
    'synchronizationOffsetCommutativityDefect',field_metrics(subtract(postSync,synced),g,bands), ...
    'rawLargeFieldDerivativeError',field_metrics(subtract(physical_dx(large,g),q),g,bands), ...
    'synchronizedLargeFieldDerivativeError',field_metrics(subtract(physical_dx(largeSync,g),q),g,bands), ...
    'thresholdApplied',false,'centeredRepresentationCertifiedByThisExperiment',false);
end

function q=physical_dx(f,g)
d=ipm_cr.mesh.diff(f,g);
q=struct('core',d.core.x,'polar',d.polar.x);
end

function f=constant_field(g,value)
f=struct('core',value*ones(size(g.core.X)),'polar',value*ones(size(g.polar.X)));
end

function f=subtract(a,b)
f=struct('core',a.core-b.core,'polar',a.polar-b.polar);
end

function info=field_metrics(field,g,bands)
info=struct();
for patch={'core','polar'}
    key=patch{1};p=g.(key);v=field.(key);
    assert(isequal(size(v),size(p.X))&&all(isfinite(v),'all'), ...
        'ipm_cr:ConnectionTestFinite','A diagnostic native field must be finite.');
    info.(key)=struct('active',metric(v,p.active,p.X,p.Y), ...
        'activeNear',metric(v,p.active&hypot(p.X,p.Y)<=3,p.X,p.Y), ...
        'activeRemote',metric(v,p.active&hypot(p.X,p.Y)>3,p.X,p.Y), ...
        'activePhysicalWall',metric(v,p.active&p.Y==0,p.X,p.Y), ...
        'activeRemotePhysicalWall',metric(v,p.active&hypot(p.X,p.Y)>3&p.Y==0,p.X,p.Y), ...
        'ghost',metric(v,p.ghost,p.X,p.Y), ...
        'ghostStencilActiveBand',metric(v,bands.(key),p.X,p.Y));
end
end

function info=metric(value,mask,x,y)
indices=find(mask);info=struct('sampleCount',numel(indices), ...
    'absoluteInfinity',NaN,'absoluteRms',NaN,'maximumLocation',struct());
if isempty(indices),return;end
v=value(indices);[maximum,k]=max(abs(v));j=indices(k);
info.absoluteInfinity=maximum;info.absoluteRms=sqrt(mean(v.^2));
info.maximumLocation=struct('X',x(j),'Y',y(j),'r',hypot(x(j),y(j)), ...
    'physicalWall',y(j)==0,'signedValue',value(j),'nativeLinearIndex',j);
end

function info=geometry_summary(g)
info=struct('coreShape',size(g.core.X),'polarShape',size(g.polar.X), ...
    'coreSpacing',[g.core.dx,g.core.dy],'coreActiveXBounds',g.core.activeXBounds, ...
    'coreActiveYBounds',g.core.activeYBounds, ...
    'annularInnerGhostRadius',g.polar.innerHaloRadius, ...
    'annularInnerActiveRadius',g.polar.innerActiveRadius,'outerRadius',g.polar.r(end), ...
    'activeDofCount',g.activeDofCount,'ghostWidth',g.ghostWidth, ...
    'interpolationWidth',g.interpolationWidth,'gridOptions',g.gridOptions);
end

function rows=observed_orders(records,names)
rows=struct([]);h=[records.h];
quantities={'synchronizedGhostValueError','rawDerivativeError', ...
    'synchronizedDerivativeError','exchangedRawDerivativeError','commutator'};
regions={'active','activeNear','ghost','ghostStencilActiveBand'};
for name=names
    for quantity=quantities
        for patch={'core','polar'}
            for region=regions
                errors=zeros(1,numel(records));
                for j=1:numel(records)
                    item=records(j).fields.(name{1}).(quantity{1}).(patch{1}).(region{1});
                    errors(j)=item.absoluteInfinity;
                end
                orders=nan(1,numel(records)-1);
                for j=1:numel(orders)
                    if errors(j)>0&&errors(j+1)>0&&isfinite(errors(j))&&isfinite(errors(j+1))
                        orders(j)=log(errors(j)/errors(j+1))/log(h(j)/h(j+1));
                    end
                end
                rows=append(rows,struct('field',name{1},'quantity',quantity{1}, ...
                    'patch',patch{1},'region',region{1},'h',h,'absoluteInfinityErrors',errors, ...
                    'pairwiseObservedOrders',orders,'orderCertified',false, ...
                    'samePhysicalQuerySet',false, ...
                    'interpretation','Errors use native region nodes at each level; active/ghost boundaries move with fixed three-layer collars. Orders are raw observations.'));
            end
        end
    end
end
end

function inventory=source_inventory()
paths={mfilename('fullpath'),which('ipm_cr.mesh.build'), ...
    which('ipm_cr.mesh.fill'),which('ipm_cr.mesh.diff'), ...
    which('ipm_cr.mesh.tensorMap'),which('ipm_cr.mesh.localMap'), ...
    which('ipm_cr.mesh.polar'),which('ipm_cr.mesh.radialAxis'), ...
    which('ipm_cr.mesh.fd'),which('ipm_cr.io.sha')};
if ~endsWith(paths{1},'.m'),paths{1}=[paths{1},'.m'];end
inventory=struct([]);
for j=1:numel(paths)
    assert(~isempty(paths{j})&&isfile(paths{j}),'ipm_cr:ConnectionTestSource', ...
        'Every directly recorded numerical source must exist.');
    item=dir(paths{j});
    inventory=append(inventory,struct('path',paths{j},'bytes',item.bytes, ...
        'sha256',ipm_cr.io.sha(paths{j})));
end
end

function persist(folder,report)
temporary=fullfile(folder,'connection_operators.writing.mat');
save(temporary,'report','-v7.3');
[ok,message]=movefile(temporary,fullfile(folder,'connection_operators.mat'),'f');
assert(ok,'ipm_cr:ConnectionTestSave','%s',message);
temporary=fullfile(folder,'connection_operators.json.writing');
fid=fopen(temporary,'w');assert(fid>=0,'ipm_cr:ConnectionTestSave');
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(report,'PrettyPrint',true),'char');clear cleanup
[ok,message]=movefile(temporary,fullfile(folder,'connection_operators.json'),'f');
assert(ok,'ipm_cr:ConnectionTestSave','%s',message);
end

